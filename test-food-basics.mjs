  'Говядина отварная', 'Свинина нежирная', 'Куриная грудка варёная', 'Куриное бедро сырое',
  'Индейка филе сырое', 'Минтай', 'Горбуша', 'Сельдь', 'Тунец',
  'Гречка варёная', 'Рис белый варёный', 'Овсянка на воде', 'Макароны варёные',
  'Картофель варёный', 'Картофель жареный', 'Пюре картофельное',
  'Хлеб белый пшеничный', 'Хлеб ржаной', 'Хлеб цельнозерновой', 'Лаваш армянский', 'Батон нарезной',
  'Банан', 'Яблоко', 'Помидор', 'Огурец', 'Морковь', 'Капуста белокочанная',
  'Грецкий орех', 'Миндаль', 'Семечки подсолнечные',
  'Масло подсолнечное', 'Масло оливковое', 'Масло сливочное 82.5%', 'Сахар', 'Мёд',
  'Борщ', 'Щи из свежей капусты', 'Суп куриный с лапшой',
  'Плов с курицей', 'Котлета куриная', 'Пельмени варёные', 'Сырники', 'Блины', 'Салат Оливье',
  'Сок апельсиновый', 'Компот из сухофруктов', 'Кофе с молоком и сахаром', 'Чай с сахаром',
