  'Молоко 1.5%', 'Молоко 2.5%', 'Молоко 3.2%',
  'Кефир 1%', 'Кефир 2.5%', 'Кефир 3.2%',
  'Творог обезжиренный', 'Творог 2%', 'Творог 5%', 'Творог 9%', 'Творог 18%',
  'Сметана 10%', 'Сметана 15%', 'Сметана 20%',
