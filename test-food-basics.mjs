// test-food-basics.mjs — стартовый справочник базовых продуктов.
//
// Проверяет САМ ФАЙЛ МИГРАЦИИ sql/2026-08-06_food_basics.sql, а не базу: сид
// написан руками, и ошибка в нём (перепутанные сухая/варёная крупа, опечатка в
// разряде, дубль позиции) разъедется по дневникам всех пользователей, а
// заметят её нескоро. Дешевле поймать здесь.
//
// Разбор строкой, а не запросом к Postgres: тест должен идти в обычном
// прогоне npm test, без базы и без сети.
//
// Запуск: node test-food-basics.mjs. В сборку не входит.

import { readFileSync } from 'node:fs'

const SQL_PATH = './sql/2026-08-06_food_basics.sql'
const sql = readFileSync(SQL_PATH, 'utf8')

let pass = 0, fail = 0
function report(label, ok, detail) {
  if (ok) { pass++; console.log(`✓ PASS  ${label}`) }
  else { fail++; console.log(`✗ FAIL  ${label}${detail ? '  — ' + detail : ''}`) }
}
function assertEqual(label, actual, expected) {
  const ok = JSON.stringify(actual) === JSON.stringify(expected)
  report(label, ok, ok ? '' : `ожидалось ${JSON.stringify(expected)}, получено ${JSON.stringify(actual)}`)
}

// Формат строки сида фиксирован ровно затем, чтобы его можно было разобрать:
// ('Название', 'Категория', ккал, б, у, ж),
// Хвост [,;]? обязателен: последняя строка сида заканчивается на «);», и без
// него она молча выпадала бы из разбора — то есть единственная позиция во всём
// файле оставалась бы непроверенной.
const ROW = /^\('([^']+)', '([^']*)', ([\d.]+), ([\d.]+), ([\d.]+), ([\d.]+)\)[,;]?$/
const rows = []
for (const line of sql.split(/\r?\n/)) {
  const m = line.trim().match(ROW)
  if (m) rows.push({ name: m[1], category: m[2], kcal: +m[3], p: +m[4], c: +m[5], f: +m[6], line })
}
const byName = new Map(rows.map(r => [r.name.toLowerCase(), r]))
const find = n => byName.get(n.toLowerCase())

console.log('\n── Файл миграции ──────────────────────────────────────────────────')
report('файл читается и содержит DDL', sql.includes('create table if not exists public.food_basics'))
report('RLS включена', sql.includes('alter table public.food_basics enable row level security'))
report('политик для клиентов нет', !/create policy .*food_basics/i.test(sql))
report('права сняты с anon и authenticated', sql.includes('revoke all on table public.food_basics from anon, authenticated'))
report('права выданы только service_role', sql.includes('grant all on table public.food_basics to service_role'))
// Повторный прогон миграции не должен плодить дубли.
report('сид идемпотентен (truncate перед вставкой)', sql.includes('truncate table public.food_basics restart identity'))
report('INSERT завершён точкой с запятой', /\)\;\s*$/.test(sql.trim()))
// Апостроф в названии разорвал бы SQL-строку — заодно это ломает и разбор выше.
report('в названиях нет апострофов', !rows.some(r => r.name.includes("'")))

console.log('\n── Объём и уникальность ───────────────────────────────────────────')
report(`позиций не меньше 400 (сейчас ${rows.length})`, rows.length >= 400, `найдено ${rows.length}`)
{
  const seen = new Map()
  const dupes = []
  for (const r of rows) {
    const k = r.name.toLowerCase()
    if (seen.has(k)) dupes.push(r.name)
    seen.set(k, true)
  }
  assertEqual('дублей названий нет', dupes, [])
}
report('у всех позиций есть категория', rows.every(r => r.category.length > 0))
report('все названия с большой буквы',
  rows.every(r => r.name[0] === r.name[0].toUpperCase()),
  rows.filter(r => r.name[0] !== r.name[0].toUpperCase()).map(r => r.name).join(', '))

console.log('\n── Правдоподобие значений ─────────────────────────────────────────')
{
  const bad = rows.filter(r => !(r.kcal >= 10 && r.kcal <= 900))
  assertEqual('ккал у всех в пределах 10–900', bad.map(r => `${r.name}=${r.kcal}`), [])
}
{
  const bad = rows.filter(r => [r.p, r.c, r.f].some(v => v < 0 || v > 100))
  assertEqual('макросы у всех в пределах 0–100 г', bad.map(r => r.name), [])
}
{
  // Сумма Б+У+Ж не может превышать 100 г в 100 г продукта.
  const bad = rows.filter(r => r.p + r.c + r.f > 100.5)
  assertEqual('сумма Б+У+Ж не больше 100 г', bad.map(r => `${r.name}=${(r.p + r.c + r.f).toFixed(1)}`), [])
}
{
  // Калорийность обязана примерно сходиться с макросами: 4/4/9 ккал на грамм.
  // Допуск щедрый (±30% и не меньше 25 ккал) — в справочных таблицах ккал берут
  // из прямых измерений, плюс клетчатка в формулу не входит. Ловим не
  // неточность, а промах в разряде: 60 вместо 600 или наоборот.
  //
  // Алкоголь из проверки исключён, и это не поблажка: его калории дают не
  // белки-жиры-углеводы, а этанол (7 ккал/г), которого в формуле нет вовсе.
  // У сухого вина Б+У+Ж почти нулевые при 68 ккал — данные верные, формула
  // неприменима. Список явный: молча пропускать целую категорию нельзя, иначе
  // под этим предлогом мимо проверки уедет и настоящая ошибка.
  const ALCOHOL = new Set(['Пиво светлое', 'Вино сухое красное', 'Вино сухое белое'])
  const off = []
  for (const r of rows) {
    if (ALCOHOL.has(r.name)) continue
    const calc = r.p * 4 + r.c * 4 + r.f * 9
    if (calc === 0) continue
    const diff = Math.abs(calc - r.kcal)
    if (diff > 25 && diff / Math.max(calc, r.kcal) > 0.3) off.push(`${r.name}: указано ${r.kcal}, из макросов ${calc.toFixed(0)}`)
  }
  assertEqual('ккал сходятся с макросами (допуск 30%, кроме алкоголя)', off, [])
  // И сразу — что исключение не разрослось: три позиции, все из напитков.
  report('исключений из проверки ровно три и все алкогольные',
    ALCOHOL.size === 3 && [...ALCOHOL].every(n => find(n)?.category === 'Напитки'))
}

console.log('\n── Сухое и варёное не перепутаны ──────────────────────────────────')
// Самая опасная ошибка сида: варёная крупа втрое легче сухой, и промах здесь
// означает промах в дневнике втрое.
const range = (label, name, lo, hi) => {
  const r = find(name)
  if (!r) { report(`${label}: позиция «${name}» есть в справочнике`, false, 'не найдена'); return }
  report(`${label}: ${r.kcal} ккал в пределах ${lo}–${hi}`, r.kcal >= lo && r.kcal <= hi, `получено ${r.kcal}`)
}
range('Гречка сухая', 'Гречка ядрица сухая', 300, 340)
range('Гречка варёная', 'Гречка варёная', 85, 115)
range('Рис сухой', 'Рис белый сухой', 330, 370)
range('Рис варёный', 'Рис белый варёный', 105, 135)
range('Овсяные хлопья сухие', 'Овсяные хлопья сухие', 330, 380)
range('Овсянка на воде', 'Овсянка на воде', 70, 110)
range('Макароны сухие', 'Макароны сухие', 330, 370)
range('Макароны варёные', 'Макароны варёные', 100, 140)
range('Куриная грудка сырая', 'Куриная грудка сырая', 100, 130)
range('Куриная грудка варёная', 'Куриная грудка варёная', 135, 170)
range('Картофель варёный', 'Картофель варёный', 70, 100)
range('Картофель жареный', 'Картофель жареный', 170, 220)
range('Чечевица сухая', 'Чечевица сухая', 280, 320)
range('Чечевица варёная', 'Чечевица варёная', 95, 130)

{
  // Общее правило: у каждой пары «X сухая/сухой» и «X варёная/варёный»
  // сухая версия обязана быть заметно калорийнее.
  const pairs = [
    ['Гречка ядрица сухая', 'Гречка варёная'],
    ['Рис белый сухой', 'Рис белый варёный'],
    ['Рис бурый сухой', 'Рис бурый варёный'],
    ['Макароны сухие', 'Макароны варёные'],
    ['Булгур сухой', 'Булгур варёный'],
    ['Киноа сухая', 'Киноа варёная'],
    ['Чечевица сухая', 'Чечевица варёная'],
    ['Нут сухой', 'Нут варёный'],
    ['Горох сухой', 'Горох варёный'],
    ['Фасоль белая сухая', 'Фасоль варёная'],
  ]
  const broken = []
  for (const [dry, wet] of pairs) {
    const d = find(dry), w = find(wet)
    if (!d || !w) { broken.push(`${dry} / ${wet}: позиция отсутствует`); continue }
    if (!(d.kcal > w.kcal * 1.8)) broken.push(`${dry}=${d.kcal} vs ${wet}=${w.kcal}`)
  }
  assertEqual('сухая версия минимум в 1.8 раза калорийнее варёной', broken, [])
}

console.log('\n── Обязательное покрытие корзины ──────────────────────────────────')
