{
  const missing = MUST.filter(n => !find(n))
  assertEqual(`все ${MUST.length} обязательных позиций на месте`, missing, [])
}
{
  // Сыры «основных типов» — требование задачи, проверяем как группу.
  const cheeses = rows.filter(r => r.name.startsWith('Сыр '))
  report(`сыров не меньше 8 (сейчас ${cheeses.length})`, cheeses.length >= 8)
}
{
  const veg = rows.filter(r => r.category === 'Овощи')
  const fruit = rows.filter(r => r.category === 'Фрукты')
  report(`овощей и зелени не меньше 40 (сейчас ${veg.length})`, veg.length >= 40)
  report(`фруктов и ягод не меньше 30 (сейчас ${fruit.length})`, fruit.length >= 30)
}

console.log('\n── Выборочная сверка известных значений ───────────────────────────')
// Точечно, по позициям, которые знает наизусть любой, кто вёл дневник.
const exact = (name, kcal, p, c, f) => {
  const r = find(name)
  if (!r) { report(`${name}: есть в справочнике`, false, 'не найдена'); return }
  assertEqual(`${name} = ${kcal}/${p}/${c}/${f}`, [r.kcal, r.p, r.c, r.f], [kcal, p, c, f])
}
exact('Молоко 3.2%', 60, 2.9, 4.7, 3.2)
exact('Яйцо куриное', 157, 12.7, 0.7, 11.5)
exact('Гречка ядрица сухая', 308, 12.6, 57.1, 3.3)
exact('Банан', 96, 1.5, 21.8, 0.5)
exact('Сахар', 399, 0, 99.8, 0)
exact('Масло подсолнечное', 899, 0, 0, 99.9)
exact('Творог 5%', 121, 17.2, 1.8, 5)

