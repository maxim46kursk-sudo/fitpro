/**
 * ЗАЧЁТ ПО ПИТАНИЮ — АРИФМЕТИКА ЧЕЛЛЕНДЖА, И ТОЛЬКО ОНА.
 *
 * Ни React, ни сети, ни хранилища: день приходит числами, наружу уходит
 * процент. Ровно тем же устроен план тридцати дней (src/motion/game/challenge.js),
 * и по той же причине — счёт, который считают деньгами, обязан считаться
 * одинаково в приложении, в тестах и в разборе спора, а не «как получится на
 * том экране, где его показали».
 *
 * ЗАЧЕМ ЭТОТ ЗАЧЁТ ВООБЩЕ ЕСТЬ. Любую тренировку можно заесть за один вечер,
 * поэтому челлендж считает две вещи: как человек двигается и как он ест
 * (docs/challenge-rules.md, экраны 7–10). Второе не менее важно первого, и
 * место в челлендже — сумма двух мест.
 *
 * ГЛАВНОЕ ПРО ЗАМЫСЕЛ: ЗДЕСЬ НЕ ШТРАФУЮТ ЗА ЕДУ, ЗДЕСЬ ПЛАТЯТ ЗА ПОПАДАНИЕ В
 * НОРМУ. Недоел — промах ровно такой же, как переел: голодание не добродетель,
 * и шкала обязана говорить об этом прямо. Отсюда модуль по модулю в accuracy.
 */

/**
 * КОРИДОР: промах до 10% от нормы — это сто баллов, а не «почти сто».
 *
 * Дневник ведут руками, по граммам на глаз; требовать попадания ближе десяти
 * процентов значит требовать точности, которой нет у самих данных. Коридор
 * достижим каждый день — и в этом смысл: человек должен видеть, что попасть
 * реально, иначе бросит вести дневник на пятый день.
 */
export const CORRIDOR = 10

/**
 * ЦЕНА ПРОМАХА: каждый процент сверх коридора снимает два балла.
 *
 * Двойка выбрана так, чтобы ноль наступал на промахе в 60% — то есть на
 * «съел вдвое меньше нормы» или «съел в полтора раза больше». Дальше шкала
 * различать перестаёт, и правильно: и то и другое — не «чуть мимо», а другой
 * день.
 */
export const FALLOFF = 2

/**
 * ПОРОГ ДНЯ: НЕ МЕНЬШЕ ТРЁХ ЗАПИСЕЙ И НЕ МЕНЬШЕ ЧЕМ В ДВУХ ПРИЁМАХ.
 *
 * ЗАЧЕМ ПОРОГ ВООБЩЕ. Без него зачёт выигрывает не тот, кто ел по норме, а тот,
 * кто записал одну строку, случайно попавшую в цифры: «торт, 2400 ккал» в норму
 * по калориям попадает — и не должен давать за это сто баллов.
 *
 * ПОЧЕМУ ПРАВИЛО ИЗМЕНИЛОСЬ. Было «записи в трёх РАЗНЫХ приёмах», и оно било по
 * честному случаю: человек записал завтрак из трёх продуктов — кофе, батон,
 * брынза, — и получал за день ноль. Это не подгонка цифр, это нормально
 * заполненный завтрак, и обнулять его не за что.
 *
 * Новый порог держит ту же дверь закрытой: одной строкой не пройти (нужно три),
 * и одним продуктом, размазанным по одному приёму, тоже (нужно два приёма). А
 * честный завтрак из трёх продуктов плюс любой второй приём — проходит.
 *
 * ДВА ЧИСЛА, А НЕ ОДНО, и оба здесь: правило, по которому делят деньги, должно
 * читаться в одном месте целиком.
 */
export const MIN_ENTRIES = 3
export const MIN_MEALS = 2

/** Четыре показателя дня — в одном месте, чтобы порядок не разъезжался. */
export const KEYS = ['kcal', 'p', 'c', 'f']

/**
 * НАБРАЛСЯ ЛИ ДЕНЬ. Отдельной функцией, потому что спрашивают её двое: судья
 * (dayScore) и экраны, которым надо объяснить человеку, чего не хватило.
 * Разъедься они — в комнате писали бы одно, а в зачёт шло другое.
 *
 * `entries` может не приехать (старое сырьё без этого поля): тогда судим по
 * приёмам, как раньше. Молча обнулять людям дни из-за недостающей колонки
 * нельзя — это деньги.
 */
export function enoughRecords(meals, entries) {
  const п = num(meals) ?? 0
  if (entries == null) return п >= MIN_ENTRIES
  return (num(entries) ?? 0) >= MIN_ENTRIES && п >= MIN_MEALS
}

/** Чего не хватает дню до зачёта. Пусто — всё набрано. */
export function whatIsMissing(meals, entries) {
  if (enoughRecords(meals, entries)) return null
  const п = num(meals) ?? 0
  const з = num(entries) ?? 0
  if (entries == null) return { записей: 0, приёмов: Math.max(0, MIN_ENTRIES - п) }
  return {
    записей: Math.max(0, MIN_ENTRIES - з),
    приёмов: Math.max(0, MIN_MEALS - п),
  }
}

const num = (v) => {
  const n = Number(v)
  return Number.isFinite(n) ? n : null
}

/**
 * НАСКОЛЬКО ДЕНЬ ПОПАЛ В НОРМУ ПО ОДНОМУ ПОКАЗАТЕЛЮ, 0..100.
 *
 * НОРМЫ НЕТ — ОТВЕТ null, А НЕ НОЛЬ, и это не мелочь. «Норма не задана» и
 * «промахнулся мимо нормы» — разные вещи: первое означает, что мерить нечем
 * (человек не заполнил данные о себе), второе — что мерили и не попал. Сложи их
 * в одно среднее, и незаполненный профиль превратился бы в честно заработанный
 * ноль, а человек — в проигравшего по причине, которой не понимает.
 *
 * @param {number} fact сколько съедено
 * @param {number} norm дневная норма
 * @returns {number|null} 0..100, либо null — нормы нет
 */
export function accuracy(fact, norm) {
  const n = num(norm)
  if (n == null || n <= 0) return null

  const f = num(fact) ?? 0
  const missPct = (Math.abs(f - n) / n) * 100
  if (missPct <= CORRIDOR) return 100

  const score = 100 - (missPct - CORRIDOR) * FALLOFF
  return score > 0 ? score : 0
}

/**
 * ОЦЕНКА ДНЯ — среднее по тем показателям, у которых норма задана.
 *
 * counted говорит, ПОЧЕМУ день получил свой ноль: не набралось приёмов пищи,
 * не задана ни одна норма — или человек честно промахнулся. В споре о призах
 * это первый вопрос, и отвечать на него «ноль, и всё» нельзя.
 *
 * @param {{kcal?: number, p?: number, c?: number, f?: number}} facts съедено за день
 * @param {{kcal?: number, p?: number, c?: number, f?: number}} norms дневная норма
 * @param {number} meals в скольких приёмах пищи есть записи
 * @param {number} [entries] сколько записей за день всего. Не передали — считаем
 *   по приёмам, как раньше: старые вызовы не должны молча обнулять людям дни.
 * @returns {{score: number, parts: object, counted: boolean}}
 */
export function dayScore(facts, norms, meals, entries) {
  const parts = {}
  for (const key of KEYS) parts[key] = accuracy(facts?.[key], norms?.[key])

  const known = KEYS.map((k) => parts[k]).filter((v) => v != null)
  const мало = enoughRecords(meals, entries) === false

  // День без нормы и день без записей — оба нули, но нули разного рода; какой
  // именно, видно по parts, meals и entries у вызывающего.
  if (мало || !known.length) return { score: 0, parts, counted: false }

  const score = known.reduce((a, b) => a + b, 0) / known.length
  return { score, parts, counted: true }
}

/**
 * ИТОГ ПО ПИТАНИЮ ЗА ПОТОК — средний процент за ВСЕ дни потока.
 *
 * ДЕНЬ, КОТОРОГО НЕТ В МАССИВЕ, — НОЛЬ, А НЕ ПРОПУСК. Считай мы среднее только
 * по заполненным дням, зачёт по питанию выигрывал бы тот, кто вёл дневник три
 * дня из тридцати и все три попал в коридор. Незаполненный дневник обязан
 * стоить дорого — иначе второй зачёт челленджа не значит ничего, а он значит
 * половину места (docs/challenge-rules.md, экран 10).
 *
 * Дни принимаются либо числами (0..100), либо объектами `{score}` — тем, что
 * возвращает dayScore, чтобы результат одного не приходилось разбирать руками
 * перед передачей в другой.
 *
 * @param {Array<number|{score: number}>} days оценки заполненных дней
 * @param {number} totalDays сколько дней в потоке
 * @returns {number} 0..100
 */
export function streamScore(days, totalDays) {
  const total = Math.max(0, Math.round(num(totalDays) ?? 0))
  // Пустой поток — ноль, а не деление на ноль. Экран, показавший NaN вместо
  // процента, читается как поломка приложения, а не как «дней ещё не было».
  if (!total) return 0

  const list = Array.isArray(days) ? days : []
  let sum = 0
  // Дней в массиве может оказаться больше, чем дней в потоке (день переигран,
  // данные приехали дважды) — считаем ровно totalDays, лишнее отбрасываем.
  for (let i = 0; i < Math.min(list.length, total); i += 1) {
    const day = list[i]
    const value = num(typeof day === 'object' && day !== null ? day.score : day) ?? 0
    sum += Math.min(100, Math.max(0, value))
  }
  return sum / total
}
