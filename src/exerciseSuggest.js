// ЕДИНЫЙ ИСТОЧНИК ПОДСКАЗОК ПО НАЗВАНИЯМ УПРАЖНЕНИЙ.
//
// Зачем понадобился. Подсказки в пикере тренера брались только из каталога —
// зашитый EXERCISES плюс правки в catalog_exercises. Название, которое тренер
// ввёл словами («+ Добавить «X»»), не попадало в каталог никуда: оно уезжало в
// workout_sets.exercise обычным текстом и в подсказках не появлялось больше
// никогда. При этом в «Прогрессе по упражнениям» оно было — тот список строится
// из истории тренировок, то есть из другого источника. Тренер видел упражнение
// в одном месте приложения и не находил его в другом.
//
// Здесь эти два источника сведены в один: каталог задаёт КАНОНИЧЕСКОЕ написание,
// история добавляет всё, чего в каталоге нет.
//
// ПОЧЕМУ КАНОНИЧЕСКОЕ НАПИСАНИЕ ВАЖНО. Прошлые подходы ищутся точным равенством
// строки (workout_sets.exercise), поэтому «жим лежа» и «Жим лёжа» для базы —
// разные упражнения, и история второго к первому не подцепится. Подсказка
// обязана подставлять ровно ту строку, которой упражнение записано, иначе тренер
// молча заводит дубль и теряет всю прошлую динамику.
//
// Файл держится чистым (никакого Supabase и React) — его проверяет
// test-exercise-suggest.mjs.

/**
 * Ключ сравнения названий: нижний регистр, ё→е, схлопнутые пробелы.
 *
 * ё=е — не вкусовщина: «жим лёжа» и «жим лежа» пишут оба варианта примерно
 * поровну, и без этой замены половина поиска не находит ничего. Тот же приём
 * уже стоит в src/exerciseMeta.js и src/fuzzyMatch.js.
 */
export function normalizeName(name) {
  return String(name ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * Каталог + названия из истории, без дублей.
 *
 * @param {Array<{n:string,label?:string,m?:string,eq?:string}>} catalog каталог упражнений
 * @param {string[]} historyNames названия, встречавшиеся в записанных тренировках
 * @returns {Array<{n:string,label:string,m:string,eq:string,fromHistory:boolean}>}
 *
 * ПОРЯДОК ИСТОЧНИКОВ НЕ СЛУЧАЕН. Каталог идёт первым, и при совпадении ключей
 * побеждает он: там написание выверено и там же лежит мышечная группа и снаряд.
 * Название из истории добавляется, только если такого ключа ещё нет, — иначе
 * тренер получил бы две строки на одно упражнение и выбирал бы между ними
 * наугад, а выбор «не той» стоил бы потерянной истории.
 */
export function mergeSuggestions(catalog, historyNames) {
  const out = []
  const seen = new Set()

  for (const e of catalog || []) {
    const n = String(e?.n ?? '')
    if (!n) continue
    const key = normalizeName(n)
    if (seen.has(key)) continue
    seen.add(key)
    out.push({ n, label: e.label || n, m: e.m || '', eq: e.eq || '', fromHistory: false })
  }

  // Из истории — по алфавиту: у неё нет своего осмысленного порядка (в базе это
  // порядок появления подходов), а тренеру нужен предсказуемый список.
  const изИстории = [...new Set((historyNames || []).map(n => String(n ?? '').trim()).filter(Boolean))]
    .sort((a, b) => a.localeCompare(b, 'ru'))
  for (const n of изИстории) {
    const key = normalizeName(n)
    if (!key || seen.has(key)) continue
    seen.add(key)
    // Мышечная группа и снаряд у таких названий неизвестны: их вводили словами,
    // и придумывать их эвристикой значило бы показывать тренеру выдумку.
    out.push({ n, label: n, m: '', eq: '', fromHistory: true })
  }

  return out
}

/**
 * Отбор по строке поиска: без учёта регистра, ё=е, ПО ВХОЖДЕНИЮ.
 *
 * Вхождение, а не начало строки, потому что упражнения называют с середины:
 * «жим» ищут и в «Жим лёжа», и в «Жим гантелей сидя», а «блок» — в «Тяга
 * верхнего блока». Поиск только с начала нашёл бы из этих трёх одно.
 *
 * Пустой запрос отдаёт список целиком — пикер сам решает, показывать ли его.
 */
export function filterSuggestions(list, query) {
  const q = normalizeName(query)
  if (!q) return [...(list || [])]
  return (list || []).filter(e =>
    normalizeName(e.label).includes(q) || normalizeName(e.n).includes(q))
}

/**
 * Есть ли уже такое название — по тому же ключу, что и всё остальное.
 *
 * Нужно кнопке «+ Добавить «…»»: предлагать завести «жим лежа», когда в списке
 * есть «Жим лёжа», — это предлагать дубль, у которого не будет истории.
 */
export function findByName(list, name) {
  const key = normalizeName(name)
  if (!key) return null
  return (list || []).find(e => normalizeName(e.n) === key || normalizeName(e.label) === key) || null
}
