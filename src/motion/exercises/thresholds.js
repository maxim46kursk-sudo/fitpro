/**
 * ГРАНИЦЫ ВОЗМОЖНОЙ СТОЙКИ — угол в колене у стоящего человека.
 *
 * Снизу 130°: даже человек, который заметно не дораспрямляет колено, и даже
 * ракурс сверху не уводят стойку ниже. Сверху 185°: колено назад не гнётся, а
 * пара градусов сверх прямой — это шум замера, а не переразгиб.
 *
 * Числа тут не судейские. Они отвечают на один вопрос: «замер вообще про
 * стоящего человека?» — и всё, что за границами, означает сломанный замер, а
 * не необычного человека.
 */
export const STAND_ANGLE_MIN = 130
export const STAND_ANGLE_MAX = 185

/**
 * Пересчёт порогов под конкретного человека и ракурс.
 *
 * НЕВОЗМОЖНАЯ СТОЙКА ОТВЕРГАЕТСЯ, какой бы ни была её причина. Полевой случай
 * 18 августа: на iPhone стойка намерилась как 37.6°, и пороги встали в UP 110 /
 * DOWN 40 — судейство, в котором присед не засчитывается никогда. Человек при
 * этом честно приседает весь день и получает ноль, а на кону деньги челленджа.
 *
 * Отвергнутый замер НИЧЕГО НЕ МЕНЯЕТ: остаются прежние пороги (у первого запуска
 * — заводские). Они могут не подойти ракурсу, но это «хуже считает», а не
 * «не считает вовсе», и человек хотя бы видит зачёты.
 *
 * @param {number} standAngle измеренный угол в колене в стойке
 * @returns {object|null} новые пороги, либо {rejected: true, standAngle} —
 *   отказ, который вызывающий обязан записать в лог (calibration.reject)
 */
export function applyPersonalCalibration(standAngle) {
  if (!current.autoCalibrate || !Number.isFinite(standAngle)) return null

  if (standAngle < STAND_ANGLE_MIN || standAngle > STAND_ANGLE_MAX) {
    return {
      rejected: true,
      standAngle: Math.round(standAngle * 10) / 10,
      min: STAND_ANGLE_MIN,
      max: STAND_ANGLE_MAX,
    }
  }

  const up = clamp(standAngle - current.upMarginDeg, 110, 178)
  // между порогами обязан остаться рабочий зазор
  const down = clamp(standAngle - current.downMarginDeg, 40, up - 20)

  return setThresholds({
    standAngle: Math.round(standAngle * 10) / 10,
    upAngle: Math.round(up),
    downAngle: Math.round(down),
  })
}

function clamp(v, min, max) {
  return v < min ? min : v > max ? max : v
}

/** Между порогами обязан оставаться зазор, иначе гистерезис вырождается. */
const MIN_GAP = 10

function clampPair(values) {
  const next = { ...values }
  if (next.upAngle - next.downAngle < MIN_GAP) {
    next.downAngle = next.upAngle - MIN_GAP
  }
  return next
}

function readStorage() {
  const parsed = readJson(STORAGE_KEY)
  return parsed && typeof parsed === 'object' ? parsed : null
}

function writeStorage(values) {
  // приватный режим / переполнение — молча живём с дефолтами
  writeJson(STORAGE_KEY, values)
}

let current = clampPair({ ...DEFAULT_THRESHOLDS, ...readStorage() })

const subscribers = new Set()

export function getThresholds() {
  return { ...current }
}

export function setThresholds(patch) {
  current = clampPair({ ...current, ...patch })
  writeStorage(current)
  for (const fn of subscribers) fn(getThresholds())
  return getThresholds()
}

export function resetThresholds() {
  return setThresholds({ ...DEFAULT_THRESHOLDS })
}

export function isDefaultThresholds() {
  return Object.keys(DEFAULT_THRESHOLDS).every((k) => current[k] === DEFAULT_THRESHOLDS[k])
}

/** @returns {() => void} отписка */
export function subscribeThresholds(fn) {
  subscribers.add(fn)
  return () => subscribers.delete(fn)
}
