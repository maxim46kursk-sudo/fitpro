/**
 * ВОРОНКА ЛЕНДИНГА ЧЕЛЛЕНДЖА — кто дошёл и где отвалился.
 *
 * ЗАЧЕМ. Пост опубликован, трафик идёт, а лендинг не писал в журнал ничего: ни
 * посещений, ни отвалов. Мы видели только оплаты — то есть последнюю ступень из
 * шести, — и на вопрос «где теряем» отвечать было нечем.
 *
 * КАНАЛ ТОТ ЖЕ. Ни своей отправки, ни своей таблицы: события уходят через
 * `logEvent` в тот же поток, что и весь журнал Motion (debug/logShipper.js), и
 * ложатся в ту же `motion_log`. Разница ровно одна — их пишут и гости, у
 * которых нет ни аккаунта, ни токена; приёмник для таких строк принимает
 * ТОЛЬКО имена `challenge.*` (см. api/set-exercise.js).
 *
 * ЧТО ЕДЕТ В КАЖДОМ СОБЫТИИ:
 *   vid    — анонимный номер посетителя, живёт в localStorage. Это НЕ личность:
 *            случайные шестнадцать знаков, не связанные ни с аккаунтом, ни с
 *            устройством, ни с адресом. Нужен ровно затем, чтобы шесть ступеней
 *            одного человека сложились в одну дорожку, а не в шесть чужих;
 *   гость  — есть аккаунт или нет. По нему видно, где стена регистрации;
 *   откуда — utm_source / utm_medium / ref из адреса, ЗАПОМНЕННЫЕ НА ПЕРВОМ
 *            заходе: человек приходит по метке, а до оплаты доходит через день
 *            и уже без неё. Не запомни мы её сразу — все продажи выглядели бы
 *            «прямыми», и сравнить посты между собой было бы нечем;
 *   устройство — телефон/планшет/компьютер, грубо. Точная модель для воронки
 *            не нужна, а из User-Agent её и не достать.
 *
 * КАЖДАЯ СТУПЕНЬ — ОДИН РАЗ ЗА ВИЗИТ. Иначе «долистал до цены» считал бы
 * прокрутки, а не людей: один человек, качнувший страницу туда-сюда, дал бы
 * десяток «дошедших». Отметки о пройденных ступенях лежат в sessionStorage —
 * они живут ровно столько же, сколько вкладка, то есть ровно визит.
 */

import { logEvent } from './debug/logShipper.js'

const VID_KEY = 'fitpro.vid.v1'
const SRC_KEY = 'fitpro.src.v1'
const ШАГ_KEY = (шаг) => `fitpro.ch.${шаг}`

/** Случайные 16 знаков. crypto есть везде, где есть камера; запасной путь — на всякий. */
function новыйVid() {
  try {
    const a = new Uint8Array(8)
    globalThis.crypto.getRandomValues(a)
    return [...a].map((b) => b.toString(16).padStart(2, '0')).join('')
  } catch {
    return `${Date.now().toString(36)}${Math.floor(Math.random() * 1e6).toString(36)}`
  }
}

/**
 * Номер посетителя. Заводится один раз и живёт, пока человек не почистит
 * браузер. Приватный режим и отключённое хранилище — законный случай: тогда
 * номер живёт один визит, и человек просто посчитается как новый.
 */
export function vid() {
  try {
    const было = localStorage.getItem(VID_KEY)
    if (было) return было
    const свежий = новыйVid()
    localStorage.setItem(VID_KEY, свежий)
    return свежий
  } catch {
    return 'нет-хранилища'
  }
}

/**
 * ОТКУДА ЧЕЛОВЕК ПРИШЁЛ — запоминается на ПЕРВОМ заходе и больше не меняется.
 *
 * Порядок именно такой: метка в адресе главнее, но если её нет, а сохранённая
 * есть — остаётся сохранённая. Перезаписывать её вторым, уже прямым заходом
 * значило бы стирать единственный след того, какой пост привёл человека.
 */
export function источник(search = globalThis.location?.search) {
  let сохранён = null
  try { сохранён = JSON.parse(localStorage.getItem(SRC_KEY) || 'null') } catch { сохранён = null }

  let свежий = null
  try {
    const p = new URLSearchParams(search || '')
    const s = p.get('utm_source') || p.get('ref')
    const m = p.get('utm_medium')
    if (s || m) свежий = { s: (s || '').slice(0, 40) || undefined, m: (m || '').slice(0, 40) || undefined }
  } catch { свежий = null }

  if (свежий) {
    try { localStorage.setItem(SRC_KEY, JSON.stringify(свежий)) } catch { /* приватный режим */ }
    return свежий
  }
  return сохранён || { s: 'прямой' }
}

/** Телефон, планшет или компьютер — грубо и без версий: точнее для воронки не нужно. */
export function устройство(ua = globalThis.navigator?.userAgent) {
  const s = String(ua || '')
  if (/iPad|Tablet/i.test(s)) return 'планшет'
  if (/Mobi|Android|iPhone/i.test(s)) return 'телефон'
  if (!s) return '—'
  return 'компьютер'
}

/** Пройдена ли ступень в этом визите. Хранилище может быть недоступно — тогда без дедупа. */
function ужеБыло(шаг) {
  try {
    if (sessionStorage.getItem(ШАГ_KEY(шаг))) return true
    sessionStorage.setItem(ШАГ_KEY(шаг), '1')
    return false
  } catch {
    return false
  }
}

/**
 * Отметить ступень воронки.
 *
 * @param {string} шаг  'open' | 'scroll' | 'join-click' | 'auth'
 * @param {object} [что] дополнительное поле события (например, гость или нет)
 * @returns {boolean} записали (иначе ступень в этом визите уже была)
 */
export function ступень(шаг, что = {}) {
  try {
    if (ужеБыло(шаг)) return false
    logEvent(`challenge.${шаг}`, {
      vid: vid(),
      ...источник(),
      d: устройство(),
      ...что,
    })
    return true
  } catch {
    // Счётчик сломался — лендинг работает. Молчим: человек пришёл покупать,
    // а не помогать нам считать.
    return false
  }
}

/** Забыть отметки визита — нужно тестам, чтобы каждый шёл по чистому. */
export function забытьВизит() {
  try {
    for (const шаг of ['open', 'scroll', 'join-click', 'auth']) sessionStorage.removeItem(ШАГ_KEY(шаг))
  } catch { /* нет хранилища — нечего и забывать */ }
}
