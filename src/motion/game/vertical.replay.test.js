import { readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import { detectAll, loadRecording, reportSegments } from '../../../tools/punch-replay.mjs'

/**
 * Мах рукой вверх и прыжок — против живых записей.
 *
 * Пороги обоих детекторов сняты с `calibration-raise-jump-20260812` (20.7 fps,
 * 3 сегмента) и обязаны, во-первых, находить там всё, что человек сделал, а
 * во-вторых, НЕ находить ничего на записях, где этих движений не было вовсе:
 * калибровка пяти старых движений, игровой раунд на Android и синтетические
 * образцы. Второе важнее первого — ложное срабатывание в игре отнимает у
 * человека движение, которого он не делал.
 */

const DIR = fileURLToPath(new URL('../../../recordings/', import.meta.url))
const load = (name) => loadRecording(DIR + name)

const RAISE_JUMP = 'calibration-raise-jump-20260812.json'
const ANDROID_ROUND = 'motion-1786474294758.json'
const PUNCH_SAMPLE = 'sample-punches.json'

const eventsOf = (data, options = {}) =>
  detectAll(data.frames, { ...options, segments: data.segments ?? [] })
const countOf = (data, movement, options = {}) =>
  eventsOf(data, options).filter((e) => e.movement === movement).length

describe('запись махов и прыжков', () => {
  const data = load(RAISE_JUMP)
  const rows = reportSegments(data)
  const rowOf = (movement, side = null) =>
    rows.find((r) => r.segment.movement === movement && r.segment.side === side)

  it('в записи три сегмента: мах правой, мах левой, прыжок', () => {
    expect(rows.map((r) => [r.segment.movement, r.segment.side])).toEqual([
      ['raise', 'right'],
      ['raise', 'left'],
      ['jump', null],
    ])
    // движения дошли до детекторов: строки уже не «ждут настройки»
    expect(rows.every((r) => !r.pending)).toBe(true)
  })

  it('махи находятся на обеих сторонах, и сторона не путается', () => {
    for (const side of ['right', 'left']) {
      const row = rowOf('raise', side)
      // просили 5, человек сделал 6 — шестой мах в конце сегмента настоящий
      expect(row.own).toBe(6)
      expect(row.wrongSide).toBe(0)
    }
    // и ни один мах не вылез за пределы своих сегментов
    expect(countOf(data, 'raise')).toBe(12)
  })

  it('прыжков ровно пять — сколько и просили', () => {
    expect(rowOf('jump').own).toBe(5)
    expect(countOf(data, 'jump')).toBe(5)
  })
})

describe('на старых записях новых движений нет вовсе', () => {
  /**
   * Все записи, кроме той, где махи и прыжки действительно делались. Список
   * берётся из папки: новая запись подхватится сама, и если в ней вдруг
   * появятся ложные срабатывания — тест это покажет.
   */
  const old = readdirSync(DIR)
    .filter((name) => name.endsWith('.json'))
    .filter((name) => !/raise|jump/.test(name))

  /**
   * Разобранные и принятые срабатывания: имя записи -> сколько их там честно
   * есть. Список именной, а не общее послабление: каждая строка означает, что
   * кадры посмотрели и поняли, откуда взялось.
   */
  const ALLOWED = {
    // 122.5 с — самый хвост записи выпадов и захлёстов: сегменты кончились, и
    // человек идёт обратно к телефону. Обе стопы там действительно отрываются
    // от пола (подъём 0.25 при пороге 0.10, рывок таза 2.23 при 1.8), а через
    // три кадра поза теряется совсем. Это не ошибка детектора, а движение вне
    // разметки; limits самой записи его уже учитывают (heel/left, чужих 7).
    'calibration-lunge-heel-20260813.json': { махов: 0, прыжков: 1 },
    /**
     * Запись восьми новых движений: прыжки там ЕСТЬ, и это не ошибка.
     *
     * Два из четырёх — внутри сегмента приседа с прыжком (25.4 и 27.4 с): это
     * движение и есть прыжок, детектор обязан его видеть. Ещё два — в сегменте
     * НАКЛОНА ВПЕРЁД (49.5 и 55.7 с), и это тот самый артефакт сложенного
     * корпуса: в наклоне длина корпуса в кадре падает почти до нуля, а с ней
     * взрывается подъём стоп, на неё делённый. В игре их срезает предохранитель
     * READABLE_FOLD (см. moves.js), но detectAll в разборе судит без него —
     * это разбор сырых детекторов, а не раунд.
     */
    'calibration-new9-20260813.json': { махов: 0, прыжков: 4 },
    /**
     * Записи скручивания: махов и прыжков в них нет, но человек тянется рукой к
     * колену, и запястье при этом остаётся НИЖЕ носа — мах не срабатывает ни
     * разу. Строка стоит здесь явно, чтобы ноль был проверенным, а не случайным.
     */
    'calibration-crunch-20260813.json': { махов: 0, прыжков: 0 },
    'calibration-twist-20260814.json': { махов: 0, прыжков: 0 },
  }
  const expectedOf = (name) => ALLOWED[name] ?? { махов: 0, прыжков: 0 }

  it('таких записей несколько — регрессии есть на чём стоять', () => {
    expect(old.length).toBeGreaterThan(2)
  })

  for (const name of old) {
    it(`${name}: ноль махов и ноль прыжков`, () => {
      const data = load(name)
      expect({ махов: countOf(data, 'raise'), прыжков: countOf(data, 'jump') }).toEqual(
        expectedOf(name),
      )
    })
  }
})

/**
 * Разбор, из-за которого порог входа маха стоит именно на 0.55, а не на 0.30,
 * как казалось по одной записи махов.
 *
 * На игровом раунде Android запястье дважды поднималось выше носа само (пики
 * 0.32 и 0.44), причём держалось 599 и 2501 мс — то есть выдержка в 250 мс
 * такие всплески НЕ отсекает, их отсекает именно порог. Настоящие махи дают
 * 0.72–0.83, поэтому порог и стоит в разрыве между двумя множествами, а не на
 * краю одного из них.
 *
 * Выдержка при этом остаётся: на живых записях она ничего не решает (все
 * всплески там либо длинные, либо ниже порога), но она страхует от одиночного
 * кадра с уехавшей точкой, и её работа проверена на синтетике в vertical.test.js.
 */
describe('почему порог маха именно 0.55', () => {
  it('длинные всплески на Android режет порог, а не выдержка', () => {
    const data = load(ANDROID_ROUND)

    // боевая настройка: ни одного маха
    expect(countOf(data, 'raise')).toBe(0)
    // тот же прогон с порогом 0.30 — и всплески проходят, хотя выдержка на месте
    expect(countOf(data, 'raise', { raise: { enterK: 0.3 } })).toBe(2)
    // и без выдержки их ровно столько же: не она их держала
    expect(countOf(data, 'raise', { raise: { enterK: 0.3, holdMs: 0 } })).toBe(2)
  })

  it('на записи ударов рука выше носа не поднимается вовсе', () => {
    const data = load(PUNCH_SAMPLE)

    // даже с нулевым порогом и без выдержки: удар идёт вперёд, а не вверх
    expect(countOf(data, 'raise')).toBe(0)
    expect(countOf(data, 'raise', { raise: { enterK: 0.3, holdMs: 0 } })).toBe(0)
  })

  it('прыжок держится на двух признаках: рывка таза в старых записях хватает', () => {
    // в калибровке пяти движений есть кадры с рывком таза 3.24 корпуса/с —
    // больше, чем у иных настоящих прыжков, — и ни одного прыжка не найдено:
    // стопы там всё время на земле
    const data = load('calibration-full-20260811.json')
    expect(countOf(data, 'jump')).toBe(0)
    expect(countOf(data, 'jump', { jump: { footLiftK: 0 } })).toBeGreaterThan(0)
  })
})
