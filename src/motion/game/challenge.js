/**
 * Сколько дней челленджа проходятся без кода. Пять — это неделя минус
 * разгрузка: достаточно, чтобы человек увидел, как растут его цифры, и слишком
 * мало, чтобы это заменило челлендж.
 */
export const FREE_DAYS = 5

const UNLOCK_KEY = KEYS.challengeUnlocked

/**
 * ДОСТУП, ОТКРЫТЫЙ СТАРЫМ КОДОМ. Читается, но больше не выдаётся.
 *
 * Кода `?start=vk7m2q` больше нет: место в потоке теперь покупается билетом, и
 * общая калитка, расходящаяся по скриншотам, рядом с платным потоком уже не
 * калитка, а дыра. Но ключ в хранилище остался у тех, кому его выдали, и
 * ЗАБИРАТЬ ЕГО НЕЛЬЗЯ: человек получил доступ честно, а объяснить ему пропажу
 * нечем. Поставить этот флаг заново теперь невозможно ничем — он только
 * доживает у прежних владельцев.
 *
 * Хранилище недоступно — считаем, что не открыт: молчаливая раздача челленджа
 * всем, у кого нестандартный браузер, не лечится ничем.
 */
export function isUnlocked() {
  return readRaw(UNLOCK_KEY) === '1'
}

/**
 * Можно ли ТРЕНИРОВАТЬСЯ в этот день. Блокируется именно тренировка, а не
 * переход: человек, дошедший до шестого дня, должен увидеть свои цифры и
 * предложение продолжить, а не тупик на пятом.
 *
 * УЧАСТНИК ПОТОКА С ДАТОЙ — ровно один день, сегодняшний. Ни вчерашний (он
 * закрыт навсегда), ни завтрашний (он под замком), ни один день до старта и
 * после тридцатого. Отладочный `?day=N` тоже упирается сюда: посмотреть чужой
 * день можно, сыграть его — нет.
 *
 * ОСТАЛЬНЫЕ — как было: бесплатные первые дни и старый ключ доступа. Поток без
 * даты старта (сезон её ещё не объявил) тоже идёт по-старому: закрыть человеку
 * всё оплаченное из-за незаполненного поля было бы хуже любой из бед выше.
 *
 * УЧАСТИЕ ПРИХОДИТ ПАРАМЕТРОМ, а не читается отсюда. Этот файл — чистые числа и
 * чистые функции: он одинаково работает в приложении, в тестах и в автопрогоне,
 * и залезь он в сеть за сезоном, ни одно из трёх мест больше не смогло бы
 * посчитать день, не подняв supabase. Кто участник — знает src/challengeSeason.js,
 * и он же передаёт ответ сюда.
 *
 * @param {number} day день челленджа
 * @param {boolean} [member] участник живого потока
 * @param {string|null} [startsOn] дата старта его потока; по умолчанию — та,
 *   что уже известна разделу (setStreamStart)
 * @param {Date} [at] когда спрашиваем; по умолчанию — сейчас
 */
export const dayPlayable = (day, member = false, startsOn = streamStart(), at = new Date()) => {
  if (member === true) {
    const сегодня = streamDay(startsOn, at)
    if (сегодня === null) return true
    return сегодня >= 1 && сегодня <= DAYS && clampDay(day) === сегодня
  }
  return clampDay(day) <= FREE_DAYS || isUnlocked()
}

/** Начать челлендж заново — с первого дня и с чистой историей. */
export function resetProgress() {
  const empty = { day: 1, done: [] }
  write(empty)
  return empty
}

/**
 * День из адреса: `?day=N`. Отладочная лазейка — она открывает любой день, но
 * прогресса НЕ трогает: посмотреть двадцатый день должно быть можно, не сдав
 * девятнадцать предыдущих и не сбив себе счёт.
 *
 * @returns {number|null} null — ключа нет, идём по своему прогрессу
 */
export function forcedDay() {
  try {
    const raw = new URLSearchParams(globalThis.location?.search || '').get('day')
    if (!raw) return null
    const n = Number(raw)
    return Number.isFinite(n) ? clampDay(n) : null
  } catch {
    return null
  }
}
