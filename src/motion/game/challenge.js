/**
 * ТРИДЦАТИДНЕВНЫЙ ЧЕЛЛЕНДЖ — план как ДАННЫЕ.
 *
 * Уровень (новичок / опытный / профи) остаётся базой: он говорит, насколько
 * точно и насколько быстро человек работает. План дня говорит другое — СКОЛЬКО
 * работы сегодня, и масштабирует уровень, а не подменяет его. Одно и то же
 * движение на двадцатый день делается тем же телом и судится теми же порогами,
 * просто дольше и плотнее.
 *
 * Весь план здесь — чистые числа и чистые функции. Ни хранилища, ни React, ни
 * таймеров: день приходит снаружи, а что из него следует, считается на месте и
 * одинаково в приложении, в тестах и в автопрогоне.
 *
 * ПОЧЕМУ ИНТЕНСИВНОСТЬ ЗАДАНА ТАБЛИЦЕЙ, А НЕ ФОРМУЛОЙ. Тридцать дней — это не
 * монотонный подъём: в нём есть недельные разгрузки (дни 7, 14, 21, 28, 29),
 * есть провалы после тяжёлых дней и есть подводка к последнему. Такое расписание
 * пишут руками, глядя на людей, и подгонять его под красивую кривую значит
 * потерять именно то, ради чего оно и составлено.
 */

import { KEYS, readJson, readRaw, writeJson, writeRaw } from '../storage.js'

/**
 * Интенсивность каждого из тридцати дней, 50–100. Пятьдесят — базовый день
 * (все множители в единице своего смысла), сто — предельный.
 */
export const INTENSITY = [
  55, 60, 65, 58, 68, 72, 50,
  70, 75, 80, 68, 82, 85, 55,
  82, 86, 90, 75, 92, 95, 60,
  85, 90, 94, 80, 96, 98, 62,
  75, 100,
]

export const DAYS = INTENSITY.length

/**
 * Разгрузочные дни. В них не только падает интенсивность — из набора уходят два
 * самых ударных движения: присед с прыжком и прыжок. Разгрузка, в которой
 * человек всё равно прыгает, разгрузкой не является.
 */
export const DELOAD = new Set([7, 14, 21, 28, 29])

/**
 * Порядок силовых движений. Тяжёлое ногами идёт раньше прыжкового, между ними
 * вклиниваются движения на другую зону — иначе к пятому кругу ноги отказывают.
 * Каждый день порядок СДВИГАЕТСЯ на один: за неделю каждое движение успевает
 * побывать и первым (на свежих силах), и последним (на усталых).
 */
export const ORDER = [
  'barrier',
  'lunge',
  'jack',
  'sidelunge',
  'jumpsquat',
  'twistknee',
  'pit',
]

/** Чем заменяются ударные движения в разгрузочный день. */
const DELOAD_SWAP = { jumpsquat: 'barrier', pit: 'jack' }

/**
 * Отсчёт перед первым блоком — он же START_COUNTDOWN_MS в session.js. Числа два,
 * а смысл один: импортировать оттуда нельзя, session.js сам берёт отсюда план
 * дня. Что они сходятся, проверяет автопрогон (tools/full-session.test.js): он
 * сверяет плановую длительность дня с собранным расписанием.
 */
const COUNTDOWN_SEC = 10

const clampDay = (day) => {
  const n = Math.round(Number(day))
  if (!Number.isFinite(n)) return 1
  return Math.min(DAYS, Math.max(1, n))
}

/** Множители округляются до сотых: план читают глазами и сверяют с таблицей. */
const round2 = (v) => Math.round(v * 100) / 100

/**
 * Движения дня: сдвиг по номеру дня плюс замена ударных в разгрузку.
 *
 * Восьмой круг — «движение дня», то самое, с которого день начинается. Он
 * появляется только на тяжёлых днях (когда план даёт восемь кругов) и делается
 * дважды: первым на свежих силах и последним на усталых. Это и есть то, что
 * человек в этот день тренирует, а не просто ещё тридцать секунд работы.
 */
export function movementsOf(day) {
  const n = clampDay(day)
  const shift = (n - 1) % ORDER.length
  const swap = (movement) =>
    DELOAD.has(n) ? DELOAD_SWAP[movement] ?? movement : movement

  const week = ORDER.map((_, i) => swap(ORDER[(shift + i) % ORDER.length]))
  const extra = swap(ORDER[shift])
  return { week, extra }
}

/**
 * Параметры дня. Всё считается от одного числа — интенсивности, — и в этом
 * смысл: чтобы поменять день, достаточно поменять одну цифру в таблице, а не
 * шесть согласованных между собой.
 *
 * `k` — доля пути от базового дня к предельному: 0 на пятидесяти, 1 на ста.
 *
 * @param {number} day 1..30
 */
export function dayPlan(day) {
  const n = clampDay(day)
  const intensity = INTENSITY[n - 1]
  const k = (intensity - 50) / 50

  const circles = 7 + Math.round(k)
  const strengthSec = 30 + Math.round(15 * k)
  const fightSec = 90 + Math.round(60 * k)
  const restStrengthSec = 15 - Math.round(7 * k)
  const restFightSec = 25 - Math.round(10 * k)

  const { week, extra } = movementsOf(n)
  // восьмой круг берётся только когда план его и правда даёт
  const movements = circles > week.length ? [...week, extra] : week.slice(0, circles)

  return {
    day: n,
    intensity,
    k,
    deload: DELOAD.has(n),
    circles,
    strengthSec,
    fightSec,
    restStrengthSec,
    restFightSec,
    /**
     * Множители к уровню. Темп инструктора растёт с интенсивностью, а жизнь
     * мишени и пауза между ними — падают: тяжёлый день это и больше работы, и
     * меньше времени на каждую мишень.
     */
    tempoMult: round2(0.9 + 0.25 * k),
    lifeMult: round2(1.15 - 0.3 * k),
    gapMult: round2(1.15 - 0.3 * k),
    movements,
    /** Движение дня — то, что делается дважды на восьмикруговых днях. */
    movementOfDay: extra,
    /**
     * СКОЛЬКО ДЕНЬ ЗАНИМАЕТ ПО ПЛАНУ — отсчёт плюс полные круги, включая отдых
     * после последнего боя. Настоящая сессия короче ровно на этот последний
     * отдых (после неё отдыхать не перед чем, см. buildSession), но план — это
     * договор с человеком, и в нём круг считается целиком.
     */
    totalSec:
      COUNTDOWN_SEC +
      circles * (strengthSec + restStrengthSec + fightSec + restFightSec),
  }
}

/** Весь челлендж разом — для сверки таблицы и для ворот автопрогона. */
export const allDays = () => Array.from({ length: DAYS }, (_, i) => dayPlan(i + 1))

/* --------------------------------------------------- прогресс участника */

const STORAGE_KEY = KEYS.challenge

/**
 * ДЕНЬ РАСТЁТ ТОЛЬКО ПОСЛЕ ПОЛНОСТЬЮ ЗАВЕРШЁННОЙ СЕССИИ. Не после начатой, не
 * после прерванной на пятом круге и не по календарю: на кону деньги челленджа,
 * и «день засчитан» обязано значить ровно одно — человек прошёл его целиком.
 *
 * Даты завершений хранятся рядом. Они не влияют ни на что в игре и нужны
 * человеку: по ним видно, где он пропустил и сколько дней уже позади.
 */
/**
 * Хранимый день доходит до DAYS + 1 — это и есть «челлендж пройден». Прижимать
 * его к тридцати нельзя: тогда сданный последний день неотличим от несданного,
 * и человек до конца жизни ходил бы на тридцатый.
 */
const clampStored = (day) => {
  const n = Math.round(Number(day))
  if (!Number.isFinite(n)) return 1
  return Math.min(DAYS + 1, Math.max(1, n))
}

function read() {
  // приватный режим или мусор в хранилище — челлендж начинается сначала
  const parsed = readJson(STORAGE_KEY)
  if (!parsed || typeof parsed !== 'object') return { day: 1, done: [] }
  return {
    day: clampStored(parsed.day ?? 1),
    done: Array.isArray(parsed.done) ? parsed.done : [],
  }
}

function write(state) {
  // не сохранилось — человек переиграет день, это дешевле упавшей игры
  writeJson(STORAGE_KEY, state)
}

/** Какой день человеку идти сейчас. Челлендж пройден — остаётся тридцатый. */
export const currentDay = () => Math.min(DAYS, read().day)

/** Полный прогресс: день и даты завершений. */
export const progress = () => read()

/** Челлендж пройден: тридцатый день уже сдан. */
export const isChallengeDone = () => read().day > DAYS

/** Сдан ли день — то есть пройден ли он хоть раз целиком. */
export const isDayDone = (day) => read().done.some((row) => row.day === clampDay(day))

/**
 * Отметить день пройденным. Указатель дня НЕ ДВИГАЕТ.
 *
 * Раньше двигал — и это отнимало у человека то, за что он заплатил. Правила
 * дают три попытки на уровень в день; первая же завершённая сессия переводила
 * его на завтра, и оставшиеся попытки сгорали вместе с возможностью улучшить
 * результат. Человек, прошедший день слабо, оказывался наказан за то, что
 * дошёл до конца: брось он сессию на последнем круге, попытки остались бы при
 * нём.
 *
 * Теперь запись факта и переход разведены. Здесь — только факт: день пройден
 * целиком, значит он в `done` и с этой минуты дверь вперёд открыта. Открывает
 * её сам человек, кнопкой (advanceDay).
 *
 * Повторный проход того же дня переписывает дату: в `done` каждый день ровно
 * один раз, и последняя дата — последний честный проход.
 *
 * ЗА СКОЛЬКО ЗАХОДОВ СОБРАН ДЕНЬ — третьим полем, и это не украшение. Сессия
 * идёт двадцать минут, и с появлением продолжения незавершённой её стало можно
 * собрать за два-три подхода. Для судейства призов разница между «прошёл
 * целиком за раз» и «дособирал третьим заходом» существенна, а по одной дате
 * завершения её не восстановить никак.
 *
 * Смысл самой функции при этом прежний: она по-прежнему только отмечает факт и
 * по-прежнему не двигает указатель дня.
 *
 * @param {number} day день челленджа
 * @param {Date} [at] когда собран
 * @param {number} [runs] за сколько заходов
 * @returns {{day: number, done: object[], dayDone: boolean}}
 */
export function completeDay(day, at = new Date(), runs = 1) {
  const state = read()
  const n = clampDay(day)
  const заходов = Math.max(1, Math.round(Number(runs)) || 1)
  const next = {
    day: state.day,
    done: [
      ...state.done.filter((row) => row.day !== n),
      { day: n, at: at.toISOString(), runs: заходов },
    ].sort((a, b) => a.day - b.day),
  }
  write(next)
  return { ...next, dayDone: true }
}

/** За сколько заходов собран день. Ноль — день ещё не сдан. */
export function dayRuns(day) {
  const row = read().done.find((r) => r.day === clampDay(day))
  return row ? Math.max(1, Math.round(Number(row.runs)) || 1) : 0
}

/**
 * ПЕРЕЙТИ К СЛЕДУЮЩЕМУ ДНЮ — по воле человека, а не по факту сессии.
 *
 * Инвариант остался прежним и он единственный, ради которого всё это писалось:
 * ВПЕРЁД ТОЛЬКО ЧЕРЕЗ ПОЛНОСТЬЮ ЗАВЕРШЁННУЮ СЕССИЮ. Не сдан текущий день —
 * кнопка не работает, сколько по ней ни жми, и никакой другой двери вперёд нет.
 *
 * Назад дороги нет тоже, и это сознательно. Перешёл — прошлый день закрыт
 * навсегда: иначе человек, которому не понравился результат, ходил бы по
 * старым дням, добирая очки, и тридцатидневный челлендж превратился бы в
 * тридцать отдельных уровней, которые можно перепроходить до бесконечности.
 * Кнопка поэтому и сделана явной: за необратимое человек должен нажать сам.
 *
 * Тридцатый день плюс переход — челлендж пройден: указатель встаёт на DAYS + 1,
 * и `isChallengeDone` наконец отличает сданный последний день от несданного.
 *
 * @returns {{day: number, done: object[], advanced: boolean}}
 */
export function advanceDay() {
  const state = read()
  const canMove = state.day <= DAYS && state.done.some((row) => row.day === state.day)
  if (!canMove) return { ...state, advanced: false }

  const next = { day: state.day + 1, done: state.done }
  write(next)
  return { ...next, advanced: true }
}

/* ------------------------------------------------- бесплатные пять дней */

/**
 * Сколько дней челленджа проходятся без кода. Пять — это неделя минус
 * разгрузка: достаточно, чтобы человек увидел, как растут его цифры, и слишком
 * мало, чтобы это заменило челлендж.
 */
export const FREE_DAYS = 5

/**
 * Код активации. Тренер выдаёт его оплатившим, человек открывает
 * `?start=<код>` — и доступ остаётся на устройстве навсегда.
 *
 * Несловарный нарочно: код из словаря подбирают с третьей попытки, а этот в
 * адресной строке не угадывается и в поиске не всплывает. Защита при этом
 * честно называется тем, что она есть, — вежливая калитка, а не замок: код
 * общий, лежит в коде страницы и расходится по первому же скриншоту. Настоящая
 * дверь будет на сервере, вместе с аккаунтами; до тех пор задача кода — не
 * пустить случайного, а не остановить решительного.
 */
export const UNLOCK_CODE = 'vk7m2q'

/**
 * Куда писать за доступом. Пустая строка — кнопки нет: мёртвая кнопка «написать
 * тренеру», ведущая никуда, хуже её отсутствия. Ссылку вставим, когда она будет.
 */
export const CONTACT_URL = ''

const UNLOCK_KEY = KEYS.challengeUnlocked

/**
 * Открыт ли челлендж целиком.
 *
 * Хранилище недоступно — считаем, что не открыт: доступ такому человеку вернёт
 * та же ссылка, а вот молчаливая раздача челленджа всем, у кого нестандартный
 * браузер, не лечится ничем.
 */
export function isUnlocked() {
  return readRaw(UNLOCK_KEY) === '1'
}

/**
 * Открыть челлендж. Навсегда и на этом устройстве: человек заплатил один раз,
 * и просить его вводить код каждую неделю значит наказывать за оплату.
 *
 * @param {string} code код из адреса
 * @returns {boolean} открылось ли им
 */
export function unlock(code) {
  if (String(code ?? '').trim().toLowerCase() !== UNLOCK_CODE) return false
  // не сохранилось — челлендж откроется до перезагрузки, ссылка у человека есть
  writeRaw(UNLOCK_KEY, '1')
  return true
}

/**
 * Код из адреса: `?start=<код>`. Зовётся на старте приложения — человек
 * переходит по ссылке от тренера один раз, и дальше открывает игру как обычно.
 */
export function unlockFromUrl() {
  try {
    const raw = new URLSearchParams(globalThis.location?.search || '').get('start')
    return raw ? unlock(raw) : false
  } catch {
    return false
  }
}

/**
 * Можно ли ТРЕНИРОВАТЬСЯ в этот день. Блокируется именно тренировка, а не
 * переход: человек, дошедший до шестого дня, должен увидеть свои цифры и
 * предложение продолжить, а не тупик на пятом.
 */
export const dayPlayable = (day) => clampDay(day) <= FREE_DAYS || isUnlocked()

/** Начать челлендж заново — с первого дня и с чистой историей. */
export function resetProgress() {
  const empty = { day: 1, done: [] }
  write(empty)
  return empty
}

/**
 * День из адреса: `?day=N`. Отладочная лазейка — она открывает любой день, но
 * прогресса НЕ трогает: посмотреть двадцатый день должно быть можно, не сдав
 * девятнадцать предыдущих и не сбив себе счёт.
 *
 * @returns {number|null} null — ключа нет, идём по своему прогрессу
 */
export function forcedDay() {
  try {
    const raw = new URLSearchParams(globalThis.location?.search || '').get('day')
    if (!raw) return null
    const n = Number(raw)
    return Number.isFinite(n) ? clampDay(n) : null
  } catch {
    return null
  }
}
