/** Уровень по умолчанию: с него человек начинает, если ничего не выбрал. */
export const DEFAULT_TIER = TIERS[0].id

/** Шаг шкалы всегда внутри неё: снаружи может прийти что угодно. */
export function clampPace(step) {
  const value = Math.round(Number(step))
  if (!Number.isFinite(value)) return MIN_PACE
  return Math.min(MAX_PACE, Math.max(MIN_PACE, value))
}

/** Темп на шаге шкалы. */
export function paceFor(step) {
  const row = PACE[clampPace(step) - 1]
  return { gapMs: row.gapMs, travelMs: row.travelMs }
}

/**
 * Уровень по идентификатору. Неизвестный id — это не повод падать: в хранилище
 * может лежать имя из старой версии, и человек должен просто сыграть новичка.
 */
export function tierById(id) {
  return TIERS.find((t) => t.id === id) || TIERS[0]
}

/** Цена одного препятствия на уровне — её берёт счётчик очков. */
export function obstaclePointsFor(id) {
  return tierById(id).obstaclePoints
}

/**
 * Настройки раунда для уровня — ровно те поля, что понимает createRound.
 * Начало берётся с левого конца отрезка, конец — с правого; разгон внутри
 * раунда движок считает сам. Остального (позы, пороги, длительность) уровень
 * не касается.
 */
export function configForTier(id) {
  const tier = tierById(id)
  const start = paceFor(tier.from)
  const end = paceFor(tier.to)
  return {
    startGapMs: start.gapMs,
    endGapMs: end.gapMs,
    startTravelMs: start.travelMs,
    endTravelMs: end.travelMs,
    // ловец про темп потока не знает: у него своя тройка — точность, спешка,
    // плотность
    targetRadiusK: tier.targetRadiusK,
    targetLifeMs: tier.targetLifeMs,
    targetGapMs: tier.targetGapMs,
  }
}
