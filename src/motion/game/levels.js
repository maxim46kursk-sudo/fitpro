export const MIN_PACE = 1
export const MAX_PACE = PACE.length

/**
 * Уровни: имя, отрезок шкалы темпа и цена препятствия.
 *
 * Цены вынесены сюда таблицей намеренно — Максим сказал «надо подумать», и
 * крутить их будут не раз. Менять надо здесь и только здесь: и экран выбора, и
 * начисление очков читают эту же строку.
 *
 * Верхние концы срезаны по полевому тесту: на профи вышло 59/76, и почти все
 * промахи пришлись на вторую половину раунда, где темп уходил за десятый шаг.
 * Поэтому опытный теперь кончается на 9, профи на 12, а последний шаг шкалы
 * (2000/1800) остаётся запасом на потом — сам по себе он проверен, но раунд,
 * который к нему разгоняется, оказался быстрее, чем человек успевает.
 */
/**
 * ЧЕМ УРОВНИ ЛОВЦА РАЗЛИЧАЮТСЯ — ТРЕМЯ ЧИСЛАМИ, А НЕ ОДНИМ.
 *
 * Было одно: время жизни мишени. Полевой отзыв после сессии — «одни настройки»:
 * человек не чувствовал разницы между уровнями вовсе, и он прав. Секунда с
 * небольшим разницы во времени жизни на фоне полутора секунд, которые уходят на
 * дорогу до мишени, не читается никак.
 *
 * Теперь их три, и каждое давит своим:
 *
 *   `targetRadiusK` — РАЗМЕР КРУГА в ширинах плеч. Это точность: у новичка
 *     круг в полтора раза шире профийного, и попасть в него можно примерно, а
 *     не точно. Единственное из трёх, что меняет строгость судьи, — и меняет
 *     честно, одинаково для обеих сторон и всех четырёх частей.
 *   `targetLifeMs` — СКОЛЬКО ВИСИТ. Это спешка.
 *   `targetGapMs` — ПАУЗА МЕЖДУ МИШЕНЯМИ. Это плотность: у новичка есть
 *     полсекунды выдохнуть, у профи полторы десятых.
 *
 * Что НЕ меняется: зоны спавна, расстояние «сколько идти» (1.1 ширины плеч от
 * оси и от конечности) и состав мешка. Работа на всех уровнях одна и та же,
 * иначе результаты людей перестали бы быть сравнимыми, — разное только то,
 * насколько точно и насколько быстро её надо сделать.
 */
