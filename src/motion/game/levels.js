/**
 * Три уровня челленджа и общая шкала темпа.
 *
 * Решение Максима: сложность растёт ТОЛЬКО темпом — интервалом между
 * препятствиями и скоростью полёта. Позы, пороги и длительность раунда одни и те
 * же везде. Причина продуктовая: движение либо сделано, либо нет, и «присед
 * посложнее» — это уже другое упражнение, а не другой уровень. Значит и
 * результаты людей сравнимы: судья везде один.
 *
 * Автопрогрессия отменена. Раньше игра сама двигала человека по уровням по доле
 * зачищенных препятствий, а каждый седьмой раунд делала разгрузочным. Теперь
 * уровень выбирает человек, и выбирает заново каждый день: новичок волен пойти
 * в профи — там дороже, но темп сам отсеет.
 *
 * Шкала темпа непрерывная, 1–13, одна на все уровни. Уровень — это ОТРЕЗОК на
 * ней: раунд начинается на его левом конце и разгоняется до правого. Отрезки
 * намеренно перекрываются (1–6, 5–10, 8–13): конец лёгкого уровня совпадает с
 * началом среднего, поэтому переход между уровнями человек чувствует как
 * продолжение, а не как обрыв.
 *
 * Быстрее 2000/1800 не идём — это сегодняшний проверенный предел: на нём раунд
 * прошли 62 препятствия из 65 в поле.
 */

