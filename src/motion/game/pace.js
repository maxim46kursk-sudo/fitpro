/**
 * ТЕМП ЗАМЕРОВ — сколько миллисекунд между двумя соседними позами.
 *
 * ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ МОДУЛЕМ. Судьи движений прощают короткий срыв условия:
 * трекинг моргнул, а движение продолжается, и выдержку сбрасывать не за что.
 * Запас на это записан во времени — 120 мс, — но смысл у него в ЗАМЕРАХ: он
 * должен покрывать один потерянный замер, не больше.
 *
 * На iPhone замеры идут через 43 мс, и 120 мс покрывают почти три — запас
 * работает. На Redmi через 143 мс, и 120 мс не покрывают НИ ОДНОГО: любой
 * дрогнувший замер сбрасывает выдержку целиком. Одно и то же число означает у
 * двух людей разную строгость судьи, а это ровно то, чего быть не должно.
 *
 * Поэтому запас берётся от наблюдаемого темпа: полтора замера, но не меньше
 * прежних 120 мс. На быстрой съёмке остаётся 120 (судейство не меняется ни на
 * волос), на медленной вырастает до 215 и наконец делает то, ради чего заведён.
 *
 * Медиана, а не среднее: один провал в секунду не должен раздувать запас — а
 * именно провалы и случаются, когда телефон уходит думать над кадром.
 */

/** Сколько замеров прощаем. Полтора: один потерянный плюс половина на дрожание. */
export const GRACE_STEPS = 1.5

/** Промежутки длиннее секунды — это не темп съёмки, а провал: в медиану не идут. */
const MAX_GAP_MS = 1000

/** Пока замеров меньше — темп не считаем и живём на базовом запасе. */
const MIN_SAMPLES = 5

/** Скользящее окно: полсекунды на медленной съёмке, пара — на быстрой. */
const WINDOW = 15

export function createPace(baseGraceMs) {
  const gaps = []
  let last = null

  return {
    /** Медиана промежутка между замерами, мс. null — пока не набралось. */
    stepMs: null,
    /** Сколько прощать срыв условия при таком темпе. */
    graceMs: baseGraceMs,

    /** Отметить замер и получить запас, действующий на нём. */
    see(nowMs) {
      if (last != null) {
        const gap = nowMs - last
        if (gap > 0 && gap < MAX_GAP_MS) {
          gaps.push(gap)
          if (gaps.length > WINDOW) gaps.shift()
        }
      }
      last = nowMs

      if (gaps.length >= MIN_SAMPLES) {
        const sorted = [...gaps].sort((a, b) => a - b)
        this.stepMs = sorted[sorted.length >> 1]
        this.graceMs = Math.max(baseGraceMs, Math.round(this.stepMs * GRACE_STEPS))
      }
      return this.graceMs
    },

    reset() {
      gaps.length = 0
      last = null
      this.stepMs = null
      this.graceMs = baseGraceMs
    },
  }
}
