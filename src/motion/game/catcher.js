/**
 * ЛОВЕЦ МИШЕНЕЙ — боевой раунд, в котором судят не движение, а попадание.
 *
 * ЧТО ЭТО ВМЕСТО. Прежний бой требовал от человека УЗНАТЬ движение по летящей
 * фигуре и выдать его с амплитудой, которую увидит детектор: восемнадцать
 * движений, восемнадцать наборов порогов, разминка по два повтора на каждое и
 * промахи, причину которых без лога не назвать. Здесь ничего этого нет. На
 * экране одна мишень и одно слово под ней — ЛАДОНЬ, ЛОКОТЬ, КОЛЕНО, СТОПА.
 * Читать нечего: куда тянуться, показывает сам круг, а чем тянуться — подпись.
 *
 * ДЕТЕКТОРЫ ДВИЖЕНИЙ ЗДЕСЬ НЕ РАБОТАЮТ ВОВСЕ, и это главное решение файла.
 * Зачёт — это факт: названная точка позы оказалась внутри круга. Ни амплитуды,
 * ни выдержки, ни личных планок, ни окон вокруг пролёта. Человек сам выбирает,
 * как достать мишень; игра проверяет только то, что он её достал.
 *
 * СУДЬЯ РАБОТАЕТ В НОРМИРОВАННЫХ КООРДИНАТАХ ТОЧЕК ПОЗЫ, а не в пикселях
 * экрана, и никакого зеркала в нём нет. Зеркало живёт ровно в одном месте — в
 * отрисовке (x экрана = 1 - x точки, см. заголовок targets.js). Заведи зеркало
 * здесь — и оно окажется применено дважды, а мишени встанут не с той стороны.
 * Сторона `left`/`right` везде значит СТОРОНУ ЧЕЛОВЕКА: его левая рука лежит в
 * точках позы справа (x11 - x12 = +0.20 по всем записям), а на зеркальном
 * экране — слева. Одно значение, два вида — и ни одного переворота по дороге.
 *
 * ДВЕ ЕДИНИЦЫ ДЛИНЫ ВМЕСТО ОДНОЙ, и это не придирка. Нормированные координаты
 * анизотропны: x поделён на ширину кадра, y — на высоту, и на портретном кадре
 * 3:4 одна и та же физическая длина по вертикали выходит на треть короче, чем
 * по горизонтали. Меряй расстояние обычным hypot — и мишень под колено окажется
 * «уже задета» стоящей ногой. Пропорции кадра сюда не передаются намеренно
 * (движок про камеру ничего не знает): вертикальная единица берётся из САМОГО
 * ТЕЛА — расстояние от линии плеч до линии таза, делённое на TORSO_K. По семи
 * записям с двух разных телефонов это отношение держится в 1.46–1.54, то есть
 * тело калибрует кадр не хуже, чем это сделал бы сам кадр.
 *
 * ДО КАЖДОЙ МИШЕНИ НАДО ИДТИ — два правила об одном и том же с разных сторон,
 * и оба в ширинах плеч, а не в радиусах зачёта:
 *   от ОСИ ТЕЛА (линия «центр плеч — центр таза») не ближе 1.1;
 *   от самой КОНЕЧНОСТИ, которой ловят, не ближе 1.1 — считая ближайшую из двух
 *     её точек.
 * Первое правило держит мишень в стороне от человека вообще, второе — в стороне
 * от той руки или ноги, которой её будут доставать. Полевой лог показал, что
 * порознь ни одного не хватает: мишень, честно отстоящая от оси, всё равно
 * оказывалась под болтающимся локтем.
 *
 * Мерить в радиусах нельзя, и это выяснилось тем же логом: радиус зачёта на
 * уровнях разный (0.42 у новичка, 0.30 у профи), и правило «столько-то
 * радиусов» означало бы на них разную работу. Работа одна — значит и мера тела.
 *
 * Плюс третье, дешёвое: касание засчитывается по ДВУМ ПОПАДАНИЯМ ИЗ ТРЁХ
 * последних кадров. От одиночного дрогнувшего кадра трекинга это защищает так
 * же, как прежние «два подряд», но не отменяет честное касание, посреди
 * которого трекинг моргнул.
 *
 * Чистая логика: ни React, ни canvas, ни своих таймеров. Время и точки позы
 * приходят снаружи, бросок — сидированный из движка, и весь раунд по одному
 * сиду повторяется кадр в кадр.
 */

