/**
 * Очки раунда. Отдельно от таймлайна: правила начисления будут меняться от
 * механики к механике, а таймлайн — нет.
 *
 * ЦЕНА ОДНА И ТА ЖЕ ЗА ЛЮБОЕ ЗАСЧИТАННОЕ ДЕЙСТВИЕ. Её задаёт уровень (100 у
 * новичка, 150 у опытного, 200 у профи, см. TIERS в levels.js) и передаёт сюда
 * при создании счёта: сам счётчик про уровни ничего не знает и знать не должен.
 * Никаких множителей, надбавок и коэффициентов сверх этого нет.
 *
 * ПОЧЕМУ УБРАЛИ МНОЖИТЕЛЬ ЗА СЕРИЮ. Он был: ×1 -> ×2 -> ×3 за каждые пять
 * попаданий подряд. С ним счёт переставал быть понятным — одно и то же движение
 * стоило то 200, то 600, и человек не мог сказать, почему у него столько очков,
 * не пересчитав всю историю раунда. Прозрачная цена важнее азарта: раунд должен
 * читаться как «сколько движений я сделал», а не как задача на умножение.
 *
 * Серия при этом никуда не делась — она просто больше не про очки: по ней
 * по-прежнему летит конфетти (каждые пять зачётов подряд) и звучит акцент. Это
 * украшение, и на счёт оно не влияет.
 */

export const HIT_POINTS = 100
/** Столько зачётов подряд отмечаются конфетти и звуком. На очки не влияет. */
export const MILESTONE_EVERY = 5

export function createScore({ hitPoints = HIT_POINTS } = {}) {
  // Цена приходит снаружи и может быть какой угодно — от неё зависит весь счёт,
  // поэтому мусор здесь молча превращается в цену по умолчанию.
  const points = Number.isFinite(hitPoints) && hitPoints > 0 ? Math.round(hitPoints) : HIT_POINTS
  let total = 0
  let streak = 0
  let bestStreak = 0
  let hits = 0
  let misses = 0

  function snapshot() {
    return { total, streak, bestStreak, hits, misses, hitPoints: points }
  }

  return {
    hit() {
      hits += 1
      streak += 1
      if (streak > bestStreak) bestStreak = streak
      total += points

      return {
        ...snapshot(),
        points,
        /** Пятый зачёт подряд: повод для конфетти и акцента, но не для очков. */
        milestone: streak % MILESTONE_EVERY === 0,
      }
    },

    miss() {
      misses += 1
      streak = 0
      return { ...snapshot(), points: 0, milestone: false }
    },

    getState: snapshot,
  }
}
