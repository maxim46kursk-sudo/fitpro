/**
 * Таймлайн игрового раунда. Режимов два, и по умолчанию работает первый.
 *
 * ЛОВЕЦ МИШЕНЕЙ (`mode: 'catch'`, он же боевой раунд по умолчанию). На экране
 * одна мишень за раз, под ней слово — ЛАДОНЬ, ЛОКОТЬ, КОЛЕНО, СТОПА. Зачёт =
 * названная часть тела вошла в круг. Ни одного детектора движений здесь не
 * работает: всю логику режима держит catcher.js, а этот файл только раскладывает
 * его события в те же obstacle.spawn/clear/miss, что и раньше, — чтобы очки,
 * звук, картинка и автопрогоны не заметили подмены. Разминки у ловца нет и быть
 * не может: разучивать нечего, мишень объясняет себя сама.
 *
 * РОТАЦИЯ ДВИЖЕНИЙ (`mode: 'moves'`, ключ `?moves=1`) — всё, что описано ниже, и
 * ровно в том виде, в каком оно работало до появления ловца. Механика A
 * «Уклонение» из ТЗ (раздел 3), восемнадцать движений, разминка, детекторы,
 * личные планки. Ключ не украшение: если ловец в поле не полетит, возврат
 * должен стоить один параметр в адресе, а не один релиз.
 *
 * Дальше — про режим движений.
 *
 * Полёт от первого лица: препятствия вылетают из-за горизонта и идут навстречу.
 * Типа три, все судятся по позе, а не по нажатию:
 *   barrier — барьер сверху, надо присесть под него;
 *   wall    — стена сбоку, надо шагнуть в свободную сторону, оставаясь на ногах;
 *   beam    — балка по диагонали сверху, надо наклонить корпус, не сходя с места;
 *   strike  — астероид сбоку на уровне груди, надо разбить ударом руки;
 *   knee    — кольцо снизу, надо пробить подъёмом колена;
 *   bird    — птица над головой сбоку, надо достать махом руки вверх;
 *   pit     — яма во всю ширину, надо перепрыгнуть;
 *   lunge   — волна у земли сбоку, надо отшагнуть этой ногой назад в выпад;
 *   heel    — уголёк у земли сбоку, надо захлестнуть этой голенью к ягодице.
 *
 * У стены и балки сторона означает «уходи в противоположную», у астероида,
 * кольца, волны и уголька — наоборот, «доставай этой же рукой или ногой».
 * Разница намеренная: от препятствия либо уклоняются, либо его сбивают.
 *
 * Зачёт идёт по ОКНУ, а не по мгновению пролёта. Полевой тест: «делаю одно и то
 * же движение, а засчитывает через раз». Так и было — поза проверялась ровно в
 * кадр passAt, а присед держится внизу 200–400 мс, к этому добавлялась задержка
 * камеры 80–150 мс и сглаживание угла. Попадание в мгновение выходило лотереей.
 * Теперь движение засчитывается, если поза сошлась в любой момент окна вокруг
 * пролёта, и засчитывается сразу — человек видит зачёт в тот момент, когда его
 * заработал, а не когда препятствие поравнялось с ним.
 *
 * Порядок препятствий псевдослучайный от сида раунда. Полевой тест: жёсткое
 * чередование читалось наперёд — «два низа, два бока», и человек готовился к
 * следующему до того, как его увидел. Math.random здесь не используется: сид
 * приходит снаружи, в тестах он фиксированный, и весь раунд воспроизводим.
 *
 * Раунд начинается с разминки. Полевой тест: инструкция текстом на старте не
 * работает — человек стоит в двух метрах от телефона и мелкие буквы не читает.
 * Поэтому первые полминуты идут медленные препятствия всех типов, а команда
 * пишется на весь экран: «ПРИСЯДЬ», «ШАГНИ ВПРАВО», «НАКЛОНИСЬ ВЛЕВО». Очки в
 * разминке не идут и в итог не попадают — это проба, а не результат.
 *
 * Анти-чит: сесть один раз и сидеть весь раунд нельзя — между препятствиями
 * надо вернуться в стойку, иначе следующее не засчитывается.
 *
 * Промах ничего не стоит и нигде не отмечается: раунд не прерывается, счётчиков
 * неудач у игрока нет. Это тренировка, а не аркада на выживание — человек делает
 * движения, а в конце видит, сколько препятствий было и сколько он прошёл.
 *
 * Чистая логика: ни React, ни canvas, ни собственных таймеров. Время и поза
 * приходят снаружи — экран ведёт часы сам и останавливает их, когда человек
 * вышел из кадра. Побочная выгода — тесты гоняют раунд числами.
 *
 * События: obstacle.spawn, obstacle.clear, obstacle.miss, round.end.
 */

