const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v)
const lerp = (a, b, p) => a + (b - a) * p

/**
 * mulberry32: короткий детерминированный генератор. Нужен именно свой, а не
 * Math.random, чтобы раунд по одному сиду повторялся кадр в кадр — иначе ни
 * тесты, ни разбор полевого лога невозможны.
 */
function createRng(seed) {
  let state = (seed >>> 0) || 1
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

export function createRound(overrides = {}) {
  const config = { ...DEFAULT_ROUND, ...overrides }
  const rng = createRng(config.seed)

  /**
   * ЛОВЕЦ. Есть он — весь остальной файл спит: препятствия не спавнятся,
   * детекторы не судят, разминка не идёт. Бросок у ловца тот же самый, что и у
   * ротации, — раунд по одному сиду обязан повторяться кадр в кадр в любом
   * режиме.
   */
  const catcher =
    config.mode === MODE.MOVES
      ? null
      : createCatcher({
          rng,
          radiusK: config.targetRadiusK,
          lifeMs: config.targetLifeMs,
          gapMs: config.targetGapMs,
          firstAtMs: config.firstSpawnAtMs,
        })

  /**
   * Личные максимумы снимаются ОДИН РАЗ на старте раунда, и планка внутри
   * раунда больше не двигается. Иначе она ползла бы под ногами: человек выдал
   * амплитуду лучше прежней — и следующее препятствие потребовало бы от него
   * больше, чем предыдущее. Новые максимумы копятся весь раунд и вступают в
   * силу со следующего. Автоматы удара, прыжка и ног всё равно берут свои
   * пороги при создании, так что иначе и не вышло бы.
   */
  const personalMax = config.personalMax ?? readMaxes()
  /** Планка движения: личная, если она есть, иначе общая. */
  const barOf = (movement, global) => thresholdFrom(personalMax[movement], global)

  /**
   * Планки этого раунда. Приседа здесь нет: его порог считается вживую, потому
   * что калибровка может подвинуть рабочие углы прямо во время раунда, а
   * глубина меряется от них.
   */
  const BAR = {
    [TYPE.WALL]: barOf(TYPE.WALL, config.dodgeShouldersK),
    [TYPE.BEAM]: barOf(TYPE.BEAM, config.leanShouldersK),
    [TYPE.STRIKE]: barOf(TYPE.STRIKE, config.punchOutK),
    [TYPE.KNEE]: barOf(TYPE.KNEE, config.kneeLiftK),
    [TYPE.BIRD]: barOf(TYPE.BIRD, config.raiseK),
    [TYPE.PIT]: barOf(TYPE.PIT, config.jumpFootLiftK),
    [TYPE.LUNGE]: barOf(TYPE.LUNGE, config.lungeBackK),
    [TYPE.HEEL]: barOf(TYPE.HEEL, config.heelFootK),
    /**
     * У выпада планок ДВЕ, и вторая — просадка таза. Без неё негибкий человек
     * проходил «Настройку под себя», получал мягкую планку по ноге и всё равно
     * не видел ни одного зачёта: упирался ровно в то, чего настройка не мерила.
     */
    [LUNGE_DROP]: barOf(LUNGE_DROP, config.lungeDropK),
    /**
     * Девять новых движений судит автомат moves.js, и пороги он берёт СВОИ,
     * при создании. Поэтому здесь стоят те же общие числа, а не личные: расти
     * личной планке было бы не с чем сверяться — автомат её не видит, и планка
     * с судьёй разъехались бы. Отсюда же и отсутствие этих типов в metricNow:
     * личный максимум по ним не копится намеренно.
     */
    [TYPE.BEND]: config.bendK,
    [TYPE.JUMPSQUAT]: config.jumpsquatK,
    [TYPE.JACK]: config.jackK,
    [TYPE.HOP]: config.hopK,
    [TYPE.LEGSIDE]: config.legsideK,
    [TYPE.SIDELUNGE]: config.sidelungeK,
    [TYPE.WINGS]: config.wingsK,
    [TYPE.CLAP]: config.clapK,
    [TYPE.TWISTKNEE]: config.twistkneeK,
    // вторая планка скручивания: по ней полоска считает путь локтем
    [TWIST_ELBOW]: config.twistkneeElbowK,
  }
  /**
   * ВЫКЛЮЧЕННЫЕ ДВИЖЕНИЯ выпадают из ротации раунда и из разминки — но только
   * когда набор не задан снаружи. Явный `types` это осознанный приказ: им
   * пользуются и отладочный ключ `?types=`, и тесты детекторов, и снятие
   * записей, и запрещать им звать выключенное движение значило бы заодно
   * выключить и всю оснастку вокруг него.
   *
   * Детектор, тесты и записи при этом живут: движение снято с ротации, а не
   * удалено, и вернуть его — одна строка в конфиге.
   */
  const disabled = config.disabledTypes ?? []
  const rotation = ALL_TYPES.filter((t) => !disabled.includes(t))
  const pool = config.types?.length
    ? ALL_TYPES.filter((t) => config.types.includes(t))
    : rotation
  /**
   * Разминка показывает только то, что в раунде и правда встретится, и каждый
   * тип подряд несколько раз: с первого показа движение не считывается, человек
   * успевает только удивиться. Со второго уже пробует осознанно.
   */
  const practiceOrder = PRACTICE_ORDER.filter((t) => pool.includes(t))
  /**
   * Фазы раунда: разминка по списку движений -> «молодец» с отсчётом -> зачёт.
   * Когда начнётся зачётная часть, заранее неизвестно: это зависит от того, как
   * быстро человек справится с разминкой.
   */
  const PHASE = { PRACTICE: 'practice', READY: 'ready', ROUND: 'round' }
  /**
   * У ловца разминки нет. Разминка существует затем, чтобы показать движение,
   * которое человек иначе не узнает по летящей фигуре; мишень с подписью
   * «КОЛЕНО» не нуждается ни в показе, ни в двух пробных повторах.
   */
  let phase =
    !catcher && config.practiceNeeded > 0 && practiceOrder.length ? PHASE.PRACTICE : PHASE.ROUND
  /** Ноль, если разминки нет: тогда зачёт идёт с самого начала. */
  let roundStartsAt = phase === PHASE.ROUND ? 0 : null
  let readyAt = null
  /** Какое движение сейчас разучивается и сколько зачётов подряд уже есть. */
  let practiceIndex = 0
  let practiceDone = 0
  let practiceTries = 0
  let nextPracticeAt = config.firstSpawnAtMs

  const endAt = () => (roundStartsAt ?? 0) + config.durationMs

  /** Все препятствия раунда: и летящие, и уже отсуженные. Мишени ловца — тоже. */
  const obstacles = []
  /** Живые мишени ловца по их номеру: по нему событие находит своё препятствие. */
  const catchLive = new Map()
  let clock = 0
  let ended = false
  let spawnedCount = 0
  let cleared = 0
  /** Считается только для технического лога — игроку промахи не показываются. */
  let missed = 0
  /** Разминочные препятствия считаются отдельно и в итог не идут. */
  let practiceSpawned = 0
  let practiceCleared = 0
  let nextSpawnAt = config.firstSpawnAtMs
  let lastType = null
  let sameRun = 0

  let downAngle = config.downAngle
  let upAngle = config.upAngle
  /** Последняя известная поза: угол в колене и положение корпуса в кадре. */
  let angle = null
  let hipX = null
  let shoulderX = null
  let shoulderWidth = null
  /** Углы локтей, вынос запястий вперёд, высота колен над тазом. */
  let elbow = { left: null, right: null }
  let reach = { left: null, right: null }
  let foreshorten = { left: null, right: null }
  let armDown = { left: null, right: null }
  let kneeLift = { left: null, right: null }
  let footLift = { left: null, right: null }
  /** Насколько запястье выше носа, в длинах корпуса: по этому судится птица. */
  let raise = { left: null, right: null }
  /** Высота стоп в кадре: по ней детектор прыжка узнаёт, где земля. */
  let ankleY = { left: null, right: null }
  /**
   * Насколько стопа выше второй (в корпусах) и насколько она ушла назад по
   * глубине (в метрах мировых точек). По первому судится захлёст, по второму —
   * выпад. Глубина бывает неизвестна: устройство может не отдать мировых точек,
   * и тогда это null, а не ноль (см. legs.js).
   */
  let ankleDy = { left: null, right: null }
  let ankleBack = { left: null, right: null }
  /** История высоты таза: по ней видно, стоит человек или приседает. */
  let hipY = null
  let torso = null
  /** Сырые признаки девяти новых движений — их читает автомат moves.js. */
  let moves = null
  /**
   * Сырые точки позы. Нужны ровно ловцу: он судит не признак движения, а место
   * конкретной точки тела, и никакие производные величины его не заменят.
   */
  let landmarks = null
  const hipTrack = []

  /**
   * Удар — переход, а не поза, поэтому за каждой рукой следит свой автомат.
   * Он получает угол каждый кадр и сообщает о состоявшемся выпрямлении.
   */
  const punchOptions = {
    riseK: config.punchRiseK,
    // насколько рука должна оказаться вынесенной — планка личная
    outK: BAR[TYPE.STRIKE],
    maxMs: config.punchMaxMs,
    sideK: config.punchSideK,
  }
  const punchWatchers = {
    [SIDE.LEFT]: createPunchWatcher(punchOptions),
    [SIDE.RIGHT]: createPunchWatcher(punchOptions),
  }
  /** Рука над головой: это мах, а не удар и не нейтральная стойка. */
  const overhead = (side) => raise[side] != null && raise[side] >= config.raiseOverheadK
  /**
   * Насколько рука выброшена вперёд, 0..1 — по ней и судится удар. Рука над
   * головой не даёт значения вовсе: мах через сторону вверх детектор удара
   * принимал за вынос руки в камеру, и на калибровочной записи это давало 4
   * ложных удара на один сегмент маха. Одно и то же значение идёт и в автомат
   * удара, и в полоску — иначе судья и индикатор разошлись бы.
   */
  const punchAt = (side) =>
    overhead(side)
      ? null
      : punchValue(
          { reach: reach[side], foreshorten: foreshorten[side], elbow: elbow[side] },
          { bentAngle: config.punchBentAngle, extendedAngle: config.punchExtendedAngle },
        )
  /** Последний удар каждой рукой — по нему судится астероид в своём окне. */
  const lastPunch = { [SIDE.LEFT]: null, [SIDE.RIGHT]: null }
  /**
   * Прыжок — тоже событие, и следит за ним свой автомат: обе стопы в воздухе
   * плюс рывок таза вверх в одном кадре (см. vertical.js). Один на раунд:
   * прыжок не бывает «левым» или «правым».
   */
  const jumpWatcher = createJumpWatcher({ footLiftK: BAR[TYPE.PIT] })
  let lastJump = null
  /**
   * Выпад и захлёст — тоже события, и следит за ними один общий автомат на оба
   * движения и обе стороны (см. legs.js): они живут на одних признаках и друг
   * друга исключают. Он же считает просадку таза, и она нужна полоске выпада.
   */
  const legWatchers = createLegWatchers({
    lunge: { backK: BAR[TYPE.LUNGE], dropK: BAR[LUNGE_DROP] },
    heel: { footK: BAR[TYPE.HEEL] },
  })
  const lastLunge = { [SIDE.LEFT]: null, [SIDE.RIGHT]: null }
  const lastHeel = { [SIDE.LEFT]: null, [SIDE.RIGHT]: null }
  /**
   * Девять новых движений — тоже события, и следит за ними один общий автомат
   * (см. moves.js): у всех девяти одна опора — рост, дом и наклон плеч за
   * четыре секунды, и считать её девять раз было бы расточительством.
   */
  const moveWatchers = createMoveWatchers()
  /** Последнее событие каждого движения на каждой стороне: ключ «тип:сторона». */
  const lastMove = new Map()
  const moveKey = (type, side) => `${type}:${side ?? ''}`
  /**
   * Нога ушла назад по глубине. В выпаде колени сгибаются ровно так же, как в
   * приседе, и без этого признака барьер засчитывался бы выпадом: на записи
   * calibration-lunge-heel детектор приседа дал 6 ложных срабатываний в
   * сегментах выпадов. Тот же срез стоит и в разборе записей.
   */
  const lunging = () =>
    (ankleBack.left != null && ankleBack.left >= BAR[TYPE.LUNGE]) ||
    (ankleBack.right != null && ankleBack.right >= BAR[TYPE.LUNGE])
  /** Вернулся ли игрок в стойку после предыдущего препятствия. */
  let stood = false
  /**
   * Домашняя позиция — где человек стоит, когда никуда не уворачивается. Именно
   * от неё считается шаг: если брать положение в момент вылета, база иногда
   * снималась, пока игрок ещё возвращался с предыдущего уворота, и тот же самый
   * шаг оказывался то достаточным, то нет.
   */
  let homeX = null

  /** Разгон считаем от момента вылета, а не от номера: раунд можно ставить на паузу. */
  const rampAt = (t) =>
    Math.pow(clamp01((t - (roundStartsAt ?? 0)) / config.durationMs), config.rampCurve)
  const gapAt = (t) => lerp(config.startGapMs, config.endGapMs, rampAt(t))
  const travelAt = (t) => lerp(config.startTravelMs, config.endTravelMs, rampAt(t))

  const duckAngle = () => downAngle + config.duckMarginDeg
  /**
   * Человек в приседе. Это СОСТОЯНИЕ, а не зачёт: по нему решается, что человек
   * сейчас внизу, и по нему же режутся движения, которые делают на ногах.
   * Порог здесь всегда общий — личная планка тут ни при чём, иначе один и тот
   * же наклон у слабого человека считался бы приседом, а у сильного нет.
   */
  const isDucking = () => angle != null && angle <= duckAngle()
  /**
   * А вот ЗАЧЁТ барьера — по личной планке. Меряется глубиной в градусах
   * (стойка минус текущий угол), потому что личный максимум — это размах, а не
   * абсолютный угол: у одного колено уходит на 75°, у другого на 40°, и общий
   * порог второму недостижим.
   */
  const duckDepth = () => barOf(TYPE.BARRIER, upAngle - duckAngle())
  const duckedEnough = () => angle != null && upAngle - angle >= duckDepth()
  /** Планка, по которой судится это движение — она же уходит в лог. */
  const barFor = (type) => (type === TYPE.BARRIER ? duckDepth() : BAR[type] ?? 0)
  /**
   * Нейтральная стойка: ноги выпрямлены, руки опущены, колени внизу. Именно она
   * снимает анти-чит — иначе можно было бы держать руку вытянутой или колено
   * поднятым и собирать препятствия, ничего не делая. Чего не видно, тому и
   * не мешаем: неизвестное значение считается нейтральным.
   */
  /**
   * Нейтральная стойка снимает анти-чит. Руки в неё намеренно не входят: повтор
   * удара и так невозможен без нового сгиба — за этим следит автомат удара, — а
   * проверка «руки опущены» ломала игру, потому что в приседе люди выносят руки
   * вперёд, и после первого же приседа нейтраль больше не наступала.
   *
   * Колено считается поднятым только с большим запасом: в приседе таз опускается
   * к уровню колен, и без запаса тот же присед сам себя и блокировал.
   */
  const isNeutral = () => {
    if (angle == null || angle < upAngle) return false
    const held = config.kneeLiftK + config.kneeNeutralMarginK
    // именно != null: неизвестную высоту нельзя сравнивать с порогом напрямую —
    // null в сравнении становится нулём и при отрицательном пороге «проходит»
    const raised = (v) => v != null && v > held
    if (raised(kneeLift.left) || raised(kneeLift.right)) return false
    // Руки в нейтраль всё-таки входят, но только одним признаком: над головой их
    // быть не должно. Проверка «руки опущены» когда-то ломала игру (в приседе
    // люди выносят руки вперёд), а вот поднятая над головой рука — это уже поза
    // птицы, и с ней птиц можно было бы собирать бесплатно.
    return !overhead(SIDE.LEFT) && !overhead(SIDE.RIGHT)
  }
  const needsBase = (type) => type === TYPE.WALL || type === TYPE.BEAM

  /**
   * Нога в воздухе — значит идёт подъём колена, а не шаг и не присед. Смотрим и
   * на колено, и на стопу: колено опускается раньше, чем человек ставит ногу.
   */
  const kneeRaised = () =>
    (kneeLift.left != null && kneeLift.left > config.kneeLiftK) ||
    (kneeLift.right != null && kneeLift.right > config.kneeLiftK) ||
    (footLift.left != null && footLift.left > config.footLiftK) ||
    (footLift.right != null && footLift.right > config.footLiftK)

  /** Насколько таз гулял по вертикали за последнее окно, в длинах корпуса. */
  const hipMotion = () => {
    if (hipY == null || !torso || hipTrack.length < 2) return 0
    let span = 0
    for (const point of hipTrack) span = Math.max(span, Math.abs(point.y - hipY))
    return span / torso
  }

  /** Корпус заметно уведён вбок — значит это наклон, а не шаг. */
  const leanedAside = () => {
    if (shoulderX == null || hipX == null || !shoulderWidth) return false
    return Math.abs(shoulderX - hipX) / shoulderWidth >= config.leanShouldersK
  }

  /**
   * Что прилетит следующим. Единственное ограничение — не больше двух одинаковых
   * подряд: без него генератор изредка выдаёт серию из четырёх барьеров, и
   * раунд снова выглядит рукописным. Стороны берутся тем же броском, без
   * механического чередования — иначе сторона угадывается по предыдущей.
   */
  function pickType(practice, at) {
    // в разминке разучивается ровно одно движение за раз
    if (practice) return practiceOrder[Math.min(practiceIndex, practiceOrder.length - 1)]
    const choices = sameRun >= 2 ? pool.filter((t) => t !== lastType) : pool
    if (!choices.length) return lastType // раунд из одного типа: ограничение неприменимо

    // На плотном темпе состав потока меняется: удар и колено требуют времени на
    // возврат, и их доля падает вдвое. Именно доля, а не запрет — движения
    // остаются в раунде, просто между ними появляется воздух.
    const crowded = gapAt(at) < config.crowdedGapMs
    const weightOf = (type) =>
      crowded && RECOVERY_TYPES.includes(type) ? config.recoveryTypeWeight : 1
    const total = choices.reduce((sum, type) => sum + weightOf(type), 0)
    if (!(total > 0)) return choices[0]

    // ровно один бросок на выбор типа, как и раньше: иначе поток по тому же
    // сиду перестал бы совпадать сам с собой между версиями
    let roll = rng() * total
    for (const type of choices) {
      roll -= weightOf(type)
      if (roll < 0) return type
    }
    return choices[choices.length - 1]
  }

  const pickSide = () => (rng() < 0.5 ? SIDE.LEFT : SIDE.RIGHT)

  /**
   * Насколько игрок уже увернулся — в ширинах собственных плеч и в долях
   * зачётного порога. Считается каждый кадр, пока препятствие летит: по этой
   * доле экран рисует полоску, и человек видит, сколько ещё осталось.
   */
  /**
   * Выдержка и помеха за окно зачёта.
   *
   * У выпада и захлёста условий несколько, и держаться они должны ОДНОВРЕМЕННО
   * и подряд. Пики каждого признака порознь этого не показывают: все могут
   * побывать в норме и ни разу не сойтись в один кадр — ровно то, что случилось
   * с захлёстом в поле 13 августа. Поэтому копим максимум выдержки и считаем,
   * какое условие мешало чаще прочих.
   */
  function trackHold(obstacle, probe, keys) {
    if (!probe) return
    if (probe.heldMs > (obstacle[keys.held] ?? -1)) obstacle[keys.held] = probe.heldMs
    if (!probe.block) return
    obstacle.blockCounts = obstacle.blockCounts ?? {}
    obstacle.blockCounts[probe.block] = (obstacle.blockCounts[probe.block] ?? 0) + 1
  }

  /**
   * Пики СОБСТВЕННЫХ признаков движения за окно зачёта — каждый в свою сторону
   * (см. MOVE_PARTS). Неизвестный признак пропускается, а не записывается нулём:
   * ноль здесь читался бы как «сделал, но плохо» вместо «не видно».
   */
  function trackParts(obstacle, metrics) {
    const parts = MOVE_PARTS[obstacle.type]
    if (!parts || !metrics) return
    const other = obstacle.side === SIDE.LEFT ? SIDE.RIGHT : SIDE.LEFT
    for (const [name, dir, valueOf] of parts) {
      const value = valueOf(metrics, obstacle.side, other)
      if (value == null || !Number.isFinite(value)) continue
      obstacle.movePeaks = obstacle.movePeaks ?? {}
      const best = obstacle.movePeaks[name]
      if (best == null || dir * value > dir * best) obstacle.movePeaks[name] = value
    }
  }

  /** Те же пики, но округлённые: в логе два знака, дальше — шум. */
  const peaksOf = (obstacle) => {
    const peaks = obstacle.movePeaks
    if (!peaks) return null
    const out = {}
    for (const [name, value] of Object.entries(peaks)) out[name] = Number(value.toFixed(2))
    return out
  }

  /** Помеха, которая встречалась чаще прочих за окно. */
  const topBlock = (obstacle) => {
    const counts = obstacle.blockCounts
    if (!counts) return null
    let best = null
    for (const [name, n] of Object.entries(counts)) {
      if (!best || n > counts[best]) best = name
    }
    return best
  }

  /**
   * Личная метрика движения — то самое число, по которому растёт личный
   * максимум. Она НАМЕРЕННО та же, по которой судит движок: считай максимум по
   * одному числу, а зачёт веди по другому — и планка поедет.
   */
  function metricNow(obstacle) {
    switch (obstacle.type) {
      case TYPE.BARRIER:
        // размах, а не абсолютный угол: у одного колено уходит на 75°, у
        // другого на 40°, и сравнивать надо глубину, а не положение
        return angle == null ? null : upAngle - angle
      case TYPE.WALL:
        return obstacle.dodgeK
      case TYPE.BEAM:
        return obstacle.leanK
      case TYPE.STRIKE:
        return punchAt(obstacle.side)
      case TYPE.KNEE:
        return kneeLift[obstacle.side]
      case TYPE.BIRD:
        return raise[obstacle.side]
      case TYPE.PIT:
        return jumpWatcher.feetLift
      case TYPE.LUNGE:
        return ankleBack[obstacle.side]
      case TYPE.HEEL:
        return ankleDy[obstacle.side]
      default:
        return null
    }
  }

  /**
   * Живое состояние препятствия плюс пик его личной метрики за окно зачёта.
   * Пик копится и на промахе тоже: движение, которого не хватило на зачёт, всё
   * равно рассказывает, на что человек способен, — а именно этого и не хватало
   * прежней калибровке «покажи максимум один раз».
   */
  function refreshDodge(obstacle) {
    refreshMetrics(obstacle)
    if (!inWindow(obstacle)) return
    const now = metricNow(obstacle)
    if (now != null && Number.isFinite(now) && now > (obstacle.amplitude ?? -Infinity)) {
      obstacle.amplitude = now
    }
  }

  function refreshMetrics(obstacle) {
    const width = shoulderWidth ?? obstacle.baseShoulder
    obstacle.progress = 0
    obstacle.blocked = false

    if (obstacle.type === TYPE.BARRIER) {
      // глубина приседа тоже показывается полоской: без неё человек не знает,
      // насколько ещё подсесть, и узнаёт об этом только по факту пролёта
      if (angle == null) return
      // полоска меряет ту же планку, по которой судит движок: разойдись они —
      // и человек видел бы полную полоску без зачёта
      const span = duckDepth()
      obstacle.progress = span > 0 ? clamp01((upAngle - angle) / span) : 0
      return
    }

    if (obstacle.type === TYPE.WALL) {
      const moved = dodgeDistance(hipX, obstacle.baseX, obstacle.side)
      if (moved == null || !width) {
        obstacle.dodgeK = null
        return
      }
      obstacle.dodgeK = moved / width
      obstacle.progress = clamp01(obstacle.dodgeK / BAR[TYPE.WALL])
      return
    }

    if (obstacle.type === TYPE.STRIKE) {
      // полоска показывает, насколько рука уже выброшена вперёд
      const v = punchAt(obstacle.side)
      obstacle.elbowAngle = elbow[obstacle.side]
      // сколько таз гулял за окно зачёта: без этого числа непонятно, промах
      // из-за отсутствия рывка или его срезала проверка подвижного таза
      if (inWindow(obstacle)) {
        const hip = hipMotion()
        if (obstacle.hipPeakK == null || hip > obstacle.hipPeakK) obstacle.hipPeakK = hip
      }
      if (v == null) return
      // до чего человек реально дотянул: по этому числу и будем двигать порог,
      // если удар опять не станет засчитываться
      if (inWindow(obstacle) && v > (obstacle.strikePeak ?? 0)) obstacle.strikePeak = v
      obstacle.progress = clamp01(v / BAR[TYPE.STRIKE])
      return
    }

    if (obstacle.type === TYPE.BIRD) {
      // полоска показывает, насколько рука дотянулась выше носа
      const value = raise[obstacle.side]
      if (value == null) return
      // до чего дотянул за окно: по этому числу и двигать порог, если птица
      // перестанет засчитываться в поле
      if (inWindow(obstacle) && (obstacle.raisePeak == null || value > obstacle.raisePeak)) {
        obstacle.raisePeak = value
      }
      obstacle.progress = clamp01(value / BAR[TYPE.BIRD])
      return
    }

    if (obstacle.type === TYPE.PIT) {
      // прыжок — событие, а не поза: полоска либо пуста, либо полна
      obstacle.progress = jumpInWindow(obstacle) ? 1 : 0
      return
    }

    if (obstacle.type === TYPE.LUNGE) {
      const back = ankleBack[obstacle.side]
      const drop = legWatchers.drop
      // пики копим порознь: если мировых точек нет вовсе, глубина так и
      // останется пустой, а просадка таза всё равно будет видна в логе —
      // именно по этой паре и станет понятно, чего не хватило
      if (inWindow(obstacle)) {
        trackHold(obstacle, legWatchers.lunge?.[obstacle.side], { held: 'lungeHeldMs' })
        if (back != null && back > (obstacle.lungeBackPeak ?? -Infinity)) {
          obstacle.lungeBackPeak = back
        }
        if (drop != null && drop > (obstacle.lungeDropPeak ?? -Infinity)) {
          obstacle.lungeDropPeak = drop
        }
      }
      // Полоска обязана показывать ОБА признака сразу, иначе она врёт: стопа,
      // унесённая назад без просадки таза, выпадом не является, а полоска по
      // одной глубине уже горела бы полной. Меньший из двух и решает.
      // обе доли считаются по тем же личным планкам, по которым судит автомат
      if (back == null || drop == null) return
      obstacle.progress = clamp01(Math.min(back / BAR[TYPE.LUNGE], drop / BAR[LUNGE_DROP]))
      return
    }

    if (obstacle.type === TYPE.HEEL) {
      // полоска показывает, насколько стопа поднялась относительно второй
      const lift = ankleDy[obstacle.side]
      if (inWindow(obstacle)) {
        trackHold(obstacle, legWatchers.heel?.[obstacle.side], { held: 'heelHeldMs' })
        if (lift != null && lift > (obstacle.heelLiftPeak ?? -Infinity)) {
          obstacle.heelLiftPeak = lift
        }
        /**
         * У захлёста, кроме подъёма стопы, ТРИ обязательных условия: колено
         * внизу, таз на месте и нога не ушла назад по глубине. В поле 13
         * августа он не засчитался ни разу при подъёме стопы 0.92–1.29 против
         * планки 0.45 — то есть резало одно из этих трёх, а в логе не было ни
         * одного из них, и промах оказался неразбираем. Копим все.
         */
        const knee = kneeLift[obstacle.side]
        const back = ankleBack[obstacle.side]
        const drop = legWatchers.drop
        if (knee != null && knee > (obstacle.heelKneePeak ?? -Infinity)) {
          obstacle.heelKneePeak = knee
        }
        if (back != null && back > (obstacle.heelBackPeak ?? -Infinity)) {
          obstacle.heelBackPeak = back
        }
        if (drop != null && drop > (obstacle.heelDropPeak ?? -Infinity)) {
          obstacle.heelDropPeak = drop
        }
      }
      if (lift == null) return
      obstacle.progress = clamp01(lift / BAR[TYPE.HEEL])
      return
    }

    /**
     * Девять новых: полоска — доля от порога ГЛАВНОГО признака движения, того
     * самого, что назван в подсказке о промахе. У каждого признак свой (см.
     * moveProgress в moves.js), но правило одно, и потому оно одно на девятерых.
     *
     * Пик копится и на промахе: движение, которого не хватило на зачёт, всё
     * равно рассказывает, до чего человек дотянул, — и по этому числу потом
     * двигать порог, если движение перестанет засчитываться в поле.
     */
    if (MOVE_TYPES.includes(obstacle.type)) {
      const metrics = moveWatchers.metrics
      // в лог идёт САМ замер, а не доля: по доле порог не подвинешь, а
      // планка в том же событии уже есть отдельным полем
      const value = moveMetric(obstacle.type, obstacle.side, metrics)
      if (inWindow(obstacle)) {
        if (value != null && Number.isFinite(value)) {
          // у хлопка признак обратный — там «лучший» замер самый МАЛЕНЬКИЙ
          const better =
            obstacle.type === TYPE.CLAP
              ? value < (obstacle.movePeak ?? Infinity)
              : value > (obstacle.movePeak ?? -Infinity)
          if (better) obstacle.movePeak = value
        }
        /**
         * Главного признака мало: условий у движения два и больше, и не
         * хватить может любого. Поэтому за окно копятся ВСЕ свои признаки
         * движения, плюс выдержка и помеха — как у выпада с захлёстом.
         */
        trackParts(obstacle, metrics)
        trackHold(obstacle, moveWatchers.probes?.[obstacle.type]?.[obstacle.side ?? 'none'], {
          held: 'moveHeldMs',
        })
      }
      const share = moveProgress(obstacle.type, obstacle.side, metrics, BAR)
      if (share == null) return
      obstacle.progress = clamp01(share)
      return
    }

    if (obstacle.type === TYPE.KNEE) {
      const lift = kneeLift[obstacle.side]
      if (lift == null) return
      obstacle.kneeLiftK = lift
      // от опущенной ноги до линии таза — весь путь полоски
      obstacle.progress = clamp01(
        (lift - (BAR[TYPE.KNEE] - config.kneeRangeK)) / config.kneeRangeK,
      )
      return
    }

    if (obstacle.type !== TYPE.BEAM) return

    const lean = leanDistance(shoulderX, hipX, obstacle.side)
    if (lean == null || !width) {
      obstacle.leanK = null
      obstacle.driftK = null
      return
    }
    obstacle.leanK = lean / width
    obstacle.progress = clamp01(obstacle.leanK / BAR[TYPE.BEAM])
    // ушёл всем телом — это шаг, а не наклон: полоска гаснет, зачёта не будет
    obstacle.driftK =
      obstacle.baseX == null ? null : Math.abs(hipX - obstacle.baseX) / width
    obstacle.blocked = obstacle.driftK != null && obstacle.driftK > config.leanDriftK
  }

  /**
   * Когда открывается окно зачёта. Разминочный астероид — исключение: он ползёт
   * пять секунд, и человек бьёт его, как только увидел. Запись с айфона: удар
   * приходил за 1.5–4 с до пролёта, а рука так и оставалась вытянутой навстречу.
   * К открытию обычного окна (за hitWindowBeforeMs + punchGraceMs до пролёта)
   * тот удар был уже старым, а нового рывка не было — отсюда no-strike при
   * полном peak. Поэтому в разминке удар принимается с самого вылета.
   *
   * Зачётной части это не касается: там окно по записи раунда верное — удар
   * приходит реакцией на увиденное, уже после пролёта.
   */
  const windowOpensAt = (obstacle) =>
    obstacle.practice && EVENT_TYPES.includes(obstacle.type)
      ? obstacle.spawnAt
      : obstacle.passAt - config.hitWindowBeforeMs
  /**
   * Сколько окно живёт после пролёта. Шире обычного оно у движений-реакций:
   * удар человек делает уже после того, как увидел цель, а выпад и захлёст к
   * тому же отдаются автоматом только по выдержке.
   */
  const windowAfterOf = (type) => {
    if (type === TYPE.STRIKE) return config.strikeWindowAfterMs
    if (type === TYPE.LUNGE || type === TYPE.HEEL) return config.legWindowAfterMs
    /**
     * Девяти новым движениям поставлено то же окно, что волне и угольку, и это
     * ПРИКИДКА, а не замер, — ровно такая же, как у них. Основание то же:
     * человек делает движение реакцией на увиденное, а автомат отдаёт событие
     * не раньше, чем оно продержится свою выдержку (200 мс, у разведения рук
     * 400), то есть с запозданием уже по устройству. Настоящее число снимается
     * с записи ЖИВОГО раунда по полю moveAt в логах game.clear/game.miss.
     */
    if (MOVE_TYPES.includes(type)) return config.legWindowAfterMs
    return config.hitWindowAfterMs
  }
  const windowClosesAt = (obstacle) => obstacle.passAt + windowAfterOf(obstacle.type)

  /**
   * Самое широкое окно среди типов, которые вообще могут выпасть в этом раунде.
   *
   * По нему решается, выпускать ли последнее препятствие. Раньше запас считался
   * по обычному окну в 500 мс, а у удара, выпада и захлёста оно 1400: такое
   * препятствие успевало вылететь, раунд кончался раньше, чем закрывалось его
   * окно, и оно НАВСЕГДА оставалось incoming. В итоге spawned было больше, чем
   * cleared + missed, и экран результата занижал «сколько было».
   *
   * Тип на момент проверки ещё не выбран — он определяется только внутри
   * spawnObstacle, — поэтому берём худший случай по всему пулу. Плата: в конце
   * раунда изредка недосчитается одно препятствие. Это честнее, чем оставить
   * неотсуженное.
   */
  const maxWindowAfter = pool.reduce(
    (max, type) => Math.max(max, windowAfterOf(type)),
    config.hitWindowAfterMs,
  )
  const inWindow = (obstacle) =>
    clock >= windowOpensAt(obstacle) && clock <= windowClosesAt(obstacle)
  /**
   * Был ли удар этой рукой в зачётном окне астероида. Удар часто приходится
   * чуть раньше окна: по логу люди начинают движение за 700 мс до пролёта, то
   * есть ровно на его открытии. Одна проверка и на зачёт, и на разбор промаха —
   * иначе причина в логе расходилась бы с тем, что видел судья.
   */
  const punchInWindow = (obstacle) => {
    const punch = lastPunch[obstacle.side]
    return !!punch && punch.at >= windowOpensAt(obstacle) - config.punchGraceMs
  }

  /** Был ли прыжок в окне этой ямы. Та же логика, что у удара, и та же причина. */
  const jumpInWindow = (obstacle) =>
    !!lastJump && lastJump.at >= windowOpensAt(obstacle) - config.jumpGraceMs

  /**
   * Был ли выпад (захлёст) нужной ногой в окне. Та же логика, что у удара:
   * событие уже состоялось, и остаётся проверить сторону и время.
   */
  const legEventOf = (obstacle) =>
    (obstacle.type === TYPE.LUNGE ? lastLunge : lastHeel)[obstacle.side]
  const legInWindow = (obstacle) => {
    const event = legEventOf(obstacle)
    return !!event && event.at >= windowOpensAt(obstacle) - config.legGraceMs
  }

  /**
   * Было ли одно из девяти новых движений нужной стороной в окне. Та же логика,
   * что у выпада: событие уже состоялось, остаётся проверить сторону и время.
   */
  const moveEventOf = (obstacle) => lastMove.get(moveKey(obstacle.type, obstacle.side)) ?? null
  const moveInWindow = (obstacle) => {
    const event = moveEventOf(obstacle)
    return !!event && event.at >= windowOpensAt(obstacle) - config.legGraceMs
  }

  function judge(obstacle) {
    // сидел с прошлого препятствия и не вставал — не засчитываем ничего
    if (!stood) return false

    // Присед: обе ноги на полу. Иначе подъём колена засчитывался бы барьером —
    // на калибровочной записи угол в согнутой поднятой ноге падает до 109°,
    // и для измерителя глубины это неотличимо от приседа.
    // Присед: обе ноги на полу и корпус не уведён вбок. Иначе приседом
    // засчитывались бы подъём колена и наклон — в обоих ноги сгибаются.
    if (obstacle.type === TYPE.BARRIER) {
      // выпадом барьер не проходится: в нём колени сгибаются так же, как в
      // приседе, и измеритель глубины этой разницы не видит вовсе
      return duckedEnough() && !kneeRaised() && !leanedAside() && !lunging()
    }

    /**
     * Колено судится ДО среза по приседу. Поднятая нога сама сгибается, средний
     * угол коленей падает ниже зачётной глубины, и общий срез «в приседе ничего
     * не судим» отбивал правильный подъём: в полевом логе lift 0.27–0.41 при
     * пороге 0.2 — и промах с причиной 'sitting'.
     *
     * Настоящий присед кольцом всё равно не пройдёт: от этого защищает не угол,
     * а асимметрия — в приседе оба колена идут к тазу одинаково, а подъём всегда
     * односторонний.
     */
    if (obstacle.type === TYPE.KNEE) {
      const lift = kneeLift[obstacle.side]
      if (lift == null || lift <= BAR[TYPE.KNEE]) return false
      // второе колено внизу: иначе это присед, а не подъём колена
      const other = kneeLift[obstacle.side === SIDE.LEFT ? SIDE.RIGHT : SIDE.LEFT]
      return other == null || lift - other >= config.kneeSideK
    }

    /**
     * Яма судится до среза по приседу, и по той же причине, что колено: прыжок
     * УЖЕ состоялся, а приземляются люди в полуприсед — гасить им удар о пол.
     * Отменять зачёт за мягкую посадку было бы наказанием за правильную технику.
     */
    if (obstacle.type === TYPE.PIT) return jumpInWindow(obstacle)

    /**
     * Волна и уголёк — тоже до среза по приседу, и это не перестраховка, а
     * замер: в выпаде угол в колене падает до 72°, то есть глубже любого
     * зачётного приседа. Общий срез «в приседе ничего не судим» зарезал бы
     * САМО движение — ровно та грабля, что была с подъёмом колена (промахи
     * 'sitting' при честном lift 0.27–0.41, коммит c7a3918).
     *
     * Присед вместо выпада при этом не пройдёт: судит не поза, а состоявшееся
     * событие автомата, а тому нужна ушедшая назад нога, которой в приседе нет.
     */
    if (obstacle.type === TYPE.LUNGE || obstacle.type === TYPE.HEEL) {
      return legInWindow(obstacle)
    }

    /**
     * Девять новых — тоже до среза по приседу, и по той же причине, что колено
     * и выпад: в приседе с прыжком, в наклоне вперёд и в боковом выпаде колени
     * согнуты по самому устройству движения, и общий срез «в приседе ничего не
     * судим» зарезал бы САМИ движения. Ложного зачёта отсюда не выйдет: судит
     * не поза, а состоявшееся событие автомата, а ему нужны признаки, которых
     * в приседе нет.
     */
    if (MOVE_TYPES.includes(obstacle.type)) return moveInWindow(obstacle)

    // всё остальное делается на ногах, присед здесь не спасает
    if (isDucking()) return false

    if (obstacle.type === TYPE.BIRD) {
      // птица висит на уровне головы: достать её надо рукой своей стороны
      const value = raise[obstacle.side]
      if (value == null || value < BAR[TYPE.BIRD]) return false
      // вторая рука внизу: обе вверх — это потягивание, а не мах
      const other = raise[obstacle.side === SIDE.LEFT ? SIDE.RIGHT : SIDE.LEFT]
      return other == null || other < config.raiseOtherK
    }

    if (obstacle.type === TYPE.STRIKE) {
      // удар делают стоя: если таз идёт вниз-вверх, это присед с выносом рук
      if (hipMotion() > config.punchHipMoveK) return false
      // засчитывается не поза, а состоявшийся удар: той рукой и внутри окна
      return punchInWindow(obstacle)
    }

    if (obstacle.type === TYPE.WALL) {
      // шаг — это перенос веса, а не подъём колена и не наклон: при подъёме
      // колена таз уезжает вбок ровно так же, как при шаге
      if (kneeRaised() || leanedAside()) return false
      return obstacle.dodgeK != null && obstacle.dodgeK >= BAR[TYPE.WALL]
    }
    if (kneeRaised()) return false
    return obstacle.leanK != null && obstacle.leanK >= BAR[TYPE.BEAM] && !obstacle.blocked
  }

  function metricOf(obstacle) {
    if (obstacle.type === TYPE.WALL) return obstacle.dodgeK
    if (obstacle.type === TYPE.BEAM) return obstacle.leanK
    if (obstacle.type === TYPE.KNEE) return obstacle.kneeLiftK
    return null
  }

  function missReason(obstacle) {
    if (!stood) return 'no-stand'
    if (obstacle.type === TYPE.BARRIER) return angle == null ? 'no-person' : 'not-low'
    // Колено судится и с согнутыми ногами, поэтому 'sitting' его причиной быть
    // не может: не хватило либо высоты, либо асимметрии — и то и другое человек
    // исправляет одним и тем же «колено выше».
    if (obstacle.type === TYPE.KNEE) return hipX == null ? 'no-person' : 'no-knee'
    // яма, как и колено, судится и с согнутыми ногами: причина у неё одна
    if (obstacle.type === TYPE.PIT) return hipX == null ? 'no-person' : 'no-jump'
    // Выпад и захлёст судятся до среза по приседу, поэтому 'sitting' их
    // причиной быть не может: в выпаде колени и должны быть согнуты.
    if (obstacle.type === TYPE.LUNGE) return hipX == null ? 'no-person' : 'no-lunge'
    if (obstacle.type === TYPE.HEEL) return hipX == null ? 'no-person' : 'no-heel'
    // девять новых судятся до среза по приседу, поэтому 'sitting' их причиной
    // быть не может: в приседе с прыжком и в боковом выпаде колени и должны
    // быть согнуты
    if (MOVE_TYPES.includes(obstacle.type)) {
      return hipX == null ? 'no-person' : `no-${obstacle.type}`
    }
    if (isDucking()) return 'sitting'
    if (hipX == null) return 'no-person'
    if (obstacle.type === TYPE.WALL) return 'no-step'
    if (obstacle.type === TYPE.BIRD) return 'no-raise'
    if (obstacle.type === TYPE.STRIKE) {
      // рывок рукой был, а зачёта нет — значит срезала проверка подвижного
      // таза: человек бил на ходу вниз-вверх, а не стоя. Без этой развилки
      // 'no-strike' накрывал оба случая, и по логу было не понять, какой
      return punchInWindow(obstacle) ? 'strike-hips' : 'no-strike'
    }
    if (obstacle.blocked) return 'stepped'
    return 'no-lean'
  }

  /** Выпустить препятствие: разминочное разучивает движение, зачётное считается. */
  function spawnObstacle(spawnAt, practice, events) {
    const travelMs = practice ? config.practiceTravelMs : Math.round(travelAt(spawnAt))
    // состав потока зависит от темпа в этот момент раунда, а не от номера
    const type = pickType(practice, spawnAt)
    if (!practice) {
      sameRun = type === lastType ? sameRun + 1 : 1
      lastType = type
    }

    const obstacle = {
      id: spawnedCount + practiceSpawned + 1,
      index: practice ? practiceSpawned : spawnedCount,
      practice,
      type,
      side: SIDELESS_TYPES.includes(type) ? null : pickSide(),
      spawnAt,
      passAt: spawnAt + travelMs,
      travelMs,
      status: 'incoming',
      judgedAt: null,
      angleAtPass: null,
      /** Откуда считать уклонение: домашняя позиция игрока. */
      baseX: needsBase(type) ? homeX ?? hipX : null,
      baseShoulder: needsBase(type) ? shoulderWidth : null,
      dodgeK: null,
      leanK: null,
      driftK: null,
      /** Замеры удара: сколько миллисекунд шло выпрямление и с каких углов. */
      strikeMs: null,
      strikeFrom: null,
      strikeTo: null,
      /** До какого значения дотянул вынос руки за окно зачёта. */
      strikePeak: null,
      /** Насколько таз гулял за окно зачёта — в длинах корпуса. */
      hipPeakK: null,
      /** Когда пришёл удар относительно пролёта: минус — раньше, плюс — позже. */
      punchAtMs: null,
      /** До какой высоты дотянулась рука за окно птицы, в длинах корпуса. */
      raisePeak: null,
      /** Когда случился прыжок относительно пролёта ямы. */
      jumpAtMs: null,
      /**
       * Волна: до чего дотянулись оба её признака за окно — глубина ухода ноги
       * назад и просадка таза. Уголёк: насколько поднялась стопа. Плюс момент
       * события относительно пролёта — по нему и снимутся настоящие окна.
       */
      lungeBackPeak: null,
      lungeDropPeak: null,
      heelLiftPeak: null,
      /** Три страховки захлёста: без них его промах в логе неразбираем. */
      heelKneePeak: null,
      heelBackPeak: null,
      heelDropPeak: null,
      /**
       * Сколько условие держалось подряд и что мешало чаще прочих. У выпада и
       * захлёста условий несколько, и сойтись они должны В ОДИН КАДР — по
       * пикам порознь этого не видно.
       */
      lungeHeldMs: null,
      heelHeldMs: null,
      blockCounts: null,
      legAtMs: null,
      /**
       * Девять новых: до чего дотянул главный признак движения за окно и когда
       * само движение случилось относительно пролёта. Второе число — то же, что
       * legAt у волны: только по нему и снимаются настоящие окна зачёта.
       */
      movePeak: null,
      moveAtMs: null,
      /**
       * И его собственные признаки за окно — по два-четыре на движение (см.
       * MOVE_PARTS), плюс выдержка. Без них промах девяти новых в логе
       * неразбираем: главный признак один, а условий несколько.
       */
      movePeaks: null,
      moveHeldMs: null,
      /** Высота колена над линией таза в длинах корпуса. */
      kneeLiftK: null,
      /**
       * Пик личной метрики этого движения за окно зачёта. По нему растёт личный
       * максимум — то есть планка снимается с настоящей игры, а не с отдельного
       * экрана «покажи максимум», который кто-нибудь непременно прошёл бы
       * вполсилы: на кону деньги.
       */
      amplitude: null,
      elbowAngle: null,
      progress: 0,
      blocked: false,
    }

    obstacles.push(obstacle)
    if (practice) practiceSpawned += 1
    else spawnedCount += 1
    events.push({ type: 'obstacle.spawn', at: obstacle.spawnAt, obstacle })
    return obstacle
  }

  /**
   * Разминка засчитана: движение сделано нужное число раз подряд. Дальше либо
   * следующее движение, либо «молодец» и отсчёт перед зачётной частью.
   */
  function advancePractice(ok, events) {
    practiceTries += 1
    // «два раза подряд»: промах обнуляет пару, а не уменьшает её на единицу
    practiceDone = ok ? practiceDone + 1 : 0

    const learned = practiceDone >= config.practiceNeeded
    // предел попыток нужен только автотестам и особым сессиям: по умолчанию
    // разминка ждёт столько, сколько нужно
    const givenUp = config.practiceMaxTries > 0 && practiceTries >= config.practiceMaxTries

    if (learned || givenUp) {
      events.push({
        type: 'practice.move',
        at: clock,
        movement: practiceOrder[practiceIndex],
        learned,
        tries: practiceTries,
      })
      practiceIndex += 1
      practiceDone = 0
      practiceTries = 0
    }

    if (practiceIndex >= practiceOrder.length) {
      phase = PHASE.READY
      readyAt = clock + config.readyMs
      events.push({ type: 'practice.done', at: clock, readyAt })
    }
  }

  /**
   * Мишень ловца в одежде препятствия. Наружу игра отдаёт один и тот же вид
   * события в обоих режимах — иначе очки, звук, слой мишеней, логи и оба
   * автопрогона пришлось бы учить второму словарю, и половина их разъехалась бы
   * с первой же правкой.
   *
   * `passAt` и `travelMs` тут не про полёт, а про жизнь мишени: экран по ним
   * рисует хвост и пульс, и обе величины у ловца означают ровно то же самое —
   * «когда пора» и «сколько всего было времени».
   */
  function catchObstacle(target) {
    return {
      id: target.id,
      index: spawnedCount,
      practice: false,
      type: CATCH_TYPE,
      /** Какую часть тела назвала подпись и с какой стороны висит круг. */
      part: target.part,
      side: target.side,
      /** Место и радиус в НОРМИРОВАННЫХ координатах: отрисовка переведёт сама. */
      spot: { x: target.x, y: target.y, rx: target.rx, ry: target.ry },
      spawnAt: target.spawnAt,
      passAt: target.expiresAt,
      travelMs: target.lifeMs,
      lifeMs: target.lifeMs,
      status: 'incoming',
      judgedAt: null,
      timingMs: null,
      /** Сколько было до нужной части при появлении и насколько близко подошла. */
      gapK: target.gapK,
      nearK: null,
      /**
       * ЖИВЫЕ ЧИСЛА ДЛЯ КАРТИНКИ — обновляются каждый кадр, пока мишень висит.
       *
       * `near`: где нужная часть тела ПРЯМО СЕЙЧАС, в радиусах круга (1 — ровно
       * по краю). По нему мишень отвечает на подводимую руку — разгорается тем
       * ярче, чем ближе. Это именно текущий кадр, а не лучший за жизнь: по
       * лучшему мишень светилась бы и после того, как рука ушла.
       *
       * `aged`: доля прожитой жизни, 0..1. По ней идёт кольцо-таймер и
       * учащается пульс на последней трети.
       *
       * Оба числа — ТОЛЬКО для отрисовки. Судейство их не видит и видеть не
       * должно: судит catcher.js, и второго мнения у игры нет.
       */
      near: null,
      aged: 0,
      /** Место найдено по правилам, а не отдано по истечении поиска. */
      clean: target.clean,
      /** Мишень пришлось прижать к краю кадра: по доле таких видно, не велика ли зона. */
      edged: target.edged,
      /** Как далеко мишень от оси тела: жёсткий инвариант ловца, не меньше 1.1. */
      axisK: target.axisK,
      progress: 0,
      blocked: false,
    }
  }

  /**
   * Ловец: спавн и суд целиком внутри catcher.js, здесь только счёт и события.
   * Обратите внимание, чего тут НЕТ: ни окна зачёта, ни анти-чита на стойку, ни
   * личных планок, ни причин промаха на выбор. У мишени причина ровно одна —
   * не успел, — и выдумывать вторую значило бы врать человеку.
   */
  function advanceCatch(events) {
    /**
     * Мишень, которая не успевает дожить до конца раунда, не выпускаем: иначе
     * она повиснет неотсуженной, и spawned окажется больше, чем cleared+missed.
     * Сравнение строгое по той же причине, что и у препятствий: промах
     * объявляется на кадре ПОСЛЕ истечения, а раунд кончается на кадре endAt.
     */
    const allowSpawn = clock + config.targetLifeMs < endAt()

    for (const event of catcher.update(clock, landmarks, { allowSpawn })) {
      if (event.kind === 'spawn') {
        const obstacle = catchObstacle(event.target)
        obstacles.push(obstacle)
        catchLive.set(event.target.id, obstacle)
        spawnedCount += 1
        events.push({ type: 'obstacle.spawn', at: obstacle.spawnAt, obstacle })
        continue
      }

      const obstacle = catchLive.get(event.target.id)
      if (!obstacle) continue
      catchLive.delete(event.target.id)
      const ok = event.kind === 'clear'
      obstacle.status = ok ? 'cleared' : 'hit'
      obstacle.judgedAt = clock
      obstacle.progress = ok ? 1 : 0
      obstacle.nearK = event.target.nearK
      /** Сколько человек ловил мишень: от появления до зачёта. */
      obstacle.timingMs = ok ? Math.round(clock - obstacle.spawnAt) : null
      if (ok) cleared += 1
      else missed += 1

      events.push({
        type: ok ? 'obstacle.clear' : 'obstacle.miss',
        at: clock,
        obstacle,
        angle,
        side: obstacle.side,
        practice: false,
        /** Часть тела и время реакции: по ним видно, какая мишень даётся хуже. */
        part: obstacle.part,
        timing: obstacle.timingMs,
        /**
         * Насколько близко часть подходила к центру, в радиусах: 1 — ровно по
         * краю круга. Это единственное число, по которому разбирается промах
         * ловца, и оно разводит два совершенно разных случая — «тянулся и не
         * дотянул» (1.1) и «даже не пробовал» (3.4).
         */
        near: obstacle.nearK == null ? null : Number(obstacle.nearK.toFixed(2)),
        /** С какого расстояния мишень начиналась — чтобы near было с чем сравнить. */
        gap: obstacle.gapK == null ? null : Number(obstacle.gapK.toFixed(2)),
        reason: ok ? null : 'no-catch',
      })
    }

    /**
     * Живые числа для картинки — после разбора событий, потому что мишень могла
     * появиться прямо сейчас и её надо застать уже с ними. Отсуженной мишени
     * они больше не двигаются: экран дорисовывает её ещё долю секунды, и
     * доводить в этот момент таймер до конца значило бы показывать, будто она
     * ещё жива.
     */
    const live = catcher.target
    if (live) {
      const obstacle = catchLive.get(live.id)
      if (obstacle) {
        obstacle.near = live.near
        obstacle.aged = clamp01((clock - obstacle.spawnAt) / obstacle.lifeMs)
      }
    }

    // конец раунда — только по времени, другого способа его закончить нет
    if (clock >= endAt()) {
      ended = true
      events.push({ type: 'round.end', at: endAt(), spawned: spawnedCount, cleared, missed })
    }
  }

  function advance(now, events) {
    if (ended) return
    // часы только вперёд: кадры и raf приходят вперемешку
    if (now > clock) clock = now

    if (catcher) {
      advanceCatch(events)
      return
    }

    // высота таза за последнее окно: по ней отличаем удар от приседа с руками
    if (hipY != null) {
      hipTrack.push({ t: clock, y: hipY })
      while (hipTrack.length && clock - hipTrack[0].t > config.punchHipWindowMs) hipTrack.shift()
    }

    /**
     * 0. Девять новых движений судятся первыми, и не по прихоти: их автомат
     * считает опору кадра — рост человека на картинке и складку корпуса, — а от
     * складки зависит, читаемы ли вообще остальные признаки.
     */
    for (const move of moveWatchers.update(clock, moves)) {
      lastMove.set(moveKey(move.movement, move.side), move)
    }

    /**
     * 0a. ПРЕДОХРАНИТЕЛЬ НА СЛОЖЕННЫЙ КОРПУС. В наклоне вперёд длина корпуса в
     * кадре падает до 0.06 от обычной: плечи доходят до линии таза и уходят
     * ниже. Всё, что на неё делится, в этот момент взрывается — на записи это
     * дало 10 ложных ПРЫЖКОВ на наклонах, то есть наклоном вперёд можно было бы
     * бесплатно проходить ямы. Поэтому прыжок, колено, птица и захлёст в такой
     * позе не судятся вовсе: их признаки становятся НЕИЗВЕСТНЫ (null), а не
     * нулём. Пороги при этом не тронуты — чинить надо не планку, а деление на
     * почти ноль.
     *
     * Значения перетираются до автоматов и до судейства, а следующий кадр
     * приносит их заново через applyPose — прошлое состояние не залипает.
     */
    if (moveWatchers.fold != null && moveWatchers.fold < READABLE_FOLD) {
      kneeLift = { left: null, right: null }
      raise = { left: null, right: null }
      ankleDy = { left: null, right: null }
      ankleY = { left: null, right: null }
      footLift = { left: null, right: null }
    }

    // 0б. нейтральная стойка снимает анти-чит: следующее препятствие снова можно
    // засчитать. Заодно кормим автоматы ударов — удар виден только по переходу
    for (const side of [SIDE.LEFT, SIDE.RIGHT]) {
      const other = side === SIDE.LEFT ? SIDE.RIGHT : SIDE.LEFT
      const punch = punchWatchers[side].update(clock, punchAt(side), punchAt(other))
      if (punch) lastPunch[side] = punch
    }
    // прыжок виден только по переходу, поэтому автомат кормится каждый кадр
    const jumped = jumpWatcher.update(clock, { ankleY, hipY, torso })
    if (jumped) lastJump = jumped
    // выпад и захлёст — тоже переходы: автомат ведёт медиану таза за четыре
    // секунды и отдаёт событие по выдержке, поэтому кадры ему нужны все подряд
    for (const leg of legWatchers.update(clock, { ankleDy, kneeLift, ankleBack, hipY, torso })) {
      if (leg.movement === TYPE.LUNGE) lastLunge[leg.side] = leg
      else lastHeel[leg.side] = leg
    }
    if (isNeutral()) stood = true

    // 1. фаза «молодец, погнали»: обратный отсчёт перед зачётной частью
    if (phase === PHASE.READY && clock >= readyAt) {
      phase = PHASE.ROUND
      roundStartsAt = readyAt
      nextSpawnAt = roundStartsAt + config.breatherMs
      events.push({ type: 'round.start', at: roundStartsAt })
    }

    // 2. что вылетело из-за горизонта
    if (phase === PHASE.PRACTICE) {
      // разминочные идут строго по одному: разучивается ровно одно движение
      const busy = obstacles.some((o) => o.status === 'incoming')
      if (!busy && clock >= nextPracticeAt) spawnObstacle(nextPracticeAt, true, events)
    } else if (phase === PHASE.ROUND) {
      for (;;) {
        if (nextSpawnAt > clock) break
        // Препятствие, которое не успевает долететь и отсудиться до конца
        // раунда, не выпускаем: иначе оно повисает неотсуженным.
        //
        // Сравнение строгое, и это не придирка: промах объявляется только на
        // кадре ПОСЛЕ закрытия окна, а раунд кончается на кадре endAt. Успей
        // окно закрыться ровно в endAt — такого кадра уже не будет, и
        // препятствие останется incoming навсегда.
        const travelMs = Math.round(travelAt(nextSpawnAt))
        if (nextSpawnAt + travelMs + maxWindowAfter >= endAt()) break
        spawnObstacle(nextSpawnAt, false, events)
        nextSpawnAt += Math.round(gapAt(nextSpawnAt))
      }
    }

    // 1a. живое состояние по каждому летящему препятствию
    let anyWindowOpen = false
    for (const obstacle of obstacles) {
      if (obstacle.status !== 'incoming') continue
      if (inWindow(obstacle)) anyWindowOpen = true
      // если в момент вылета человека не было видно — берём первую же позу
      if (needsBase(obstacle.type) && obstacle.baseX == null && hipX != null) {
        obstacle.baseX = homeX ?? hipX
        obstacle.baseShoulder = shoulderWidth
      }
      refreshDodge(obstacle)
    }

    // 1b. домашняя позиция обновляется только в спокойные моменты: пока ничего
    // не судится и человек стоит, а не приседает и не уворачивается
    if (!anyWindowOpen && hipX != null && !isDucking()) homeX = hipX

    // 2. окно зачёта: движение засчитывается, как только поза сошлась, а промах
    // объявляется, только когда окно закрылось — до этого шанс ещё есть
    for (const obstacle of obstacles) {
      if (obstacle.status !== 'incoming') continue
      if (clock < windowOpensAt(obstacle)) continue

      // даже на промахе снимаем фактические величины: по ним калибруются пороги
      if (obstacle.type === TYPE.STRIKE) {
        const punch = lastPunch[obstacle.side]
        if (punchInWindow(obstacle)) {
          obstacle.strikeMs = Math.round(punch.durationMs)
          obstacle.strikeFrom = Number(punch.fromValue.toFixed(2))
          obstacle.strikeTo = Number(punch.toValue.toFixed(2))
          // когда удар случился относительно пролёта: по этому числу видно,
          // попадает ли человек в окно вообще или бьёт мимо него
          obstacle.punchAtMs = Math.round(punch.at - obstacle.passAt)
        }
      }

      // и то же для ямы: был ли прыжок и когда именно относительно пролёта
      if (obstacle.type === TYPE.PIT && jumpInWindow(obstacle)) {
        obstacle.jumpAtMs = Math.round(lastJump.at - obstacle.passAt)
      }

      // и для волны с угольком: окна им поставлены на глаз, и снять настоящие
      // можно только по этому числу с живого раунда
      if (
        (obstacle.type === TYPE.LUNGE || obstacle.type === TYPE.HEEL) &&
        legInWindow(obstacle)
      ) {
        obstacle.legAtMs = Math.round(legEventOf(obstacle).at - obstacle.passAt)
      }

      // и для девяти новых: окна у них поставлены по аналогии с волной, то есть
      // на глаз, и снять настоящие можно только по этому числу с живого раунда
      if (MOVE_TYPES.includes(obstacle.type) && moveInWindow(obstacle)) {
        obstacle.moveAtMs = Math.round(moveEventOf(obstacle).at - obstacle.passAt)
      }

      const ok = inWindow(obstacle) && judge(obstacle)
      if (!ok && clock <= windowClosesAt(obstacle)) continue

      obstacle.status = ok ? 'cleared' : 'hit'
      obstacle.judgedAt = clock
      obstacle.angleAtPass = angle
      obstacle.hipAtPass = hipX
      /** Насколько раньше (минус) или позже (плюс) пролёта человек успел. */
      obstacle.timingMs = ok ? Math.round(clock - obstacle.passAt) : null

      if (obstacle.practice) {
        if (ok) practiceCleared += 1
      } else if (ok) cleared += 1
      else missed += 1

      // Личный максимум растёт от РЕАЛЬНОЙ игры, и на зачёте, и на промахе:
      // занизить его нельзя — можно только не показать амплитуду вовсе, а это
      // и есть честное слабое движение. Разминка считается наравне: там человек
      // двигается так же, просто очки не идут.
      observe(obstacle.type, obstacle.amplitude)
      // у выпада признака два, и растить надо оба: иначе личной становится
      // только нога, а упирается человек в таз
      if (obstacle.type === TYPE.LUNGE) observe(LUNGE_DROP, obstacle.lungeDropPeak)

      // разминка ведётся по списку движений: следующее начнётся, только когда
      // это сделано нужное число раз подряд
      if (obstacle.practice) {
        nextPracticeAt = clock + config.practiceGapMs
        advancePractice(ok, events)
      }

      events.push({
        type: ok ? 'obstacle.clear' : 'obstacle.miss',
        at: clock,
        obstacle,
        angle,
        side: obstacle.side,
        practice: obstacle.practice,
        timing: obstacle.timingMs,
        /**
         * Фактическое уклонение в ширинах плеч со знаком: плюс — ушёл от
         * препятствия, минус — в его сторону. Пишется и на зачёте, и на промахе:
         * только по этим числам видно, одинаково ли даются обе стороны.
         */
        dodge: metricOf(obstacle),
        /** Для балки — насколько при этом уехал таз (шаг вместо наклона). */
        drift: obstacle.driftK,
        /** Фактические величины движения — по ним калибруются пороги в поле. */
        strikeMs: obstacle.strikeMs,
        strikeFrom: obstacle.strikeFrom,
        strikeTo: obstacle.strikeTo,
        strikePeak: obstacle.strikePeak == null ? null : Number(obstacle.strikePeak.toFixed(2)),
        /** Насколько гулял таз за окно: по нему видно, что срезала стойка. */
        hip: obstacle.hipPeakK == null ? null : Number(obstacle.hipPeakK.toFixed(2)),
        /** Когда пришёл удар относительно пролёта — попал ли он в окно вообще. */
        punchAt: obstacle.punchAtMs,
        /** Птица: до какой высоты дотянулась рука за окно. */
        raise: obstacle.raisePeak == null ? null : Number(obstacle.raisePeak.toFixed(2)),
        /** Яма: был ли прыжок и когда он случился относительно пролёта. */
        jumped: obstacle.type === TYPE.PIT ? obstacle.jumpAtMs != null : null,
        jumpAt: obstacle.jumpAtMs,
        /**
         * Волна: оба её признака за окно — без пары этих чисел промах
         * неразбираем, потому что «не дотянул ногой» и «не сел» выглядят в
         * логе одинаково. Уголёк: до какой высоты дошла стопа.
         */
        lungeBack:
          obstacle.lungeBackPeak == null ? null : Number(obstacle.lungeBackPeak.toFixed(2)),
        lungeDrop:
          obstacle.lungeDropPeak == null ? null : Number(obstacle.lungeDropPeak.toFixed(2)),
        heelLift:
          obstacle.heelLiftPeak == null ? null : Number(obstacle.heelLiftPeak.toFixed(2)),
        /** Что могло зарезать захлёст: колено вверх, нога назад, таз вниз. */
        heelKnee:
          obstacle.heelKneePeak == null ? null : Number(obstacle.heelKneePeak.toFixed(2)),
        heelBack:
          obstacle.heelBackPeak == null ? null : Number(obstacle.heelBackPeak.toFixed(2)),
        heelDrop:
          obstacle.heelDropPeak == null ? null : Number(obstacle.heelDropPeak.toFixed(2)),
        /**
         * Сколько условие продержалось подряд и что мешало чаще прочих.
         * Пара, без которой промах движения с несколькими условиями
         * неразбираем: пики порознь не говорят, сошлись ли они в один кадр.
         */
        held: obstacle.heelHeldMs ?? obstacle.lungeHeldMs ?? obstacle.moveHeldMs ?? null,
        block: topBlock(obstacle),
        /** Когда пришло движение относительно пролёта: по нему снимаются окна. */
        legAt: obstacle.legAtMs,
        /**
         * Девять новых: до чего дотянул главный признак и когда движение
         * случилось относительно пролёта. Пара нужна и на промахе: «не дотянул»
         * и «сделал мимо окна» в логе иначе выглядят одинаково.
         */
        movePeak: obstacle.movePeak == null ? null : Number(obstacle.movePeak.toFixed(2)),
        moveAt: obstacle.moveAtMs,
        /**
         * И все его собственные признаки за окно, по именам условий: у
         * скручивания это высота колена и встречная рука. Отдельным объектом, а
         * не россыпью полей: имена у девяти повторяются (drop, kneeLift), и в
         * плоском событии они схлестнулись бы с чужими замерами.
         */
        peaks: peaksOf(obstacle),
        lift: obstacle.kneeLiftK,
        /**
         * По какой планке судили и что человек выдал. Без первого числа
         * полевой лог нечитаем: у каждого своя планка, и «не хватило 0.4» без
         * неё ничего не значит.
         */
        bar: Number(barFor(obstacle.type).toFixed(2)),
        amp: obstacle.amplitude == null ? null : Number(obstacle.amplitude.toFixed(2)),
        /** Почему промах — по этому полю в логе видно, чего не хватило. */
        reason: ok ? null : missReason(obstacle),
      })

      // следующее препятствие требует новой стойки
      stood = false
    }

    // 3. конец раунда — только по времени, другого способа его закончить нет
    if (phase === PHASE.ROUND && clock >= endAt()) {
      ended = true
      events.push({
        type: 'round.end',
        at: endAt(),
        spawned: spawnedCount,
        cleared,
        missed,
      })
    }
  }

  function applyPose(pose) {
    if (pose == null) {
      angle = null
      hipX = null
      shoulderX = null
      shoulderWidth = null
      elbow = { left: null, right: null }
      reach = { left: null, right: null }
      foreshorten = { left: null, right: null }
      armDown = { left: null, right: null }
      kneeLift = { left: null, right: null }
      footLift = { left: null, right: null }
      raise = { left: null, right: null }
      ankleY = { left: null, right: null }
      ankleDy = { left: null, right: null }
      ankleBack = { left: null, right: null }
      hipY = null
      torso = null
      moves = null
      landmarks = null
      return
    }
    angle = pose.angle ?? null
    hipX = pose.hipX ?? null
    shoulderX = pose.shoulderX ?? null
    shoulderWidth = pose.shoulderWidth ?? null
    elbow = pose.elbow ?? { left: null, right: null }
    reach = pose.reach ?? { left: null, right: null }
    foreshorten = pose.foreshorten ?? { left: null, right: null }
    armDown = pose.armDown ?? { left: null, right: null }
    kneeLift = pose.kneeLift ?? { left: null, right: null }
    footLift = pose.footLift ?? { left: null, right: null }
    raise = pose.raise ?? { left: null, right: null }
    ankleY = pose.ankleY ?? { left: null, right: null }
    ankleDy = pose.ankleDy ?? { left: null, right: null }
    ankleBack = pose.ankleBack ?? { left: null, right: null }
    hipY = pose.hipY ?? null
    torso = pose.torso ?? null
    moves = pose.moves ?? null
    // сырые точки — только ловцу; в режиме движений их никто не спрашивает
    landmarks = pose.landmarks ?? null
  }

  return {
    config,

    /**
     * Продвинуть раунд до момента now (мс от старта) с текущей позой.
     * Поза нужна именно каждый кадр: по ней судится пролёт.
     * @param {{angle: number|null, hipX: number|null, shoulderX: number|null,
     *          shoulderWidth: number|null}} pose
     */
    update(now, pose) {
      if (pose !== undefined) applyPose(pose)
      const events = []
      advance(now, events)
      return events
    },

    /** Поза отдельно — когда кадр пришёл, а часы двигать не надо. */
    setPose: applyPose,

    /** Калибровка меняет рабочие пороги прямо во время раунда. */
    setThresholds({ downAngle: down, upAngle: up } = {}) {
      if (Number.isFinite(down)) downAngle = down
      if (Number.isFinite(up)) upAngle = up
    },

    getState() {
      const practice = phase === PHASE.PRACTICE
      const live = obstacles.filter((o) => o.status === 'incoming')
      return {
        phase,
        /** Ловец на месте движений: экран по этому полю решает, что рисовать. */
        mode: catcher ? MODE.CATCH : MODE.MOVES,
        elapsedMs: Math.min(clock, endAt()),
        /** Остаток зачётной части: до её старта она ещё вся впереди. */
        remainingMs:
          phase === PHASE.ROUND
            ? Math.max(0, Math.min(config.durationMs, endAt() - clock))
            : config.durationMs,
        /** Идёт разминка — очки не начисляются, на экране крупные команды. */
        practice,
        /** Какое движение разучивается сейчас и сколько зачётов уже подряд. */
        practiceMovement: practice ? practiceOrder[practiceIndex] : null,
        practiceIndex,
        practiceTotal: practiceOrder.length,
        practiceDone,
        practiceNeeded: config.practiceNeeded,
        practiceSpawned,
        practiceCleared,
        /** Разминка пройдена, идёт отсчёт до зачётной части. */
        ready: phase === PHASE.READY,
        readyLeftMs: phase === PHASE.READY ? Math.max(0, readyAt - clock) : 0,
        ended,
        spawned: spawnedCount,
        cleared,
        missed,
        angle,
        hipX,
        duckAngle: duckAngle(),
        standAngle: upAngle,
        ducking: isDucking(),
        /**
         * Игрок засиделся: пока не встанет, следующее препятствие не
         * засчитается. У ловца анти-чита на стойку нет вовсе — его роль играет
         * правило полутора радиусов, — и требовать стойку значило бы ругать
         * человека за то, чего игра от него не просила.
         */
        mustStand: catcher ? false : !stood,

        /** 0..1 — насколько разогнан раунд. По нему же ускоряется картинка. */
        tempo: rampAt(clock),
        incoming: live,
        /**
         * Человек сейчас пойдёт к краю кадра. В режиме движений это стена, у
         * ловца — мишень под колено или стопу: они висят в полутора ширинах
         * плеч вбок, и нога уходит туда же. Экран по этому флагу перестаёт
         * считать потерю ног поводом для паузы. Балка сюда не входит: под ней
         * стоят на месте, ноги никуда не уходят.
         */
        wallIncoming: catcher
          ? live.some((o) => o.part === 'foot' || o.part === 'knee')
          : live.some((o) => o.type === TYPE.WALL),
      }
    },
  }
}
