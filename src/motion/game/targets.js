/**
 * ПОЯВЛЕНИЕ. Круг выпрыгивает с перелётом: 0 -> 1.15 -> 1.0 за четверть
 * секунды. Перелёт не украшение — он и есть то, чем появление отличается от
 * «круг просто был». Мишень живёт две с половиной секунды, и человек обязан
 * заметить её в первую десятую, а не искать глазами по экрану.
 *
 * Кривая — обычный easeOutBack; коэффициент подобран так, чтобы вершина легла
 * ровно на 1.15 (пик равен 1 + 4c³/27(c+1)²).
 */
const POP_MS = 250
const POP_BACK = 2.2
export const popAt = (ageMs) => {
  const u = clamp01(ageMs / POP_MS) - 1
  return 1 + (POP_BACK + 1) * u * u * u + POP_BACK * u * u
}

/** Скорость пульса. На последней трети жизни удваивается — см. beatAt. */
const PULSE_RATE = 0.012

/**
 * Пульс мишени. Частота удваивается на последней трети, но ФАЗА при этом не
 * рвётся: она копится, а не пересчитывается от нуля. Смени частоту в лоб — и в
 * момент перехода круг скакнёт, а скачок читается как сбой картинки, а не как
 * «время кончается».
 */
export function beatAt(clockMs, spawnAt, lifeMs, aged) {
  const urgentAt = spawnAt + lifeMs * (1 - URGENT_SHARE)
  const phase = clockMs * PULSE_RATE + Math.max(0, clockMs - urgentAt) * PULSE_RATE
  return 1 + (0.05 + 0.06 * clamp01(aged)) * Math.sin(phase)
}

/**
 * МАГНИТ. Мишень отвечает на подводимую конечность: дальше двух радиусов —
 * обычное свечение, ближе — разгорается, у самого края обводка почти белая в
 * ореоле своего цвета.
 *
 * Зачем. Судья требует времени внутри круга и молчит до самого зачёта, а
 * человек в этот момент не знает, ведёт он руку туда или мимо: круг
 * на экране и рука в двух метрах от телефона не совпадают буквально. Магнит —
 * это ответ игры «да, туда», и он приходит ДО зачёта. Судейством он при этом не
 * является ни на волос: движок присылает готовое число, а порог зачёта у него
 * свой и этой картинке не подчиняется.
 */
const MAGNET_FROM = 2
export const pullAt = (near) =>
  near == null ? 0 : clamp01((MAGNET_FROM - near) / (MAGNET_FROM - 1))

/**
 * ОРБИТА. Вокруг круга крутится пунктирное кольцо, по нему бегут три искры.
 * Живая мишень должна выглядеть живой: неподвижный круг с таймером читается как
 * элемент интерфейса, а вращение — как «работает, тикает, ждёт тебя».
 *
 * Скорость растёт на последней трети — вместе с уже сделанным учащением пульса,
 * и той же непрерывной фазой: рвани её, и кольцо дёрнется в самый заметный
 * момент. Одно движение, две скорости, ни одного скачка.
 */
const ORBIT_RATE = 0.0018
const ORBIT_URGENT = 1.4
const ORBIT_SPARKS = 3

export function spinAt(clockMs, spawnAt, lifeMs) {
  const urgentAt = spawnAt + lifeMs * (1 - URGENT_SHARE)
  return clockMs * ORBIT_RATE + Math.max(0, clockMs - urgentAt) * ORBIT_RATE * ORBIT_URGENT
}

/**
 * ЩЕЛЧОК МАСШТАБА — короткий рывок и мягкий возврат. Им отзываются серия и
 * всплывающие очки: цифра, появившаяся без рывка, глазом не ловится вовсе.
 */
export const kickAt = (ageMs, ms, power) => {
  const t = 1 - clamp01(ageMs / ms)
  return 1 + power * t * t
}

