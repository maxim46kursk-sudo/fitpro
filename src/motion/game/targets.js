const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v)
const lerp = (a, b, k) => a + (b - a) * k

/** Псевдослучайное без Math.random: картинка воспроизводима в тестах. */
function hash01(n) {
  const x = Math.sin(n * 127.1) * 43758.5453
  return x - Math.floor(x)
}

/** Тот же цвет с заданной прозрачностью. Цвета здесь только свои, шестизначные. */
function rgbaOf(hex, alpha) {
  const v = parseInt(hex.slice(1), 16)
  return `rgba(${(v >> 16) & 255}, ${(v >> 8) & 255}, ${v & 255}, ${alpha})`
}

/** Смешать два цвета: 0 — первый, 1 — второй. Цвета здесь только свои, шестизначные. */
function mixHex(from, to, k) {
  const t = clamp01(k)
  // смешивать нечего — отдаём исходный цвет ровно таким, каким он записан
  if (t <= 0) return from
  const a = parseInt(from.slice(1), 16)
  const b = parseInt(to.slice(1), 16)
  const channel = (shift) =>
    Math.round((((a >> shift) & 255) * (1 - t) + ((b >> shift) & 255) * t))
  return `rgb(${channel(16)}, ${channel(8)}, ${channel(0)})`
}

