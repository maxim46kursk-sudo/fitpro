/**
 * ЭКОНОМНЫЙ РЕЖИМ ДЕЛИТ ЭФФЕКТЫ ПО ЦЕНЕ, А НЕ ПО НОВИЗНЕ.
 *
 * Раньше он делил их по возрасту: всё новое выключалось скопом. Цена вышла
 * такая: телефон, ради которого игра и делается, выдаёт двадцать кадров в
 * секунду, то есть 50 мс на кадр при пороге включения 26 — экономный режим на
 * нём включён ПОСТОЯННО. Значит, всё, что выключено «на всякий случай»,
 * выключено навсегда и именно там, где должно работать.
 *
 * Поэтому граница проходит по настоящей стоимости кадра:
 *
 *   ОСТАЁТСЯ ВСЕГДА — то, что стоит O(1) на кадр и не плодит объектов: рывки
 *     масштаба (чистая арифметика), счётчик серии и его обрыв, орбита с
 *     искрами (одна дуга плюс три точки), кольца-волны (одна дуга), белая
 *     вспышка зачёта, виньетка (четыре полосы на три кадра).
 *
 *   ВЫКЛЮЧАЕТСЯ — то, что стоит дорого КАЖДЫЙ кадр или растёт числом объектов:
 *     shadowBlur (самая дорогая операция Canvas2D на телефоне — и магнит из-за
 *     этого показывает себя толщиной обводки), шлейфы за кистями (двенадцать
 *     отрезков на каждую руку каждый кадр), полные взрывы (остаются
 *     половинные), конфетти (шестьдесят объектов разом) и тряска.
 *
 * Правило проверяется тестом: в экономном режиме за кадр не должно быть ни
 * одного присвоения shadowBlur больше нуля, а юбилей серии не должен добавлять
 * частиц.
 */

