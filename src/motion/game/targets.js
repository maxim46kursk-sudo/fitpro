/**
 * ИДЁТ ЛИ МИШЕНЬ ЗА ТЕЛОМ — самое важное решение всей раскладки.
 *
 * Мишени под РУКУ, КОЛЕНО и СТОПУ висят на теле и едут вместе с ним: человек
 * стоит на месте, тянется к ним конечностью, и подвинуться они не мешают.
 *
 * А мишени, в которые надо попасть САМИМ ТЕЛОМ — кольцо приседа, кольцо
 * наклона, звезда прыжка, ноги врозь, — приколачиваются к месту в момент
 * появления. Иначе кольцо, привязанное к тазу, уезжает вниз ровно с той же
 * скоростью, с какой человек приседает, и дотянуться до него нельзя никогда.
 * Это ровно та ошибка, из-за которой не полетела стена с вырезом.
 */
const FOLLOWS_BODY = new Set([
  'strike',
  'bird',
  'knee',
  'legside',
  'heel',
  'wings',
  'clap',
  'twistknee',
])

/** Точки позы, которые нужны раскладке. */
const LM = {
  nose: 0,
  shoulderL: 11,
  shoulderR: 12,
  wristL: 15,
  wristR: 16,
  hipL: 23,
  hipR: 24,
  kneeL: 25,
  kneeR: 26,
  ankleL: 27,
  ankleR: 28,
}

const mid = (a, b) => ({ x: (a.x + b.x) / 2, y: (a.y + b.y) / 2 })

/**
 * Опорные точки тела в пикселях экрана.
 *
 * @param {Array} landmarks точки позы (нормированные к кадру камеры)
 * @param {{ox:number, oy:number, dw:number, dh:number}} fit куда вписан кадр
 * @returns {object|null} null — позы нет или она не читается
 */
export function readBody(landmarks, fit) {
  if (!landmarks || landmarks.length < 29 || !fit || !(fit.dw > 0)) return null
  // x зеркальный: человек видит себя в отражении
  /**
   * ТОЧКА БЕРЁТСЯ, ТОЛЬКО ЕСЛИ ОНА ВИДНА.
   *
   * Раскладка мишеней и скелета строилась по любой точке с числовыми
   * координатами — а MediaPipe отдаёт координаты всегда, достраивая то, чего в
   * кадре нет. Мишень садилась на выдуманное колено, и человек получал задачу,
   * которой не видел. isPointOk — тот же разбор, что у гейта кадра.
   */
  const at = (index) => {
    const point = landmarks[index]
    if (!point || typeof point.x !== 'number') return null
    if (!isPointOk(point, index)) return null
    return { x: fit.ox + (1 - point.x) * fit.dw, y: fit.oy + point.y * fit.dh }
  }

  const nose = at(LM.nose)
  const shoulderL = at(LM.shoulderL)
  const shoulderR = at(LM.shoulderR)
  const hipL = at(LM.hipL)
  const hipR = at(LM.hipR)
  if (!nose || !shoulderL || !shoulderR || !hipL || !hipR) return null

  const shoulder = mid(shoulderL, shoulderR)
  const hip = mid(hipL, hipR)
  const kneeL = at(LM.kneeL)
  const kneeR = at(LM.kneeR)
  const ankleL = at(LM.ankleL)
  const ankleR = at(LM.ankleR)
  const width = Math.hypot(shoulderL.x - shoulderR.x, shoulderL.y - shoulderR.y)
  const torso = Math.abs(hip.y - shoulder.y)
  if (!(width > 0) || !(torso > 0)) return null

  return {
    nose,
    shoulder,
    shoulderL,
    shoulderR,
    hip,
    hipL,
    hipR,
    // кисти нужны не раскладке, а шлейфам: по ним видно скорость своей руки.
    // Пропасть они могут в любой момент — шлейф это переживает, раскладка их
    // и не спрашивает
    wristL: at(LM.wristL),
    wristR: at(LM.wristR),
    // колени и стопы теряются чаще всего — их подменяет продолжение корпуса
    knee: kneeL && kneeR ? mid(kneeL, kneeR) : { x: hip.x, y: hip.y + torso * 1.1 },
    ankle: ankleL && ankleR ? mid(ankleL, ankleR) : { x: hip.x, y: hip.y + torso * 2.2 },
    width,
    torso,
  }
}

/**
 * СТОРОНА ДВИЖЕНИЯ -> СТОРОНА ЭКРАНА. Единственное место, где это решается.
 *
 * Полевой лог: у шага в сторону 16 промахов no-step подряд при честной
 * амплитуде до 1.7 ширины плеч — человек шагал бодро, но НЕ ТУДА. Кольцо
 * висело на стороне стены, человек шёл в него, а детектор считает зачётным
 * ровно противоположное направление. Единственный зачёт за весь заход случился,
 * когда человек шагнул мимо кольца.
 *
 * ДВА РАЗНЫХ СМЫСЛА У ОДНОГО СЛОВА `side`, и в этом вся ловушка:
 *
 *   у УДАРА, КОЛЕНА, МАХА, ПЯТКИ, СКРУЧИВАНИЯ и БОКОВОГО ВЫПАДА сторона — это
 *     РАБОЧАЯ КОНЕЧНОСТЬ человека. Видео зеркалится, поэтому его левая рука
 *     лежит слева на экране, и мишень под неё — тоже слева;
 *   у СТЕНЫ и БАЛКИ сторона — это МЕСТО ПРЕПЯТСТВИЯ на экране, а уходить от
 *     него надо в свободную сторону. Так их и рисовал прежний слой (стена на
 *     своей стороне), и так же судят детекторы: dodgeDistance при side left
 *     даёт плюс за шаг ВПРАВО по экрану, leanDistance — за наклон вправо.
 *
 * Мишень — это КУДА ИДТИ, а не где препятствие. Поэтому у стены и балки знак
 * переворачивается, а у остальных остаётся. Проверено тестом против самих
 * детекторов: см. targets.test.js.
 */
const AWAY_FROM = new Set(['wall', 'beam'])

export function screenDir(type, side) {
  const own = side === 'left' ? -1 : 1
  return AWAY_FROM.has(type) ? -own : own
}

/**
 * Насколько глубоко человек приседает — в долях расстояния «таз — колени».
 * Личная амплитуда приседа в ГРАДУСАХ (см. personal.js), и перевести её в
 * пиксели нечем: угол в колене и высота таза связаны ростом и пропорциями.
 * Поэтому она работает не как высота, а как РУЧКА: приседающему глубоко кольцо
 * ставится ниже, неглубоко — выше. Без личных данных берётся середина, ровно
 * как в макете.
 */
const squatShare = (personal) => {
  const deg = personal?.barrier
  if (!Number.isFinite(deg)) return 0.45
  return 0.3 + 0.5 * Math.max(0, Math.min(1, (deg - 30) / 50))
}

/**
 * Раскладка мишеней движения. Чистая функция: те же точки — та же картинка.
 *
 * @returns {{label:string, zone:string, follow:boolean, spots:Array}|null}
 */
export function layoutFor(type, side, body, options = {}) {
  if (!body) return null
  // сторона экрана считается ОДНИМ местом на все боковые типы: разъехавшийся
  // знак стоил шестнадцати промахов подряд
  const dir = screenDir(type, side)
  const W = body.width
  const zone = TYPE_ZONE[type] ?? 'legs'
  const label = TYPE_LABEL[type] ?? ''
  const follow = FOLLOWS_BODY.has(type)

  /**
   * МИШЕНЬ, УЕХАВШАЯ ЗА КРАЙ ЭКРАНА, — та же невидимая цель, что и раньше:
   * человек не видит, куда тянуться, и стоит.
   *
   * А уезжает она легко: боковые мишени висят в полутора ширинах плеч от тела,
   * и стоит человеку встать не по центру кадра (или кадру оказаться узким из-за
   * полей object-fit), как круг оказывается за границей. Автопрогон полного
   * раунда поймал пять таких на семидесяти препятствиях — у маха ногой, шага,
   * наклона и маха рукой.
   *
   * Поэтому мишень прижимается к краю, а не обрезается. Сторону это не меняет:
   * человек стоит посередине, и прижатый круг остаётся с той же стороны от него.
   */
  const screen = options.screen
  const fit = (spots) => {
    if (!screen?.width || !screen?.height) return spots
    for (const spot of spots) {
      const pad = spot.r + 2
      spot.x = Math.min(Math.max(spot.x, pad), screen.width - pad)
      spot.y = Math.min(Math.max(spot.y, pad), screen.height - pad)
    }
    return spots
  }
  const done = (spots) => ({ label, zone, follow, spots: fit(spots) })

  /** Круг под конечность и кольцо под тело — разные вещи и рисуются по-разному. */
  const circle = (x, y, r) => ({ kind: 'circle', x, y, r })
  const ring = (x, y, r) => ({ kind: 'ring', x, y, r })

  switch (type) {
    case 'strike':
      return done([circle(body.shoulder.x + dir * W * 1.15, body.shoulder.y + body.torso * 0.3, W * 0.4)])
    case 'bird':
      return done([circle(body.shoulder.x + dir * W * 0.95, body.nose.y - W * 0.95, W * 0.4)])
    case 'knee':
      return done([circle(body.hip.x + dir * W * 0.7, body.hip.y, W * 0.38)])
    case 'legside':
      return done([circle(body.hip.x + dir * W * 1.5, body.ankle.y - W * 0.25, W * 0.38)])
    case 'heel':
      // у ягодицы рабочей ноги: пятка идёт туда, а не вбок
      return done([circle(body.hip.x + dir * W * 0.45, body.hip.y + body.torso * 0.2, W * 0.34)])
    case 'wings':
      return done([
        circle(body.shoulder.x - W * 1.45, body.shoulder.y, W * 0.36),
        circle(body.shoulder.x + W * 1.45, body.shoulder.y, W * 0.36),
      ])
    case 'clap':
      return done([
        { kind: 'half', x: body.nose.x - W * 0.5, y: body.nose.y - W * 1.05, r: W * 0.36, dir: -1 },
        { kind: 'half', x: body.nose.x + W * 0.5, y: body.nose.y - W * 1.05, r: W * 0.36, dir: 1 },
      ])
    case 'twistknee':
      return done([circle(body.hip.x + dir * W * 0.8, body.hip.y - body.torso * 0.25, W * 0.36)])
    case 'barrier':
      return done([
        ring(body.hip.x, body.hip.y + (body.knee.y - body.hip.y) * squatShare(options.personal), W * 0.75),
      ])
    case 'lunge': {
      /**
       * Кольцо выпада стоит на СВОЕЙ просадке — той, что движок и меряет
       * (lunge-drop, в длинах корпуса). Но физически просадка выпада и глубина
       * приседа почти совпадают: на обычном человеке кольца расходятся на
       * десяток точек и выглядят одним и тем же. Поэтому кольцо выпада
       * поднимается хотя бы на свой радиус выше приседного — разные движения
       * не должны рисоваться одинаково, даже если тело в них опускается
       * одинаково.
       */
      const drop = Number.isFinite(options.personal?.['lunge-drop'])
        ? options.personal['lunge-drop']
        : 0.3
      const r = W * 0.7
      const own = body.hip.y + body.torso * Math.max(0.15, Math.min(0.6, drop))
      const squat = body.hip.y + (body.knee.y - body.hip.y) * squatShare(options.personal)
      return done([ring(body.hip.x, Math.min(own, squat - r * 0.9), r)])
    }
    case 'sidelunge':
      return done([ring(body.hip.x + dir * W * 1.5, body.hip.y + body.torso * 0.25, W * 0.7)])
    case 'wall':
      return done([ring(body.nose.x + dir * W * 1.6, body.nose.y, W * 0.62)])
    case 'beam':
      return done([ring(body.shoulder.x + dir * W * 1.6, body.shoulder.y, W * 0.6)])
    case 'bend':
      return done([ring(body.hip.x, body.knee.y, W * 0.7)])
    case 'pit':
      return done([{ kind: 'star', x: body.nose.x, y: body.nose.y - W * 1.5, r: W * 0.6 }])
    case 'hop':
      return done([
        circle(body.ankle.x - W * 1.25, body.ankle.y, W * 0.36),
        circle(body.ankle.x + W * 1.25, body.ankle.y, W * 0.36),
      ])
    case 'jack':
      // крест: две мишени под кисти над головой, две под стопы у пола
      return done([
        circle(body.shoulder.x - W * 0.85, body.nose.y - W * 1.15, W * 0.4),
        circle(body.shoulder.x + W * 0.85, body.nose.y - W * 1.15, W * 0.4),
        circle(body.ankle.x - W * 1, body.ankle.y, W * 0.4),
        circle(body.ankle.x + W * 1, body.ankle.y, W * 0.4),
      ])
    case 'jumpsquat':
      /**
       * Две половины одного движения, и вторая показывается ТОЛЬКО после
       * первой. Кольцо приседа гаснет, когда движок сказал «человек внизу»
       * (его же признак приседа, никаких своих проверок), и на его месте
       * вспыхивает звезда над головой.
       */
      return options.ducked
        ? done([{ kind: 'star', x: body.nose.x, y: body.nose.y - W * 1.5, r: W * 0.6 }])
        : done([
            ring(body.hip.x, body.hip.y + (body.knee.y - body.hip.y) * squatShare(options.personal), W * 0.75),
          ])
    default:
      return null
  }
}

