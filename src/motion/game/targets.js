/**
 * Раскладка мишени ловца. Ни одного решения о МЕСТЕ здесь не принимается: точку
 * и радиус выбрал catcher.js при появлении мишени и приколотил их — тут только
 * перевод нормированных координат в пиксели вписанного кадра.
 *
 * РАДИУС БЕРЁТСЯ МЕНЬШИЙ ИЗ ДВУХ. Судья меряет расстояние двумя разными
 * единицами — своей по горизонтали и своей по вертикали (нормированные
 * координаты анизотропны, см. catcher.js), поэтому его область на экране это
 * строго говоря эллипс. Эллипс почти круглый: обе единицы сходятся с точностью
 * до нескольких процентов, потому что вертикальная берётся из корпуса, а
 * корпус — те же полторы ширины плеч. Но «почти» надо разрешать в правильную
 * сторону, и меньший радиус — это она: нарисованный круг целиком лежит внутри
 * судейской области, то есть КАЖДОЕ видимое попадание засчитывается. Обратная
 * ошибка — круг шире судьи — это человек, попавший в мишень и не получивший
 * зачёта, а таких в этой игре быть не должно.
 *
 * @param {object} obstacle препятствие-мишень из движка (нужны spot и part)
 * @param {{ox:number, oy:number, dw:number, dh:number}} fit куда вписан кадр
 * @param {{life?:number}} options сколько жизни осталось, 0..1 — на кольцо-таймер
 */
export function catchLayout(obstacle, fit, options = {}) {
  const spot = obstacle?.spot
  if (!spot || !fit || !(fit.dw > 0) || !(fit.dh > 0)) return null
  const r = Math.min(spot.rx * fit.dw, spot.ry * fit.dh)
  if (!(r > 0)) return null
  return {
    label: PART_LABEL[obstacle.part] ?? '',
    zone: PART_ZONE[obstacle.part] ?? 'legs',
    // мишень ловца приколочена по своему устройству: за телом ей идти нечем
    follow: false,
    spots: [
      {
        kind: 'catch',
        // зеркало ровно одно и ровно здесь
        x: fit.ox + (1 - spot.x) * fit.dw,
        y: fit.oy + spot.y * fit.dh,
        r,
        life: clamp01(options.life ?? 1),
      },
    ],
  }
}

/**
 * Сколько жизни осталось у мишени, 0..1.
 *
 * Долю прожитого считает движок и кладёт прямо в мишень (`aged`) — оттуда и
 * берём: у отсуженной мишени она замирает, и таймер не доходит до конца на
 * трупе, который экран ещё дорисовывает. Часы — запасной путь, на случай если
 * мишень пришла без этого поля.
 */
export const catchLife = (obstacle, clockMs) => {
  if (Number.isFinite(obstacle?.aged)) return clamp01(1 - obstacle.aged)
  return obstacle?.lifeMs > 0 ? clamp01(1 - (clockMs - obstacle.spawnAt) / obstacle.lifeMs) : 0
}

/**
 * ПОСЛЕДНЯЯ ТРЕТЬ ЖИЗНИ — время, когда мишень начинает торопить. Треть, а не
 * половина: половина превращает тревогу в фон, и она перестаёт что-либо значить.
 */
const URGENT_SHARE = 1 / 3
export const catchUrgent = (obstacle, clockMs) => catchLife(obstacle, clockMs) <= URGENT_SHARE

