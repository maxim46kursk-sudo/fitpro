/**
 * МИШЕНИ НА ТЕЛЕ — игровой слой формата «человек — герой».
 *
 * Прежние три подхода рисовали ПРЕДМЕТ, летящий в человека: свои фигуры на
 * каждое движение, стену с вырезом, единую плиту со стрелкой. Все три требовали
 * одного и того же — сначала понять картинку, потом перевести её в движение.
 * Мишень не требует ничего: она висит там, куда надо попасть, и человек тянется
 * к ней рукой, коленом или головой, не читая ни значка, ни подписи.
 *
 * ЖЕЛЕЗНОЕ ПРАВИЛО: МИШЕНЬ — ТОЛЬКО КАРТИНКА. Ни одна проверка попадания здесь
 * не живёт и жить не может. Засчитывают движение детекторы движка — те же, что
 * и раньше, — а мишень лишь показывает, куда тянуться, и радуется вместе с
 * человеком, когда движок сказал «зачёт». Стоит завести здесь свою проверку —
 * и в игре появятся два судьи с разными мнениями, а человек будет видеть
 * попадание там, где ему не засчитали.
 *
 * Отсюда же и вся неточность мишеней: они стоят ПРИМЕРНО там, где нужное
 * движение проходит. Промахнуться мимо круга и получить зачёт — нормально;
 * попасть в круг и не получить — тоже (значит, движок не увидел амплитуды).
 * Мишень — приглашение, а не замок.
 *
 * КАРТИНКА И ЭФФЕКТЫ портированы с docs/design/juice-live.html: шлейфы за
 * кистями, взрыв частиц и кольцо-волна на зачёте, всплывающие очки, лёгкая
 * тряска слоя, конфетти за серию.
 *
 * ЗЕРКАЛО. Видео показывается зеркально (в CameraView обёртка scaleX(-1)), а
 * этот слой рисуется поверх без зеркала — поэтому x точки берётся как (1 - x).
 * Ошибись здесь знаком, и все боковые мишени окажутся не с той стороны.
 *
 * ЛОВЕЦ МИШЕНЕЙ. У его мишени места на теле нет вовсе: catcher.js выбрал точку
 * при появлении и приколотил её, а сюда она приходит готовой, в нормированных
 * координатах. Здесь остаётся один перевод в пиксели — тот же (1 - x), — круг
 * того же стиля, крупная подпись части тела под ним и кольцо-таймер по
 * окружности. Железное правило файла от этого только твёрже: судит catcher.js
 * в движке, здесь картинка.
 */

