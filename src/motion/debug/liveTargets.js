/**
 * ЧТО СЕЙЧАС ВИСИТ НА ЭКРАНЕ — наружу, только для отладки.
 *
 * Зачем. Виртуальный тестировщик (`tools/motion-persona/`) прогоняет полную
 * сессию в настоящем браузере через весь конвейер. Одного ему не хватало:
 * ЗРЕНИЯ. Какая мишень висит прямо сейчас, во время боя нарисовано на холсте —
 * ни в разметке, ни в журнале этого нет, и прочитать это так же, как читает
 * человек, неоткуда. Персонаж бил вслепую и добирал 8% зачётов против 57% в
 * поле; сцена в бою стояла почти пустая, а значит отрисовка и эффекты
 * попадания прогоном не проверялись вовсе.
 *
 * ПОЧЕМУ ЭТО НЕ «ЕЩЁ ОДИН ХУК В ГОРЯЧЕМ ЦИКЛЕ». Требование к цене жёсткое: при
 * выключенной отладке в цикле боя не должно происходить НИЧЕГО — ни выделений,
 * ни копий, ни даже чтения полей мишени. Поэтому:
 *
 *   1. решение принимается ОДИН РАЗ при загрузке модуля (`TARGETS_LIVE`), а не
 *      на каждом кадре: адресная строка за время боя не меняется;
 *   2. `publishTargets` при выключенном флаге выходит первой строкой, не
 *      прикоснувшись к аргументу — это проверено тестом через Proxy, который
 *      считает КАЖДОЕ обращение к списку, включая `length` и перебор;
 *   3. зовущая сторона к тому же обёрнута в `if (TARGETS_LIVE)`, так что в
 *      боевом заходе не делается и самого вызова.
 *
 * ЧИТАТЬ — ТОЛЬКО ЧИТАТЬ. Наружу уходит копия нужных полей, а не живой объект
 * движка: отдай мы ссылку на `round.incoming`, и любой, кто её взял, мог бы
 * подвинуть мишень или отсудить её сам. Копия стоит выделения на кадр, но
 * платится оно исключительно в отладочном заходе.
 */

import { DEBUG_PARAM } from './debugParam.js'

/**
 * Включена ли публикация. Читается один раз на загрузку модуля.
 *
 * Правило то же, что у диагностической панели: `?motion-debug=0` выключает
 * явно, наличие ключа или хеш — включают. Разойдись эти два правила, и панель
 * с публикацией открывались бы разными ключами.
 */
function readFlag() {
  try {
    const search = new URLSearchParams(globalThis.location?.search || '')
    const hash = (globalThis.location?.hash || '').toLowerCase()
    if (search.get(DEBUG_PARAM) === '0') return false
    return search.has(DEBUG_PARAM) || hash.includes(DEBUG_PARAM)
  } catch {
    return false
  }
}

export const TARGETS_LIVE = readFlag()

/** Пустой снимок — общий на все выключенные заходы, чтобы не плодить объекты. */
const EMPTY = Object.freeze({ clockMs: 0, mode: null, targets: Object.freeze([]) })

let snapshot = EMPTY

/**
 * Опубликовать то, что висит на экране.
 *
 * @param {number} clockMs часы раунда — по ним видно, сколько мишени осталось
 * @param {string} mode 'catch' | 'moves' — чем вообще занят раунд
 * @param {Array<object>} incoming живые препятствия из состояния движка
 */
export function publishTargets(clockMs, mode, incoming) {
  // ПЕРВОЙ СТРОКОЙ И ДО ЛЮБОГО ОБРАЩЕНИЯ К АРГУМЕНТАМ
  if (!TARGETS_LIVE) return

  const targets = []
  if (Array.isArray(incoming)) {
    for (const o of incoming) {
      targets.push({
        id: o.id,
        type: o.type,
        // у ловца мишень называет часть тела и висит в нормированных
        // координатах кадра; у движений этих полей нет вовсе
        part: o.part ?? null,
        side: o.side ?? null,
        spot: o.spot ? { x: o.spot.x, y: o.spot.y, rx: o.spot.rx, ry: o.spot.ry } : null,
        spawnAt: o.spawnAt,
        passAt: o.passAt,
        practice: !!o.practice,
      })
    }
  }
  snapshot = { clockMs, mode, targets }
}

/** Последний опубликованный снимок. При выключенной отладке всегда пустой. */
export function readTargets() {
  return snapshot
}

/**
 * Забыть снимок при закрытии раздела.
 *
 * Мишени прошлого боя, оставшиеся в модульной переменной, — это не только
 * лишняя память: следующий заход прочитал бы их как «на экране что-то висит»
 * ещё до первого кадра.
 */
export function resetLiveTargets() {
  snapshot = EMPTY
}
