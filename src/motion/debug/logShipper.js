/**
 * Отправка лога с телефона туда, где его читают.
 *
 * Зачем: приложение работает на телефоне, разбор — на компьютере, и между ними
 * нет ничего. Каждый круг отладки упирался в то, что с устройства не доходило
 * ни одной цифры, и правки делались на угад.
 *
 * Как: строки копятся в буфер и раз в пару секунды уходят POST-запросом. Куда
 * именно — решает среда (см. ниже): на дев-сервере в файл, на проде в вывод
 * serverless-функции. Приёмник не ответил — отправка молча выключается, и лог
 * остаётся в буфере, откуда его забирает кнопка выгрузки в панели.
 */

/**
 * КУДА СЛАТЬ. Два приёмника, и оба настоящие:
 *
 *   на дев-сервере — `/__log`, обработчик в vite.config.js дописывает строки
 *     прямо в logs/ на компьютере разработчика;
 *   на проде — `/api/log`, serverless-функция Vercel (api/log.js), печатающая
 *     строки в свой вывод.
 *
 * Раньше приёмник был один, дев-серверный, и на проде отправка молча
 * выключалась: лог с телефона доезжал только выгрузкой файлом через кнопку в
 * панели. После полевой сессии стало ясно, чего это стоит — до разбора доезжает
 * то, что человек догадался сохранить, а не то, что случилось.
 */
const DEV_ENDPOINT = '/__log'
const PROD_ENDPOINT = '/api/log'

/**
 * ПРИЁМНИК ЗАДАЁТ ХОЗЯИН. У Motion в своём проекте он свой (дев-сервер и
 * serverless-функция), внутри FitPro — ветка ручки, которая требует токен
 * вошедшего человека.
 *
 * Модуль про хозяина ничего не знает и знать не должен: импортируй он здесь
 * клиент Supabase из FitPro — и папку src/motion нельзя было бы больше
 * копировать целиком. Поэтому адрес и добыча токена приходят снаружи одним
 * вызовом, а без него всё работает ровно как раньше.
 */
let endpointOverride = null
let getToken = null
/**
 * КАК ЧАСТО УХОДИТ БУФЕР. Десять секунд.
 *
 * Число упирается в лимит запросов приёмника. Внутри FitPro ветка приёма живёт
 * в set-exercise.js, и перед ней стоит общий rateLimit на тридцать запросов в
 * минуту ПО IP, общий с тренерскими действиями: отправка раз в две секунды —
 * это ровно весь лимит, и два телефона в одной квартире пробивают его
 * гарантированно. Первым при этом отвалился бы не лог, а работа тренера.
 *
 * Десять секунд дают шесть запросов в минуту на телефон. Сверх того у ветки
 * есть СВОЙ лимит по userId, а не по адресу, — квартира с двумя телефонами
 * больше никого не задевает.
 *
 * Буфер на шестьсот строк десять секунд переживает с запасом. Хвост не
 * теряется: уход со страницы и закрытие раздела отдают накопленное сами
 * (см. attachLogShipper и lifecycle.js).
 */
const FLUSH_MS = 10000
/**
 * ПАДЕНИЕ МИНУТУ НЕ ЖДЁТ. Строка `client.error` — единственное, ради чего лог
 * упавшей сессии вообще читают, а до следующих часов вкладка может не дожить:
 * человек, увидевший карточку падения, закрывает её.
 *
 * Три секунды, а не мгновенно: падение в цикле отрисовки приходит пачкой, и
 * мгновенная отправка сделала бы из одной посылки десяток — то есть ровно то, от
 * чего минутный буфер и защищает. За три секунды пачка складывается в одну.
 */
const ERROR_FLUSH_MS = 3000
/**
 * Сколько строк держит буфер. Число важно только когда отправка НЕ работает
 * (приложение открыто не с дев-сервера): тогда весь лог сессии копится здесь и
 * выгружается кнопкой. Двадцать минут сессии — это 240 снимков состояния, и
 * прежних двухсот строк не хватало на них одних.
 */
const MAX_BUFFER = 600

/**
 * МАССОВЫЕ ВИДЫ СОБЫТИЙ — те, которых за сессию сотни, и потерять любое из них
 * не жалко: снимок состояния раз в пять секунд и каждый зачёт с промахом.
 *
 * Полевой лог сессии: начало обрезано, и весь силовой блок приседа пропал из
 * него целиком — вместе с block.start, всеми block.attempt и block.end. То
 * есть ровно те строки, ради которых диагностика и писалась, вытеснил поток
 * снимков и зачётов. Поэтому переполнение теперь выбрасывает СНАЧАЛА массовое,
 * а редкие события блоков и старта сессии остаются, сколько бы ни шло игры.
 */
const BULK_TAGS = new Set(['snapshot', 'game.clear', 'game.miss'])

/**
 * СОБЫТИЯ-ОТКЛОНЕНИЯ (render.cheap, audio.blocked, page.hidden, wakelock.lost/paused,
 * orientation.change, camera.degraded) в массовые НЕ входят — они и есть то,
 * ради чего лог читают. Захлебнуться ими нельзя по построению: каждое пишет
 * только ПЕРЕХОД, а не состояние, и либо один раз за сессию (audio.blocked),
 * либо не чаще раза в несколько секунд (createTransitionLog ниже). Худший
 * мыслимый случай — телефон, который двадцать минут скачет через порог
 * экономного режима: это 240 строк при буфере в 600, и вытеснит он сначала
 * снимки и зачёты, а не сам себя.
 */

/**
 * ЧТО НЕ ВЫТЕСНЯЕТСЯ НИКОГДА. Ошибка клиента — единственное событие, ради
 * которого лог вообще стоит читать в тот день, когда приложение упало. Всё
 * остальное описывает, как человек играл; это описывает, почему он играть не
 * смог, и потерять его из-за потока снимков состояния — потерять весь смысл
 * телеметрии.
 *
 * Беречь их можно только потому, что их мало: errorReporter не пишет повторы
 * одного падения и держит потолок в двадцать ошибок за сессию. Без потолка
 * ошибка в цикле отрисовки забила бы буфер собой за десять секунд, и защита
 * сработала бы против лога.
 */
/**
 * Жалоба человека здесь по той же причине, что и ошибка клиента, только повод
 * сильнее: её отправил ЖИВОЙ ЧЕЛОВЕК, нажав кнопку, и потерять её — значит
 * ответить молчанием на единственное обращение, которое он вообще сделал.
 * Заодно попадание в этот список торопит отправку: жалоба уезжает секундами, а
 * не через полный интервал, — человек в этот момент ещё смотрит на экран.
 */
const KEEP_TAGS = new Set(['client.error', 'user.report'])

let sessionId = makeSessionId()
let buffer = []
let timer = null
/** Отложенная отправка уже срочная — второй раз торопить её нечем. */
let timerUrgent = false
let failed = false
let enabled = detectEnabled()
/** Снять слушатели ухода со страницы. null — они не повешены. */
let detach = null

function makeSessionId() {
  const d = new Date()
  const pad = (n) => String(n).padStart(2, '0')
  const stamp = `${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}-${pad(d.getHours())}${pad(d.getMinutes())}${pad(d.getSeconds())}`
  return `session-${stamp}`
}

/** Идёт ли разработка. Обёрнуто: import.meta.env есть не в каждой среде. */
function isDev() {
  try {
    return !!import.meta.env?.DEV
  } catch {
    return false
  }
}

/** Приёмник по среде: на деве свой, на проде свой. */
export function logEndpoint() {
  if (endpointOverride) return endpointOverride
  return isDev() ? DEV_ENDPOINT : PROD_ENDPOINT
}

/**
 * Отправка включена там, где есть приёмник.
 *
 * ПРИЁМНИК ЗАДАЁТСЯ СБОРКОЙ. В своём проекте Motion он есть всегда: на
 * дев-сервере это `/__log`, на проде — serverless-функция. Внутри FitPro его
 * пока нет ВОВСЕ, и отправка означала бы 404 на каждую посылку — не «тихо не
 * работает», а регулярный мусор в консоли и в логах сервера у живых людей.
 *
 * Поэтому отправка ВЫКЛЮЧЕНА, пока её явно не включили: `VITE_MOTION_LOG=1`.
 * Умолчание именно такое, а не наоборот, по одной причине — переменные окружения
 * на Vercel живут в панели проекта, а не в репозитории. Умолчание «включено»
 * означало бы, что забытая настройка сыплет 404 у живых людей; умолчание
 * «выключено» означает, что забытая настройка молчит. Из двух ошибок выбираем
 * ту, которую видно нам, а не пользователю.
 *
 * Заглушки-приёмника при этом не заводится: пустая ручка, отвечающая 204, — тот
 * же мусор, только молчаливый. Журнал включится, когда переедет в Supabase
 * (этап 2 переезда).
 *
 * Ключ `?log=0` остаётся: он нужен на случай, когда лог мешает замеру (например,
 * при подсчёте кадров) или когда сеть плохая и запросы её добивают.
 */
function detectEnabled() {
  /**
   * Настроенный хозяином приёмник главнее любых умолчаний — и проверяется
   * ПЕРВЫМ. Иначе сброс состояния на открытии раздела (resetLogShipper) гасил
   * бы отправку сразу после того, как хозяин её включил: порядок двух вызовов
   * решал бы, работает журнал или нет.
   */
  if (endpointOverride) return true
  try {
    if (import.meta.env?.VITE_MOTION_LOG !== '1') return false
  } catch {
    // сборочной настройки нет вовсе (тесты, воркер) — решает адрес ниже
  }
  try {
    const params = new URLSearchParams(globalThis.location?.search || '')
    if (params.get('log') === '0') return false
    return true
  } catch {
    // адреса нет вовсе (тесты, воркер) — слать некуда и незачем
    return false
  }
}

/**
 * Настроить отправку под хозяина.
 *
 * @param {object} options
 * @param {string} [options.endpoint] куда слать вместо умолчания
 * @param {() => Promise<string|null>} [options.token] как добыть токен
 * @returns {() => void} снять настройку (нужно тестам и закрытию раздела)
 */
export function configureLogShipper({ endpoint = null, token = null } = {}) {
  endpointOverride = endpoint
  getToken = token
  /**
   * Настроенный приёмник — сам по себе разрешение слать: хозяин не стал бы его
   * задавать, если бы принимать было некому. Иначе включение пришлось бы
   * дублировать переменной окружения, а она живёт в панели Vercel отдельно от
   * кода, и забыть её ничего не стоит.
   */
  if (endpoint) enabled = true
  return () => {
    endpointOverride = null
    getToken = null
  }
}

export function isShipping() {
  return enabled && !failed
}

export function logSessionId() {
  return sessionId
}

/**
 * СОБЫТИЕ-ПЕРЕХОД: пишется смена состояния, а не само состояние.
 *
 * Зачем отдельный помощник. Экономный режим боя, ориентация экрана, видимость
 * вкладки — всё это проверяется каждый кадр, и записывать их «как есть» значит
 * забить лог одинаковыми строками. Записывать надо момент, когда стало иначе.
 *
 * Дребезг гасится паузой: состояние на границе порога скачет туда-сюда, и без
 * паузы лог получил бы ту же простыню, только из чередующихся строк. Пока пауза
 * не вышла, переход не пишется И НЕ ЗАПОМИНАЕТСЯ — то есть скачок «туда и
 * обратно» внутри паузы не оставляет следа вовсе, а устойчивая смена
 * записывается сразу, как только пауза истекла.
 *
 * @param {number} gapMs сколько молчать после записи
 * @returns {(tag: string, state: any, data?: object, now?: number) => boolean}
 */
export function createTransitionLog(gapMs = 0) {
  let current
  let lastAt = -Infinity

  return function note(tag, state, data, now = Date.now()) {
    if (state === current) return false
    if (now - lastAt < gapMs) return false
    current = state
    lastAt = now
    logEvent(tag, data)
    return true
  }
}

/** Одна строка лога. Дёшево: форматирование и push в массив. */
export function logEvent(tag, data) {
  const line = `${new Date().toISOString()} [${tag}] ${format(data)}`
  buffer.push({ tag, line })
  if (buffer.length > MAX_BUFFER) evict()
  if (!enabled || failed) return

  /**
   * Падение ТОРОПИТ уже заведённые часы, а не заводит вторые: иначе минутный
   * таймер остался бы висеть и отправил бы пустой буфер следом за срочным.
   *
   * Уже срочные часы не перезаводятся: пачка одинаковых падений иначе отодвигала
   * бы отправку каждой следующей строкой — то есть срочность отменяла бы саму
   * себя ровно в том случае, ради которого заведена.
   */
  const urgent = KEEP_TAGS.has(tag)
  if (urgent && timer && !timerUrgent) {
    clearTimeout(timer)
    timer = null
  }
  if (!timer) {
    timerUrgent = urgent
    timer = setTimeout(flush, urgent ? ERROR_FLUSH_MS : FLUSH_MS)
  }
}

/**
 * Освободить место под новую строку. Порядок жертв — от самого дешёвого:
 *
 *   сначала самое старое МАССОВОЕ событие (снимки, зачёты, промахи);
 *   потом самое старое обычное — события блоков и сессии дороже, но переживают
 *     переполнение только пока есть что выбросить вперёд них;
 *   ошибки клиента не выбрасываются вовсе.
 *
 * Последняя строка — страховка памяти, а не сценарий: чтобы до неё дошло, весь
 * буфер должен состоять из шестисот ошибок, а их за сессию не больше двадцати.
 * Без неё буфер рос бы без предела, и лог съел бы телефон.
 */
function evict() {
  const bulk = buffer.findIndex((entry) => BULK_TAGS.has(entry.tag))
  if (bulk >= 0) {
    buffer.splice(bulk, 1)
    return
  }
  const plain = buffer.findIndex((entry) => !KEEP_TAGS.has(entry.tag))
  buffer.splice(plain >= 0 ? plain : 0, 1)
}

function format(data) {
  if (data == null) return ''
  if (typeof data === 'string') return data
  try {
    return JSON.stringify(data)
  } catch {
    return String(data)
  }
}

/** Всё, что накопилось, — текстом. Пригодится и для выгрузки файлом. */
export function getShippedText() {
  return buffer.map((entry) => entry.line).join('\n')
}

export async function flush() {
  // Отложенная отправка больше не нужна: то, чего она ждала, уходит прямо
  // сейчас. Без снятия таймер доживал бы до закрытия раздела и стрелял уже в
  // чужом приложении.
  if (timer) clearTimeout(timer)
  timer = null
  timerUrgent = false
  if (!enabled || failed || buffer.length === 0) return

  const sent = buffer
  buffer = []

  try {
    const body = JSON.stringify({ session: sessionId, lines: sent.map((e) => e.line) })
    // Именно fetch, а не sendBeacon: beacon возвращает true даже когда
    // эндпоинта нет, и на Vercel мы бы вечно слали запросы в пустоту.
    // По ответу видно, что сервер приёма отсутствует, и отправка выключается.
    /**
     * Токен добывается ПЕРЕД отправкой, а не при настройке: он живёт около часа
     * и обновляется сам, а раздел человек держит открытым дольше. Взятый один
     * раз, он протух бы посреди тренировки, и приёмник ответил бы 401 — то есть
     * лог выключился бы навсегда ровно в середине сессии.
     */
    const auth = getToken ? await getToken() : null
    const response = await fetch(logEndpoint(), {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        ...(auth ? { Authorization: `Bearer ${auth}` } : {}),
      },
      body,
      keepalive: true,
    })
    if (!response.ok) throw new Error(`HTTP ${response.status}`)
  } catch {
    // сервера нет (открыто с Vercel) — молча выключаемся, лог остаётся
    // в буфере и доступен кнопкой выгрузки в панели
    failed = true
    buffer = sent.concat(buffer)
    while (buffer.length > MAX_BUFFER) evict()
  }
}

/**
 * СЛУШАТЕЛИ УХОДА СО СТРАНИЦЫ — теперь по вызову, а не при импорте модуля.
 *
 * Раньше они вешались на window прямо при загрузке файла и не снимались никогда.
 * Пока Motion был всем приложением, это было честно: страница закрывается вместе
 * с ним. Внутри FitPro это два слушателя, которые переживают закрытие раздела и
 * висят на чужом приложении до конца его жизни — а ленивый чанк Motion, единожды
 * загруженный, из памяти уже не уходит.
 *
 * @returns {() => void} снять слушатели; повторный вызов attach вернёт тот же
 *   деинсталлятор, то есть двойное открытие не удваивает подписку
 */
export function attachLogShipper() {
  if (detach) return detach
  if (typeof window === 'undefined') return () => {}

  const onPageHide = () => flush()
  const onVisibility = () => {
    if (document.visibilityState === 'hidden') flush()
  }

  window.addEventListener('pagehide', onPageHide)
  window.addEventListener('visibilitychange', onVisibility)

  detach = () => {
    detach = null
    window.removeEventListener('pagehide', onPageHide)
    window.removeEventListener('visibilitychange', onVisibility)
  }
  return detach
}

/**
 * Забыть накопленное и начать новую сессию лога.
 *
 * Ключевое здесь — `failed`. Он выставляется навсегда при первой же неудачной
 * отправке, и это правильно, пока «навсегда» кончается перезагрузкой страницы.
 * Внутри FitPro перезагрузки нет: одна потерянная сеть в первом заходе выключила
 * бы отправку лога до конца дня, и все следующие тренировки этого человека
 * никуда бы не доехали. Новое открытие раздела — новая сессия и новая попытка.
 *
 * Отложенная отправка гасится здесь же: таймер, доживший до закрытия, выстрелил
 * бы уже в чужом приложении.
 */
export function resetLogShipper() {
  if (timer) clearTimeout(timer)
  timer = null
  timerUrgent = false
  buffer = []
  failed = false
  enabled = detectEnabled()
  sessionId = makeSessionId()
}
