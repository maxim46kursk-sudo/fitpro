/**
 * СКОЛЬКО ИДЁТ ПУТЬ ОТ «РУКА В КРУГЕ» ДО КАДРА СО ВЗРЫВОМ — только для отладки.
 *
 * Зачем. Жалоба владельца звучит так: «мишени взрываются с запаздыванием».
 * Разбор по стадиям в проекте есть (`stageMeter.js`), но он отвечает на другой
 * вопрос — сколько стоит КАЖДАЯ стадия по отдельности. Между стадиями есть
 * ожидания, и именно они складываются в то, что человек видит глазами:
 *
 *   захват кадра ──► результат модели ──► тик игрового цикла ──► показ
 *
 * Ни одно из трёх ожиданий длительностью стадии не измеряется. Кадр может
 * считаться 40 мс и ещё 60 мс пролежать в очереди; судейство может стоить 2 мс,
 * а прождать тика цикла 16; показ синхронного режима вообще ЖДЁТ НАРОЧНО, пока
 * до события доедет картинка (см. pose/frameSync.js). Сложить их в голове
 * нельзя — надо мерить сквозным путём одного попадания.
 *
 * ЧТО СЧИТАЕТСЯ НАЧАЛОМ. Время ЗАХВАТА того кадра, по которому мишень
 * засчитана: на этом кадре рука уже в круге. Физически она вошла в круг
 * где-то между предыдущим кадром и этим, поэтому вместе с записью хранится и
 * промежуток между замерами — на него настоящее начало и «размазано».
 *
 * ЦЕНА ПРИ ВЫКЛЮЧЕННОЙ ОТЛАДКЕ — НОЛЬ, по тем же правилам, что у liveTargets.js:
 * решение принимается один раз при загрузке модуля, `noteHit` выходит первой
 * строкой, не прикоснувшись к аргументу, а зовущая сторона обёрнута в проверку
 * той же константы.
 *
 * СУДЕЙСТВА ЭТО НЕ КАСАЕТСЯ ВООБЩЕ. Здесь только часы: ни одного решения о
 * зачёте, ни одного порога, ни одной величины, которая уходила бы в очки.
 */

import { DEBUG_PARAM } from './debugParam.js'

function readFlag() {
  try {
    const search = new URLSearchParams(globalThis.location?.search || '')
    const hash = (globalThis.location?.hash || '').toLowerCase()
    if (search.get(DEBUG_PARAM) === '0') return false
    return search.has(DEBUG_PARAM) || hash.includes(DEBUG_PARAM)
  } catch {
    return false
  }
}

/** Меряем ли путь попадания. Читается один раз на загрузку модуля. */
export const HITS_TIMED = readFlag()

/**
 * Потолок числа записей. Сессия — это восемь боёв по полторы минуты и до
 * сотни зачётов в каждом; тысяча с запасом покрывает семь кругов, а расти
 * бесконечно измерителю нельзя даже в отладочном заходе.
 */
const MAX = 4000

const hits = []

/**
 * Записать путь одного попадания.
 *
 * @param {object} rec
 * @param {number} rec.cycle    номер круга сессии — по нему сравнивают начало и конец
 * @param {number} rec.poseAt   когда захвачен кадр, по которому засчитали
 * @param {number} rec.gotAt    когда результат модели вернулся в приложение
 * @param {number} rec.judgeAt  когда движок выдал событие зачёта
 * @param {number} rec.shownAt  когда взрыв реально поставлен на сцену
 * @param {number} rec.gapMs    промежуток до предыдущего результата модели
 * @param {string} [rec.mode]   режим показа: sync — картинка ждёт, live — нет
 */
export function noteHit(rec) {
  // ПЕРВОЙ СТРОКОЙ И ДО ЛЮБОГО ОБРАЩЕНИЯ К АРГУМЕНТУ
  if (!HITS_TIMED) return
  if (hits.length >= MAX) return
  hits.push({
    cycle: rec.cycle ?? 0,
    // Время храним промежутками, а не метками: метки — это чужие часы, и
    // сравнивать их между прогонами нельзя, а промежутки сравнимы всегда.
    замер: Math.round((rec.gotAt - rec.poseAt) * 10) / 10,
    судейство: Math.round((rec.judgeAt - rec.gotAt) * 10) / 10,
    показ: Math.round((rec.shownAt - rec.judgeAt) * 10) / 10,
    всего: Math.round((rec.shownAt - rec.poseAt) * 10) / 10,
    промежуток: Math.round((rec.gapMs ?? 0) * 10) / 10,
    режим: rec.mode ?? null,
  })
}

/** Всё, что накопилось. Копия, а не живой массив. */
export function readHits() {
  return hits.slice()
}

export function resetHits() {
  hits.length = 0
}
