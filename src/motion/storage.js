/**
 * ЕДИНСТВЕННАЯ ДВЕРЬ В ХРАНИЛИЩЕ УСТРОЙСТВА.
 *
 * Зачем модуль, если `localStorage.getItem` и так работает. Затем, что ключей
 * девять, а мест, где они читаются, было девять же — каждое со своим try/catch,
 * своим разбором JSON и своим ответом на «а если приватный режим Safari». Пока
 * Motion живёт один, это просто повтор; внутри FitPro это три отдельные задачи,
 * и все три упираются в отсутствие списка:
 *
 *   выход из аккаунта обязан стирать данные Motion — а `clearFitproData()`
 *     фильтрует по `fitpro_` через подчёркивание и мимо `fitpro-motion.` через
 *     дефис проходит насквозь (на этом уже обожглись с `fitpro-auth`);
 *   выгрузка и удаление аккаунта должны знать, что вообще лежит на устройстве;
 *   прогресс переезжает в базу — и подменить придётся ОДИН слой, а не девять
 *     разрозненных try/catch.
 *
 * ЧТО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он не меняет ни ключей, ни формы записей, ни
 * синхронности чтения. Асинхронное чтение и сервер как источник правды — этап 3
 * переезда, и делать его заодно значит смешать переезд с рефакторингом: если
 * после этапа 0 хоть один день челленджа прочитается иначе, разбираться придётся
 * сразу в двух изменениях. Поэтому здесь ровно то же поведение, включая ответы
 * на исключения: чтение упало — значит «данных нет», запись упала — значит
 * молча живём дальше.
 */

/**
 * Общий префикс. Через ДЕФИС, и это не опечатка: у FitPro ключи через
 * подчёркивание (`fitpro_role`), и различие — единственное, что мешает его
 * уборщику снести данные Motion заодно. Менять префикс нельзя: он уже лежит на
 * телефонах участников.
 */
export const PREFIX = 'fitpro-motion.'

/**
 * ВСЁ, ЧТО MOTION ХРАНИТ НА УСТРОЙСТВЕ. Один список — одно место, куда смотреть,
 * когда спрашивают «что останется после человека».
 */
export const KEYS = {
  /** тумблер звука: '1' | '0' */
  audio: `${PREFIX}audio.v1`,
  /** выбранная камера: строка deviceId */
  cameraDevice: `${PREFIX}camera.deviceId.v1`,
  /** прогресс челленджа: {day, done[]} */
  challenge: `${PREFIX}challenge.v1`,
  /** попытки по дням: {days: {"1": {...}}} */
  challengeAttempts: `${PREFIX}challenge.attempts.v1`,
  /** челлендж открыт кодом: '1' */
  challengeUnlocked: `${PREFIX}challenge.unlocked.v1`,
  /**
   * ПОЗДРАВЛЕНИЕ С ПОКУПКОЙ УЖЕ ПОКАЗЫВАЛИ — id потока строкой.
   *
   * Оплата это СОБЫТИЕ, а не состояние: полоса «оплата прошла» имеет право
   * появиться в комнате один раз, в первый заход после покупки. Раньше она
   * была целым экраном и висела все тридцать дней — человек с идущим потоком
   * каждый день читал новость про деньги вместо своего дня.
   *
   * Хранится id потока, а не «да/нет»: в следующем потоке поздравление
   * законно появится снова.
   */
  challengeGreeted: `${PREFIX}challenge.greeted.v1`,
  /** панель диагностики была открыта: '1' */
  debugOpen: `${PREFIX}debug.open.v1`,
  /** лучший счёт: число строкой */
  best: `${PREFIX}game.best.v1`,
  /** личные максимумы амплитуд: {version, max} */
  personal: `${PREFIX}game.personal.v1`,
  /** пороги судейства: объект углов */
  thresholds: `${PREFIX}thresholds.v2`,
  /**
   * ЧЕЙ ЭТО КЭШ. Не данные игры, а служебная отметка: чей прогресс лежит на
   * устройстве сейчас.
   *
   * Нужна из-за того, что телефон бывает общим. Ключи Motion переживают выход из
   * аккаунта — уборщик FitPro фильтрует по `fitpro_` через подчёркивание, а у
   * нас префикс через дефис, — и без этой отметки второй человек на том же
   * телефоне открыл бы раздел с чужим прогрессом: чужой день, чужие рекорды,
   * чужие попытки. Отметка сверяется на входе, и несовпадение стирает кэш.
   */
  owner: `${PREFIX}owner.v1`,
}

/**
 * ЧТО ЖИВЁТ НА СЕРВЕРЕ, А ЧТО ОСТАЁТСЯ НА УСТРОЙСТВЕ.
 *
 * Правило простое: свойства ЧЕЛОВЕКА едут в базу, свойства ТЕЛЕФОНА остаются
 * здесь. Выбранная камера, тумблер звука и память отладочной панели — это про
 * конкретный аппарат: переносить их на другой телефон бессмысленно, а иногда и
 * вредно (deviceId чужой камеры там просто не существует).
 */
export const SYNCED_KEYS = [
  KEYS.challenge,
  KEYS.challengeAttempts,
  KEYS.challengeUnlocked,
  KEYS.best,
  KEYS.personal,
  KEYS.thresholds,
]

/** Ключи, которые остаются на устройстве и в базу не едут. */
/**
 * challengeGreeted здесь, а не в SYNCED_KEYS: «эту полосу тут уже показывали» —
 * свойство экрана, а не человека. Цена ошибки в худшую сторону — одна лишняя
 * строка на втором устройстве, и она дешевле лишнего поля в общем прогрессе.
 */
export const DEVICE_KEYS = [KEYS.audio, KEYS.cameraDevice, KEYS.debugOpen, KEYS.challengeGreeted]

/**
 * Ключи, которые Motion БОЛЬШЕ НЕ ЧИТАЕТ, но которые лежат на устройствах.
 * Здесь они затем же, зачем KEYS: уборка обязана снести и их, иначе «удалить мои
 * данные» оставит на телефоне запись о тренировках.
 */
export const LEGACY_KEYS = [
  // формат до челленджа: результат дня по дате, а не по номеру дня
  `${PREFIX}game.day.v1`,
]

/** Всё, что принадлежит Motion. Для уборки при выходе из аккаунта. */
export function allKeys() {
  return [...Object.values(KEYS), ...LEGACY_KEYS]
}

/**
 * ХРАНИЛИЩЕ В ПАМЯТИ — для гостя без аккаунта.
 *
 * Гость пробует всё, но следа не оставляет: сохранность обещает аккаунт, и
 * только он. Прежде его попытки, черновик и снимок незавершённой сессии
 * ложились в те же ключи, что у участника челленджа, — и на общем телефоне
 * следующий человек открывал раздел с чужим прогрессом, а сам гость видел
 * «сохранённое», которое держалось на одном браузере и умирало от очистки кэша.
 *
 * ПОДМЕНЯЕТСЯ ОДИН СЛОЙ, И В ЭТОМ ВЕСЬ СМЫСЛ МОДУЛЯ. Девять ключей читаются из
 * десятка мест, но все — через эти четыре функции. Игра при этом не знает о
 * подмене ничего: попытки считаются, черновик кладётся, «Продолжить» работает —
 * ровно до перезагрузки вкладки, и это обещанное поведение, а не отказ.
 */
let memory = null

/**
 * Переключить режим. Идемпотентна: зовётся из тела компонента на каждый
 * рендер, и создавать новую память на каждый из них значило бы терять данные
 * между отрисовками.
 *
 * @param {boolean} on true — писать в память вкладки, false — на устройство
 */
export function useMemoryStorage(on) {
  const want = !!on
  if (want === (memory !== null)) return
  memory = want ? new Map() : null
}

/** В памяти ли мы сейчас. Нужна тестам и разбору. */
export const isMemoryStorage = () => memory !== null

/**
 * Сырая строка по ключу.
 *
 * @returns {string|null} null и когда ключа нет, и когда хранилище недоступно —
 *   для читающей стороны это одно и то же: данных нет.
 */
export function readRaw(key) {
  if (memory) return memory.has(key) ? memory.get(key) : null
  try {
    return globalThis.localStorage?.getItem(key) ?? null
  } catch {
    // приватный режим Safari бросает на чтение — значит данных нет
    return null
  }
}

/**
 * Записать строку.
 * @returns {boolean} легло ли. Ни один вызывающий не обязан это проверять:
 *   потерянная запись всюду дешевле упавшей игры.
 */
export function writeRaw(key, value) {
  if (memory) {
    memory.set(key, String(value))
    // слушателя не зовём: следить не за чем, на сервер гостевое не уезжает
    return true
  }
  try {
    globalThis.localStorage?.setItem(key, value)
  } catch {
    // приватный режим или переполнение — молча живём дальше
    return false
  }
  // о записи узнаёт синхронизация: сама запись при этом уже состоялась и от
  // слушателя не зависит — игра не ждёт ни сети, ни его согласия
  try {
    onWrite?.(key)
  } catch {
    // слушатель не имеет права ломать запись
  }
  return true
}

/**
 * КТО УЗНАЁТ О ЗАПИСИ. Одна точка на все девять модулей: они пишут через эту
 * обёртку, значит и слушателю достаточно быть здесь. Иначе отправку на сервер
 * пришлось бы вешать в каждый модуль по отдельности — и забыть её в одном из
 * них было бы делом времени.
 */
let onWrite = null

/**
 * Следить за записями. Возвращает функцию отписки.
 * @param {(key: string) => void} fn
 */
export function watchWrites(fn) {
  onWrite = fn
  return () => {
    onWrite = null
  }
}

/** Забыть ключ. Молча: нечего чистить — тоже результат. */
export function remove(key) {
  if (memory) {
    memory.delete(key)
    return
  }
  try {
    globalThis.localStorage?.removeItem(key)
  } catch {
    // нечего чистить
  }
}

/**
 * Разобранный JSON по ключу.
 *
 * Мусор в хранилище читается как «данных нет» — ровно так же, как отсутствие
 * ключа. Проверять форму прочитанного обязана вызывающая сторона: только она
 * знает, что там должно лежать.
 *
 * @returns {any|null}
 */
export function readJson(key) {
  const raw = readRaw(key)
  if (!raw) return null
  try {
    return JSON.parse(raw)
  } catch {
    // мусор — начинаем с чистого листа
    return null
  }
}

/**
 * Записать JSON.
 * @returns {boolean} легло ли
 */
export function writeJson(key, value) {
  let raw
  try {
    raw = JSON.stringify(value)
  } catch {
    // несериализуемое значение — записывать нечего
    return false
  }
  return writeRaw(key, raw)
}

/**
 * Снести всё, что Motion положил на устройство.
 *
 * Здесь — потому что список ключей здесь. Внутри FitPro это вызовет
 * `clearFitproData()` одной строкой вместо девяти (этап 4 переезда).
 */
export function clearAll() {
  for (const key of allKeys()) remove(key)
}
