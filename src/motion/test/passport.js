import { expect } from 'vitest'
import { screen } from '@testing-library/react'

/**
 * ПАСПОРТ ЭКРАНА — список того, без чего экран не экран.
 *
 * Зачем понадобилось. Обычные тесты экранов проверяют поведение: блок отдаёт
 * итог, отдых объявляет следующее, полоса называет круг. Ни один из них не
 * ловит ПРОПАЖУ. Элемент можно случайно вынести за условие, задеть при вёрстке
 * соседа, потерять при переносе разметки — и все тесты останутся зелёными,
 * потому что каждый смотрит на свой кусок и ни один не смотрит на экран
 * целиком. Человек в поле при этом остаётся без таймера или без счёта, и узнаём
 * мы об этом от него.
 *
 * ОДИН ПОМОЩНИК, А НЕ ПЯТЬ НАБОРОВ ПРОВЕРОК: паспорт должен читаться как
 * договор — вот экран, вот что человек на нём обязан видеть. Список рядом с
 * причиной, зачем элемент нужен; красный тест называет и то, и другое, чтобы
 * тот, кто его получит, не гадал, важна пропажа или нет.
 *
 * @param {string} name Экран — попадёт в текст ошибки.
 * @param {Array<{testid: string, что: string, зачем: string}>} required
 */
export function expectPassport(name, required) {
  const missing = required.filter((item) => screen.queryByTestId(item.testid) === null)

  if (missing.length) {
    const list = missing.map((m) => `  • ${m.что} (${m.testid}) — ${m.зачем}`).join('\n')
    throw new Error(`Экран «${name}»: пропали обязательные элементы\n${list}`)
  }

  // проверка должна быть видна в отчёте как утверждение, а не только как
  // отсутствие исключения
  expect(missing).toHaveLength(0)
}

