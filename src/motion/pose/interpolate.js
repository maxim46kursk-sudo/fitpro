import { MIN_VISIBILITY, visibilityOf } from './landmarks.js'

/**
 * ПРОМЕЖУТОЧНАЯ ПОЗА между двумя результатами распознавания — только для
 * картинки.
 *
 * Зачем. На слабом телефоне распознаватель отдаёт около девяти поз в секунду
 * (Redmi, GPU, модель Lite — легче уже некуда), а экран обновляется шестьдесят
 * раз. Скелет перерисовывался ровно в моменты прихода результатов, то есть
 * стоял на месте пять-шесть кадров подряд и потом прыгал. Человек видит это не
 * как «медленное распознавание», а как «игра тормозит», и в этот момент решает,
 * работает она у него или нет.
 *
 * ЭТО ТОЛЬКО ПИКСЕЛИ. Судейство, движок и детекторы получают сырые результаты и
 * ничего об этой функции не знают. Придуманная поза, попавшая в зачёт, была бы
 * зачётом за движение, которого человек не делал, — на кону деньги челленджа, и
 * такого не должно случиться ни при каком раскладе. Отсюда и место: отдельный
 * модуль, который зовёт один слой отрисовки.
 *
 * ВПЕРЁД НЕ ЗАГЛЯДЫВАЕМ. Отрисовка идёт с отставанием — не больше RENDER_LAG_MS
 * от свежей позы: между двумя известными позами картинка всегда честная, а
 * экстраполяция угадывала бы, куда человек пойдёт дальше, и промахивалась бы
 * ровно там, где он меняет направление, — то есть на каждом повторе.
 */

/**
 * СГЛАЖИВАНИЕ ПОТОЧЕЧНОЕ, а не одно на всю позу.
 *
 * Полевой тест: корпус на экране стоит ровно, а мах ногой заметно опаздывает за
 * настоящей ногой. Причина — общий k: он выбран так, чтобы не дрожала статика,
 * и на неподвижном плече это ровно то, что нужно, а на конечности, пролетающей
 * полкадра за интервал, то же самое сглаживание превращается в задержку. Плечо
 * и стопа в один кадр движутся по-разному, и мерить их одной меркой нельзя.
 *
 * Поэтому доля пути считается для КАЖДОЙ точки по её собственному смещению
 * между двумя результатами (в долях кадра, координаты нормированные):
 *
 *   до SLOW_MOVE       — точка стоит; дрожание распознавателя тут больше
 *                        настоящего движения, и сглаживание идёт полное
 *   от FAST_MOVE       — точка летит; ждать её незачем, рисуем сразу свежей
 *   между ними         — линейный переход, без ступеньки на границе
 *
 * Экстраполяции по-прежнему НЕТ: доля пути нигде не выходит за единицу, то есть
 * дальше свежей позы точка не уезжает ни на пиксель.
 */

/**
 * Ниже этого смещения за интервал точка считается стоящей. 0.008 кадра — это
 * примерно та амплитуда, с которой распознаватель дрожит на неподвижном
 * человеке: сглаживать её надо целиком, иначе скелет «кипит» на статике.
 */
export const SLOW_MOVE = 0.008

/**
 * Выше этого смещения точка считается летящей и рисуется свежей без сглаживания.
 * 0.03 кадра за интервал — это уже осознанное движение конечности (мах, удар,
 * шаг), а не дрожание: на нём заметна задержка, а не рывок.
 */
export const FAST_MOVE = 0.03

/**
 * Доля пути для ОДНОЙ точки: общий k, подтянутый к единице тем сильнее, чем
 * быстрее едет точка.
 *
 * @param {number} k общая доля пути (poseMix)
 * @param {number} d смещение точки между результатами, в долях кадра
 */
function pointMix(k, d) {
  if (d <= SLOW_MOVE) return k
  if (d >= FAST_MOVE) return 1
  return k + (1 - k) * ((d - SLOW_MOVE) / (FAST_MOVE - SLOW_MOVE))
}

/**
 * @param {Array|null} from ранняя поза
 * @param {Array|null} to поздняя поза, она же свежая
 * @param {number} t 0 — ровно ранняя, 1 — ровно свежая; за края не выходит
 * @returns {Array|null} точки для отрисовки
 * @param {object} [options]
 * @param {boolean} [options.adaptive] Считать долю пути по каждой точке
 *   отдельно (см. выше). ВЫКЛЮЧАЕТСЯ в синхронном режиме показа: там поза
 *   выравнивается на время захвата показанного кадра, и подтяни мы быструю
 *   точку к свежей позе — она обогнала бы картинку, то есть ровно то
 *   расхождение, ради которого весь синхронный режим и делался.
 */
export function lerpPose(from, to, t, { adaptive = true } = {}) {
  if (!Array.isArray(to) || !to.length) return Array.isArray(from) ? from : null
  /**
   * Разной длины наборы не смешиваем: соответствие точек в них не гарантировано,
   * а перепутать локоть с коленом хуже, чем нарисовать рывок.
   */
  if (!Array.isArray(from) || from.length !== to.length) return to

  const k = t <= 0 ? 0 : t >= 1 ? 1 : t
  // свежая поза целиком — считать по точкам нечего
  if (k === 1) return to

  const out = new Array(to.length)
  for (let i = 0; i < to.length; i += 1) {
    const a = from[i]
    const b = to[i]
    if (!a || !b) {
      out[i] = b ?? a
      continue
    }
    /**
     * Точка, невидимая хоть в одном из кадров, берётся из СВЕЖЕГО и не
     * смешивается. Координаты невидимой точки распознаватель не считает —
     * он их досочиняет, и они улетают куда угодно. Смешай их с настоящими, и
     * рука на экране поедет к выдуманному месту тем плавнее, чем аккуратнее
     * мы интерполируем.
     */
    if (visibilityOf(a) < MIN_VISIBILITY || visibilityOf(b) < MIN_VISIBILITY) {
      out[i] = b
      continue
    }
    /**
     * Скорость точки меряется ПО КАДРУ (x, y), без глубины: глубина у
     * распознавателя шумная сама по себе, и мах рукой на камеру считался бы по
     * ней быстрым движением там, где на экране не сдвинулось ничего.
     */
    const dx = b.x - a.x
    const dy = b.y - a.y
    const ki = adaptive ? pointMix(k, Math.hypot(dx, dy)) : k
    if (ki >= 1) {
      out[i] = b
      continue
    }
    // видимость и всё прочее — от свежего кадра, смешиваются только координаты
    out[i] = {
      ...b,
      x: a.x + dx * ki,
      y: a.y + dy * ki,
      z: a.z == null || b.z == null ? b.z : a.z + (b.z - a.z) * ki,
    }
  }
  return out
}

/**
 * ЗА СКОЛЬКО отрисовка доезжает от ранней позы к свежей.
 *
 * Растягивать переход на весь интервал между результатами нельзя: на слабом
 * телефоне их приходит около девяти в секунду, и скелет доходил бы до свежей
 * позы через ~110 мс после неё — поверх задержки самого распознавания. На
 * полевом прогоне (Redmi A3) это видно прямо: скелет тянется за телом.
 *
 * Шестьдесят миллисекунд — это примерно четыре кадра экрана: рывок глазом уже
 * не читается, а отставание сверх инференса почти исчезает. На быстром телефоне
 * интервал и так короче (~33 мс), и там ничего не меняется вовсе.
 */
export const RENDER_LAG_MS = 60

/**
 * Насколько далеко отрисовка ушла от ранней позы к свежей.
 *
 * В момент прихода свежей позы на экране ранняя (t = 0), дальше картинка едет к
 * свежей и доезжает за меньшее из двух: интервал между результатами или
 * RENDER_LAG_MS. Дошла — стоит на свежей до следующего результата. Дальше
 * единицы не идём: новый результат задержался, и держать надо последнюю
 * известную позу, а не выдумывать.
 *
 * Интервал берётся ФАКТИЧЕСКИЙ, между двумя последними результатами, а не
 * средний: на телефоне он гуляет от кадра к кадру, и подставь мы среднее,
 * картинка на коротком интервале не успевала бы дойти до свежей позы.
 *
 * @param {number} prevAt когда пришла ранняя поза
 * @param {number} curAt когда пришла свежая
 * @param {number} now текущее время
 */
export function poseMix(prevAt, curAt, now) {
  const span = curAt - prevAt
  if (!(span > 0)) return 1
  const k = (now - curAt) / Math.min(span, RENDER_LAG_MS)
  return k <= 0 ? 0 : k >= 1 ? 1 : k
}

/**
 * ДОЛЯ ПУТИ ПО ВРЕМЕНИ ЗАХВАТА — для синхронного показа.
 *
 * Здесь другая задача, чем у poseMix. Тот отвечает «сколько прошло с прихода
 * свежей позы» и живёт по часам отрисовки; этот отвечает «где было тело в
 * момент, который сейчас на экране», и живёт по часам КАМЕРЫ. Метки — те, что
 * стоят на результатах (result.timestamp, время захвата кадра), а точка отсчёта
 * — время показанного кадра.
 *
 * Никакого запаса на сглаживание тут нет и быть не должно: показанный кадр
 * лежит между двумя позами, и его положение между ними известно точно.
 *
 * Экстраполяции нет: за краями отрезка отдаётся крайняя поза. Вышли за свежую —
 * значит, результат для этого кадра ещё не пришёл, и честно показать можно
 * только последнее известное.
 *
 * @param {number} prevAt время захвата ранней позы
 * @param {number} curAt время захвата свежей
 * @param {number} at время показанного кадра
 */
export function poseMixAt(prevAt, curAt, at) {
  const span = curAt - prevAt
  if (!(span > 0)) return 1
  const k = (at - prevAt) / span
  return k <= 0 ? 0 : k >= 1 ? 1 : k
}
