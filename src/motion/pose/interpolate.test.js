import { describe, expect, it } from 'vitest'
import {
  FAST_MOVE,
  RENDER_LAG_MS,
  SLOW_MOVE,
  lerpPose,
  poseMix,
  poseMixAt,
} from './interpolate.js'
import { MIN_VISIBILITY } from './landmarks.js'

/**
 * Промежуточная поза для отрисовки. На слабом телефоне распознаватель отдаёт
 * около девяти поз в секунду, а экран обновляется шестьдесят раз: без этой
 * функции скелет стоит пять-шесть кадров и прыгает.
 *
 * Судейство её не видит и видеть не должно — здесь только пиксели.
 */

const pt = (x, y, visibility = 1, z = 0) => ({ x, y, z, visibility })

/**
 * Смещения точки за интервал между результатами — в долях кадра. Сглаживание
 * поточечное, и от этого числа зависит ВСЁ поведение: медленная точка идёт
 * плавно, быстрая рисуется свежей сразу.
 */
const SLOW_STEP = SLOW_MOVE / 2
const FAST_STEP = 0.2

describe('поза между двумя результатами', () => {
  it('середина пути — середина между точками', () => {
    const from = [pt(0, 0), pt(0.2, 0.4)]
    const to = [pt(SLOW_STEP, 0), pt(0.2, 0.4 + SLOW_STEP)]

    const mid = lerpPose(from, to, 0.5)
    expect(mid[0].x).toBeCloseTo(SLOW_STEP / 2, 6)
    expect(mid[0].y).toBeCloseTo(0, 6)
    expect(mid[1].x).toBeCloseTo(0.2, 6)
    expect(mid[1].y).toBeCloseTo(0.4 + SLOW_STEP / 2, 6)
  })

  it('края отдают ровно исходные позы', () => {
    const from = [pt(0, 0)]
    const to = [pt(SLOW_STEP, 0)]

    expect(lerpPose(from, to, 0)[0].x).toBeCloseTo(0, 6)
    expect(lerpPose(from, to, 1)[0]).toMatchObject({ x: SLOW_STEP })
  })

  it('за края не выходит: экстраполяции вперёд нет', () => {
    /**
     * Экстраполяция угадывала бы, куда человек пойдёт дальше, и промахивалась
     * бы ровно там, где он меняет направление, — то есть на каждом повторе.
     */
    const from = [pt(0, 0)]
    const to = [pt(SLOW_STEP, 0)]

    expect(lerpPose(from, to, 2.5)[0]).toMatchObject({ x: SLOW_STEP })
    expect(lerpPose(from, to, -1)[0].x).toBeCloseTo(0, 6)
  })

  it('глубина смешивается вместе с плоскостью, но скорости не задаёт', () => {
    // точка стоит на экране и уезжает по глубине: глубина у распознавателя
    // шумная, и считать по ней движение быстрым нельзя
    const mid = lerpPose([pt(0, 0, 1, 0)], [pt(SLOW_STEP, 0, 1, 0.4)], 0.5)
    expect(mid[0].z).toBeCloseTo(0.2, 6)
  })
})

describe('быстрая точка не ждёт медленных', () => {
  /**
   * Полевой тест: корпус стоит ровно, а мах ногой заметно опаздывает за
   * настоящей ногой. Общий на всю позу k выбран так, чтобы не дрожала статика, —
   * на конечности, пролетающей полкадра за интервал, то же сглаживание
   * превращается в задержку.
   */

  it('летящая конечность рисуется свежей, не дожидаясь конца пути', () => {
    const out = lerpPose([pt(0, 0)], [pt(FAST_STEP, 0)], 0.3)
    expect(out[0].x).toBe(FAST_STEP)
  })

  it('медленная точка сглаживается как раньше', () => {
    // 0.003 кадра за интервал — это дрожание распознавателя, а не движение
    const out = lerpPose([pt(0, 0)], [pt(0.003, 0)], 0.3)
    expect(out[0].x).toBeCloseTo(0.003 * 0.3, 6)
  })

  it('в одной позе быстрая и медленная точки живут каждая по-своему', () => {
    // ровно тот случай: плечо стоит, стопа летит — и мерить их одной меркой
    // нельзя
    const out = lerpPose([pt(0, 0), pt(0.5, 0.5)], [pt(0.003, 0), pt(0.5, 0.5 + FAST_STEP)], 0.3)
    expect(out[0].x).toBeCloseTo(0.003 * 0.3, 6)
    expect(out[1].y).toBe(0.5 + FAST_STEP)
  })

  it('переходная зона монотонна: чем быстрее точка, тем она свежее', () => {
    // без перехода на границе была бы ступенька — точка дёргалась бы туда-сюда
    // ровно на пороге
    const t = 0.25
    const fractions = []
    for (let step = 0; step <= 10; step += 1) {
      const d = SLOW_MOVE + ((FAST_MOVE - SLOW_MOVE) * step) / 10
      fractions.push(lerpPose([pt(0, 0)], [pt(d, 0)], t)[0].x / d)
    }

    // начало зоны — общий k, конец — свежая поза, между ними строго вверх
    expect(fractions[0]).toBeCloseTo(t, 6)
    expect(fractions.at(-1)).toBeCloseTo(1, 6)
    for (let i = 1; i < fractions.length; i += 1) {
      expect(fractions[i]).toBeGreaterThan(fractions[i - 1])
    }
  })

  it('вперёд не заглядываем ни на пиксель даже на самой быстрой точке', () => {
    /**
     * Быстрая точка доезжает до СВЕЖЕЙ позы и останавливается на ней. Уйти
     * дальше — это уже угадывать, куда человек пойдёт, и промахиваться на
     * каждой смене направления.
     */
    for (const t of [0, 0.3, 0.9, 1]) {
      const out = lerpPose([pt(0, 0)], [pt(FAST_STEP, FAST_STEP)], t)
      expect(out[0].x).toBe(FAST_STEP)
      expect(out[0].y).toBe(FAST_STEP)
    }
  })
})

describe('невидимые точки не смешиваются', () => {
  const bad = MIN_VISIBILITY / 2

  it('точка, невидимая в раннем кадре, берётся из свежего', () => {
    /**
     * Координаты невидимой точки распознаватель не считает — он их досочиняет,
     * и они улетают куда угодно. Смешай их с настоящими, и рука на экране
     * поедет к выдуманному месту тем плавнее, чем аккуратнее мы интерполируем.
     */
    const mid = lerpPose([pt(0, 0, bad)], [pt(1, 1, 1)], 0.5)
    expect(mid[0]).toMatchObject({ x: 1, y: 1 })
  })

  it('точка, невидимая в свежем кадре, тоже берётся из свежего', () => {
    // свежий кадр — последняя правда о том, видно точку или нет; рисовать её
    // решает слой отрисовки по видимости, и она обязана быть свежей
    const mid = lerpPose([pt(0, 0, 1)], [pt(1, 1, bad)], 0.5)
    expect(mid[0]).toMatchObject({ x: 1, y: 1 })
    expect(mid[0].visibility).toBe(bad)
  })

  it('видимые точки того же кадра смешиваются как обычно', () => {
    // одна пропавшая точка не должна замораживать весь скелет
    const mid = lerpPose([pt(0, 0, bad), pt(0, 0)], [pt(1, 1), pt(SLOW_STEP, 0)], 0.5)
    expect(mid[0]).toMatchObject({ x: 1, y: 1 })
    expect(mid[1].x).toBeCloseTo(SLOW_STEP / 2, 6)
  })
})

describe('смешивать нечего — рисуем что есть', () => {
  it('ранней позы нет', () => {
    const to = [pt(1, 1)]
    expect(lerpPose(null, to, 0.5)).toBe(to)
  })

  it('свежей позы нет', () => {
    const from = [pt(1, 1)]
    expect(lerpPose(from, null, 0.5)).toBe(from)
    expect(lerpPose(null, null, 0.5)).toBeNull()
  })

  it('наборы разной длины не смешиваются', () => {
    // соответствие точек в них не гарантировано, а перепутать локоть с коленом
    // хуже, чем нарисовать рывок
    const to = [pt(1, 1), pt(1, 1)]
    expect(lerpPose([pt(0, 0)], to, 0.5)).toBe(to)
  })

  it('исходные позы не портятся', () => {
    // они же уходят в судейство — трогать их нельзя ни при каком раскладе
    const from = [pt(0, 0)]
    const to = [pt(1, 1)]
    lerpPose(from, to, 0.5)
    expect(from[0]).toMatchObject({ x: 0, y: 0 })
    expect(to[0]).toMatchObject({ x: 1, y: 1 })
  })
})

describe('отставание отрисовки', () => {
  it('в момент прихода свежей позы на экране ещё ранняя', () => {
    /**
     * Ноль — единственная точка, где картинка совпадает с ранней позой: отсюда
     * она едет к свежей и между двумя ИЗВЕСТНЫМИ позами ничего не выдумывает.
     */
    expect(poseMix(0, 100, 100)).toBe(0)
  })

  it('короткий интервал проезжается целиком — быстрый телефон не трогаем', () => {
    // кадр экрана 16.7 мс, поз шестьдесят в секунду: интервал короче
    // RENDER_LAG_MS, и переход по-прежнему растянут ровно на него
    expect(poseMix(0, 33, 33 + 16.5)).toBeCloseTo(0.5, 6)
    expect(poseMix(0, 33, 66)).toBe(1)
  })

  it('интервал 110 мс: поза догоняется за 60, а не за все 110', () => {
    /**
     * Полевой прогон на Redmi A3: скелет тянулся за телом на целый интервал
     * между позами — ~110 мс поверх задержки самого распознавания.
     */
    expect(poseMix(0, 110, 110 + RENDER_LAG_MS)).toBe(1)
    expect(poseMix(0, 110, 110 + RENDER_LAG_MS / 2)).toBeCloseTo(0.5, 6)
    // на старой формуле здесь было бы чуть больше половины пути
    expect(poseMix(0, 110, 110 + 100)).toBe(1)
  })

  it('дошли до свежей — стоим на ней, а не летим дальше', () => {
    expect(poseMix(0, 100, 400)).toBe(1)
    expect(poseMix(0, 100, 5000)).toBe(1)
  })

  it('две позы в одну миллисекунду не делят на ноль', () => {
    expect(poseMix(100, 100, 100)).toBe(1)
    expect(poseMix(200, 100, 300)).toBe(1)
  })

  it('девять поз в секунду: рывка нет, и свежая поза берётся сразу', () => {
    /**
     * Тот самый случай с Redmi: ~111 мс между позами при кадре экрана 16.7 мс.
     * Раньше все шесть кадров показывали одно и то же; теперь первые четыре
     * доводят скелет до свежей позы, а остальные держат её.
     */
    const step = 1000 / 9
    const at = (frame) => poseMix(0, step, step + frame * 16.7)
    const moving = new Set()
    for (let frame = 0; frame < 4; frame += 1) moving.add(at(frame).toFixed(3))
    expect(moving.size).toBe(4)
    // и к четвёртому кадру картинка уже свежая — дальше ей ехать некуда
    expect(at(4)).toBe(1)
    expect(at(5)).toBe(1)
  })
})

describe('выравнивание позы по времени захвата', () => {
  /**
   * Синхронный показ: на экране кадр, снятый в известный момент, и поза обязана
   * описывать тело ИМЕННО В ЭТОТ момент. Считается всё по часам камеры — по
   * меткам захвата на результатах, — а не по часам отрисовки.
   */

  it('показанный кадр посередине между позами — поза посередине', () => {
    expect(poseMixAt(1000, 1100, 1050)).toBeCloseTo(0.5, 6)
    expect(poseMixAt(1000, 1100, 1025)).toBeCloseTo(0.25, 6)
  })

  it('кадр ровно на метке позы — эта поза и рисуется', () => {
    expect(poseMixAt(1000, 1100, 1000)).toBe(0)
    expect(poseMixAt(1000, 1100, 1100)).toBe(1)
  })

  it('за отрезком — крайняя поза: вперёд не заглядываем', () => {
    /**
     * Кадр новее свежей позы значит одно: результат для него ещё не пришёл.
     * Честно показать можно только последнее известное, а не догадку.
     */
    expect(poseMixAt(1000, 1100, 1400)).toBe(1)
    expect(poseMixAt(1000, 1100, 900)).toBe(0)
  })

  it('сглаживания тут нет: расстояние до кадра известно точно', () => {
    // половина пути между позами — это ровно середина интервала захвата
    expect(poseMixAt(0, 110, 55)).toBeCloseTo(0.5, 6)
    // а poseMix ужимает тот же путь под RENDER_LAG_MS: там полпути за 30 мс
    expect(poseMix(0, 110, 110 + RENDER_LAG_MS / 2)).toBeCloseTo(0.5, 6)
  })

  it('две позы с одной меткой не делят на ноль', () => {
    expect(poseMixAt(1000, 1000, 1000)).toBe(1)
    expect(poseMixAt(1100, 1000, 1050)).toBe(1)
  })

  it('в синхронном режиме быстрые точки не обгоняют картинку', () => {
    /**
     * Поточечное ускорение (SLOW_MOVE/FAST_MOVE) для живого режима: там оно
     * убирает задержку. В синхронном оно бы её СОЗДАЛО с другой стороны —
     * быстрая точка ушла бы вперёд показанного кадра.
     */
    const from = [pt(0, 0)]
    const to = [pt(FAST_STEP, 0)]
    const t = poseMixAt(1000, 1100, 1050)

    expect(lerpPose(from, to, t, { adaptive: false })[0].x).toBeCloseTo(FAST_STEP / 2, 6)
    // а в живом режиме та же точка по-прежнему рисуется свежей
    expect(lerpPose(from, to, t)[0].x).toBe(FAST_STEP)
  })
})
