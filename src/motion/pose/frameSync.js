/**
 * СИНХРОННЫЙ ПОКАЗ: видеокадр выходит на экран вместе с посчитанной ПО НЕМУ позой.
 *
 * Зачем. Скелет всегда отставал от тела, и никакой интерполяцией это не
 * лечится: <video> показывает живую камеру, а поза к этому моменту описывает
 * кадр возрастом 100–250 мс — столько идёт инференс. Разрыв виден на любом
 * движении, и человек читает его как «игра тормозит».
 *
 * Решение то же, что в зрелых продуктах: показывать не самый свежий кадр, а
 * тот, для которого уже есть поза. Картинка отстаёт от реальности на задержку
 * инференса — незаметно, потому что сравнивать не с чем: в зеркале нет второго,
 * «правильного» изображения. А вот расхождение картинки со скелетом заметно
 * сразу, и его больше нет.
 *
 * Здесь только арифметика и кольцевой буфер — без DOM, чтобы всё это можно было
 * проверить тестами. Рисование живёт в CameraView.
 *
 * СУДЕЙСТВО ЭТОГО НЕ ВИДИТ. Детекторы и зачёты получают сырые результаты, как и
 * раньше: буфер держит ПИКСЕЛИ и никуда, кроме экрана, не уходит.
 */

export const MODE = { SYNC: 'sync', LIVE: 'live' }

/**
 * Потолок задержки показа. Больше трети секунды — и человек уже чувствует, что
 * зеркало живёт своей жизнью: он машет рукой и ждёт. Лучше показать картинку
 * чуть свежее скелета, чем превратить зеркало в видеозвонок.
 */
export const SYNC_LAG_MAX_MS = 350

/** Глубина буфера кадров: перекрывает потолок задержки с запасом. */
export const FRAME_BUFFER_MS = 400

/**
 * Потолок числа кадров в пуле. Кадр родного разрешения (480x640) — это около
 * мегабайта, и на слабом телефоне пул важнее ограничить по памяти, чем добрать
 * последние миллисекунды глубины.
 */
export const MAX_FRAMES = 16

/** Кадры перестали приходить вовсе — показывать нечего, уходим на живое видео. */
export const SYNC_STALL_MS = 500

/**
 * Верхняя граница интервала между кадрами буфера: реже 12–13 кадров в секунду
 * картинка сама по себе рвётся, и синхронность её уже не спасает — живое видео
 * в этот момент честнее.
 */
export const SYNC_MAX_INTERVAL_MS = 80

/** Сколько кадров ждём, прежде чем судить о скорости: первые всегда рваные. */
export const SYNC_WARMUP_FRAMES = 8

/**
 * Ручной выключатель для поля: `?livecam=1` возвращает прежний режим (живое
 * видео + скелет поверх). Нужен, чтобы сравнить два режима на одном телефоне
 * подряд, не пересобирая приложение.
 */
export function isLiveCamForced(search) {
  try {
    return new URLSearchParams(search || '').get('livecam') === '1'
  } catch {
    return false
  }
}

/**
 * Режим показа на старте.
 *
 * requestVideoFrameCallback — единственный способ узнать, что <video> ПОКАЗАЛ
 * новый кадр. Без него копировать было бы нечего: rAF срабатывает чаще кадров
 * камеры, и буфер наполнялся бы копиями одного и того же.
 */
export function chooseSyncMode({ hasVideoFrameCallback, forceLive = false }) {
  if (forceLive) return MODE.LIVE
  return hasVideoFrameCallback ? MODE.SYNC : MODE.LIVE
}

/**
 * НА СКОЛЬКО ОТСТАЁТ ПОКАЗ: задержка «захват -> результат» плюс ПОЛНЫЙ интервал
 * между результатами.
 *
 * Задержка — это минимум, чтобы поза для показанного кадра вообще была
 * посчитана. Интервал сверху — чтобы она была посчитана И ДЛЯ СЛЕДУЮЩЕГО кадра
 * тоже, то есть чтобы точка показа всё время лежала МЕЖДУ двумя известными
 * позами.
 *
 * ПОЧЕМУ ПОЛНЫЙ, А НЕ ПОЛОВИНА. С полным интервалом точка показа выходит из
 * ранней позы ровно тогда, когда приходит свежая, и доезжает до свежей ровно к
 * приходу следующей: доля пути идёт 0 -> 1 и никогда не упирается в единицу.
 * Скелет с телом совпадают ВСЁ время, а не в отдельные моменты.
 *
 * С половиной (так было) точка показа стартует с середины отрезка и доезжает до
 * свежей позы за полинтервала — а вторую половину поза стоит, потому что идти
 * ей больше некуда, вперёд мы не заглядываем. Картинка в это время едет:
 * расхождение растёт от нуля до полуинтервала и рвётся с каждым результатом. На
 * семи результатах в секунду это семьдесят миллисекунд дёрганья — ровно то, что
 * видно глазом.
 *
 * Платим абсолютной задержкой зеркала: на слабом телефоне это около трети
 * секунды. Её человек не замечает — сравнивать не с чем; расхождение скелета с
 * телом он замечает всегда.
 *
 * @param {number} latencyMs сглаженная задержка захват -> результат
 * @param {number} spanMs интервал между двумя последними результатами
 */
export function syncLag(latencyMs, spanMs) {
  const lag = Math.max(0, latencyMs || 0) + Math.max(0, spanMs || 0)
  return Math.min(SYNC_LAG_MAX_MS, lag)
}

/**
 * Сглаживание задержки. Одиночный тяжёлый кадр не должен дёргать всю картинку
 * назад: задержка гуляет от кадра к кадру, а точка показа обязана ехать ровно.
 */
export function smoothLatency(prev, next, weight = 0.2) {
  if (!(next >= 0)) return prev ?? 0
  if (prev == null) return next
  return prev + (next - prev) * weight
}

/**
 * Пора ли уходить на живое видео, и по какой причине.
 *
 * Откат односторонний: вернувшись в синхронный режим, телефон снова упёрся бы в
 * то же место, и человек получил бы мигание режимов вместо картинки.
 *
 * @returns {'stalled'|'slow'|null}
 */
export function fallbackReason({ sinceLastFrameMs, frameIntervalMs, frames }) {
  if (sinceLastFrameMs > SYNC_STALL_MS) return 'stalled'
  if (frames >= SYNC_WARMUP_FRAMES && frameIntervalMs > SYNC_MAX_INTERVAL_MS) return 'slow'
  return null
}

/**
 * ЧТО СЕЙЧАС НА ЭКРАНЕ — одна запись на всё приложение.
 *
 * Пишет сюда CameraView (он единственный решает, какой кадр показан и какой
 * позой он описывается), читают те, кто рисует ПОВЕРХ картинки: мишени боя
 * висят на теле, и тело им нужно ровно то, которое человек видит.
 *
 * Раньше оверлеи брали сырую свежую позу — то есть тело из будущего
 * относительно показанного кадра. Мишень висела там, где конечность окажется, а
 * не там, где она нарисована, и зачёт вспыхивал раньше, чем рука доходила.
 *
 * СУДЕЙСТВО СЮДА НЕ СМОТРИТ И СМОТРЕТЬ НЕ ДОЛЖНО. Очки, зачёты и детекторы
 * работают на сырых результатах и живут по реальному времени: сдвинь их на
 * задержку показа — и человек получал бы зачёт за движение, которое он уже
 * сделал, но по часам игры ещё не сделал. Здесь только пиксели.
 *
 * Запись одна и переиспользуется: читатели вызывают её каждый кадр отрисовки, и
 * новый объект на кадр — это мусор на ровном месте.
 */
const shown = { landmarks: null, at: 0, mode: MODE.LIVE }

/** @returns {{landmarks: Array|null, at: number, mode: string}} */
export function getShownPose() {
  return shown
}

export function publishShownPose({ landmarks = null, at = 0, mode = MODE.LIVE } = {}) {
  shown.landmarks = landmarks
  shown.at = at
  shown.mode = mode
  return shown
}

/**
 * Сколько ответ ждёт своей точки показа, прежде чем показаться всё равно.
 *
 * Страховка на случай, когда точка показа встала: камера отвалилась, режим
 * откатился, телефон ушёл в себя. Молча проглотить ответ на движение нельзя ни
 * при каком раскладе — человек прочитает молчание как «игра меня не увидела».
 */
export const SHOW_WAIT_MAX_MS = 1000

/**
 * ОЧЕРЕДЬ ВИЗУАЛЬНОГО ОТВЕТА — показать реакцию тогда, когда до неё доехала
 * картинка.
 *
 * Судейство идёт по сырой свежей позе, а на экране поза постарше — на задержку
 * показа (syncLag). Вспышка зачёта и «+очки» поэтому появлялись раньше, чем
 * показанная рука доходила до мишени: человек видел зачёт по пустому месту.
 * Здесь ответ ждёт свой кадр: метка события — время ЗАХВАТА кадра, по которому
 * оно принято, и показывается оно, когда точка показа дошла до этой метки.
 *
 * ЖДЁТ ТОЛЬКО КАРТИНКА. Очки, статистика попытки и реакция считаются в момент
 * судейства и по реальному времени: задержи их — и reactMs стал бы несравним
 * между телефонами, потому что в него вошла бы задержка чужого экрана.
 *
 * В живом режиме очереди нет вовсе: там показ и судейство идут по одной позе, и
 * ждать нечего.
 */
export function createShowQueue({ maxWaitMs = SHOW_WAIT_MAX_MS } = {}) {
  /** По возрастанию меток: события приходят кадрами, а кадры идут по порядку. */
  const items = []

  return {
    get size() {
      return items.length
    },

    /**
     * @param {number} at метка события — время захвата кадра, по которому судили
     * @param {Function} run что показать
     * @param {{mode: string, at: number}} shown что сейчас на экране
     * @param {number} now
     * @returns {boolean} отложено (иначе показано сразу)
     */
    push(at, run, shown, now) {
      if (shown?.mode !== MODE.SYNC || !Number.isFinite(at)) {
        run()
        return false
      }
      items.push({ at, queuedAt: now, run })
      return true
    },

    /** Показать всё, чья метка уже на экране. */
    drain(shown, now) {
      if (!items.length) return 0
      const live = shown?.mode !== MODE.SYNC
      let ready = 0
      while (ready < items.length) {
        const item = items[ready]
        const arrived = live || item.at <= (shown?.at ?? 0)
        // ждать дольше нечего: точка показа встала, а ответ обязан прозвучать
        const waited = now - item.queuedAt >= maxWaitMs
        if (!arrived && !waited) break
        ready += 1
      }
      if (!ready) return 0
      // список режется ДО показа: обработчик может поставить в очередь новое
      const due = items.splice(0, ready)
      for (const item of due) item.run()
      return due.length
    },

    /** Экран уходит — очередь уходит с ним, а не остаётся висеть в памяти. */
    clear() {
      items.length = 0
    },
  }
}

/**
 * КОЛЬЦЕВОЙ БУФЕР КАДРОВ.
 *
 * Кадры копируются в переиспользуемые canvas-ы родного разрешения: новых
 * аллокаций на кадр нет вовсе. Слот, вышедший из окна, возвращается в пул и
 * достаётся оттуда же — на слабом телефоне сборщик мусора посреди тренировки
 * заметен не меньше, чем сам инференс.
 *
 * @param {object} options
 * @param {() => HTMLCanvasElement} options.createCanvas как завести новый слот
 */
export function createFrameBuffer({
  createCanvas,
  bufferMs = FRAME_BUFFER_MS,
  maxFrames = MAX_FRAMES,
} = {}) {
  /** Кадры по возрастанию времени: сюда пишет камера, отсюда читает отрисовка. */
  const frames = []
  const pool = []

  const recycle = (slot) => {
    slot.at = 0
    pool.push(slot)
  }

  return {
    get size() {
      return frames.length
    },
    get pooled() {
      return pool.length
    },

    /** Время самого старого и самого свежего кадра — по ним клампится показ. */
    oldestAt: () => (frames.length ? frames[0].at : null),
    newestAt: () => (frames.length ? frames[frames.length - 1].at : null),

    /**
     * Слот под новый кадр. Всё, что старше окна, и лишнее сверх потолка
     * возвращается в пул; вызывающий рисует в `slot.canvas` и больше ничего не
     * делает.
     *
     * @param {number} at время кадра
     * @param {number} width родное разрешение видео
     * @param {number} height
     */
    acquire(at, width, height) {
      while (frames.length && at - frames[0].at > bufferMs) recycle(frames.shift())
      while (frames.length >= maxFrames) recycle(frames.shift())

      const slot = pool.pop() ?? { canvas: createCanvas(), at: 0 }
      if (width && height && (slot.canvas.width !== width || slot.canvas.height !== height)) {
        slot.canvas.width = width
        slot.canvas.height = height
      }
      slot.at = at
      frames.push(slot)
      return slot
    },

    /**
     * Кадр, ближайший к запрошенному времени.
     *
     * За краями буфера отдаётся крайний кадр, а не пустота: показать соседний
     * кадр лучше, чем чёрный экран, — и точка показа всё равно приклеивается к
     * тому, что отдали (см. CameraView), так что скелет от картинки не уедет.
     */
    nearest(at) {
      if (!frames.length) return null
      let best = frames[0]
      let bestGap = Math.abs(best.at - at)
      for (let i = 1; i < frames.length; i += 1) {
        const gap = Math.abs(frames[i].at - at)
        // строгое «меньше»: на равных выигрывает более старый кадр — тот, для
        // которого поза заведомо уже посчитана
        if (gap < bestGap) {
          best = frames[i]
          bestGap = gap
        }
      }
      return best
    },

    /**
     * Последний кадр, показанный НЕ ПОЗЖЕ указанного времени, — то есть ровно
     * тот, который в этот момент и ушёл на инференс.
     *
     * Нужен, чтобы поза и картинка мерились одними часами. Метку результату
     * ставит насос в момент захвата, а кадр к этому моменту уже висел на экране
     * какое-то время (до интервала камеры). Разница невелика, но она
     * систематическая и вся в одну сторону — скелет отставал бы от картинки на
     * полкадра просто из-за арифметики.
     */
    latestBefore(at) {
      let best = null
      for (let i = 0; i < frames.length; i += 1) {
        if (frames[i].at > at) break
        best = frames[i]
      }
      return best
    },

    /** Всё в пул: смена камеры, разрешения или уход в живой режим. */
    clear() {
      while (frames.length) recycle(frames.pop())
    },
  }
}
