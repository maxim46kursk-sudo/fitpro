/**
 * ПОЛОСА «ИГРАЕШЬ ПО КЭШУ» — честность прогресса.
 *
 * Раздел переживает неудачную загрузку и открывается на последнем сохранённом
 * на этом устройстве. Молча так делать нельзя: человек набирает очки, а они
 * могут не сойтись с тем, что лежит на сервере, — и узнает он об этом в споре
 * о призах, задним числом.
 *
 * ПОЧЕМУ ПОЛОСА, А НЕ ВСПЛЫВАШКА. Всплывашку закрывают не читая, и она уходит
 * навсегда; беда при этом остаётся. Полоса висит, пока не починится, и на ней
 * же кнопка «Попробовать снова» — единственное действие, которое человек может
 * предпринять сам.
 *
 * @param {'load'|'push'} [props.kind] что именно случилось
 * @param {boolean} [props.busy] повтор уже идёт
 * @param {() => void} [props.onRetry]
 */
export default function SyncBanner({ kind = 'load', busy = false, onRetry = null }) {
  const загрузка = kind === 'load'
  return (
    <div className={`mt-sync mt-sync--${kind}`} data-testid={загрузка ? 'sync-warn' : 'sync-push-warn'} role="status">
      <div className="mt-sync__text">
        {загрузка ? (
          <>
            <b>Не удалось загрузить твой прогресс.</b> Играешь по последнему сохранённому на
            этом устройстве — результат может не попасть в зачёт.
          </>
        ) : (
          <>
            <b>Результат не отправлен.</b> Он сохранён на телефоне — отправим сам, когда
            появится связь.
          </>
        )}
      </div>
      {onRetry && (
        <button
          type="button"
          className="mt-sync__btn"
          data-testid="sync-retry"
          disabled={busy}
          onClick={onRetry}
        >
          {busy ? 'Пробую…' : 'Попробовать снова'}
        </button>
      )}
    </div>
  )
}
