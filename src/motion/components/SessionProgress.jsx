/**
 * ГДЕ Я СЕЙЧАС В ТРЕНИРОВКЕ — одна полоса на все три экрана сессии.
 *
 * Внутри сессии человек видит три разных экрана: силовой блок, отдых и бой. У
 * каждого свои крупные цифры — секунды, повторы, очки, — и ни одна из них не
 * отвечала на главный вопрос: сколько ещё. Человек на четвёртом круге из восьми
 * и человек на седьмом видели ровно одно и то же, а работают они по-разному:
 * первый распределяет силы, второй дотягивает. Незнание превращает любую
 * тренировку в бесконечную.
 *
 * ОДИН КОМПОНЕНТ, А НЕ ТРИ КОПИИ — иначе полоса разъедется. Три верстки одного
 * и того же расходятся не сразу: сперва на пиксель, потом на цвет, а через
 * месяц на одном экране «КРУГ 3 из 7», на другом «3/7». Человек в этот момент
 * решает, что перед ним разные счётчики, и начинает искать подвох.
 *
 * КОМПАКТНО И У ВЕРХНЕГО КРАЯ. Герой экрана — человек в кадре, и заслонять его
 * ради справки нельзя: полоса живёт в полосе высотой в строку над всем
 * остальным содержимым, а экраны сдвигают своё верхнее хозяйство ей навстречу.
 *
 * @param {number} props.cycle Текущий круг, считая с единицы.
 * @param {number} props.cycles Сколько кругов в сессии сегодня — их число даёт
 *   план дня, и на тяжёлых днях оно другое.
 * @param {number|null} [props.score] Общий счёт сессии. Нужен ОТДЫХУ: это
 *   единственный экран сессии без своих очков, а именно на отдыхе человек и
 *   смотрит на результат — на блоке и в бою ему некогда.
 * @param {boolean} [props.cheap] Телефон не вытягивает кадр. Тогда от полосы
 *   остаётся ТОЛЬКО ТЕКСТ: сегменты и свечение — украшение, а знание, на каком
 *   ты круге, — нет, и терять его из-за слабого телефона человек не должен.
 */
export default function SessionProgress({ cycle, cycles, score = null, cheap = false }) {
  // вне сессии (одиночный раунд по ?round=1) кругов нет вовсе — и полосы тоже
  if (!Number.isFinite(cycles) || cycles < 1) return null
  const at = Math.min(Math.max(1, cycle || 1), cycles)

  return (
    <div className={`mt-sprog ${cheap ? 'is-cheap' : ''}`} data-testid="session-progress">
      <div className="mt-sprog__label" data-testid="session-cycle">
        КРУГ {at} из {cycles}
      </div>

      {!cheap && (
        <div className="mt-sprog__bar" aria-hidden="true">
          {Array.from({ length: cycles }, (_, i) => (
            <span
              key={i}
              className={`mt-sprog__seg ${i < at - 1 ? 'is-done' : ''} ${i === at - 1 ? 'is-now' : ''}`}
            />
          ))}
        </div>
      )}

      {score != null && (
        <div className="mt-sprog__score" data-testid="session-progress-score">
          {score}
        </div>
      )}
    </div>
  )
}
