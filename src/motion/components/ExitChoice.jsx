/**
 * ВЫХОД ИЗ ЗАХОДА — СПРАШИВАЕМ, А НЕ РЕШАЕМ ЗА ЧЕЛОВЕКА.
 *
 * Раньше выход был один и молчаливый: нажал «Выйти» — попытка записана. Для
 * того, кто вышел потому, что позвонили, это правильно. Для того, кто понял на
 * второй минуте, что взял слишком высокий уровень, — нет: он сжигал одну из
 * трёх попыток дня на заход, который сам считает несостоявшимся, и узнавал об
 * этом уже на выборе уровня.
 *
 * Отсюда два выхода, и оба названы тем, что они делают. Ничего нового под ними
 * не изобретено: «сохранить» — это существующее закрытие черновика
 * (`closePending`), «без сохранения» — существующий `dropPending`.
 *
 * ГОСТЮ СОХРАНЯТЬ НЕКУДА. Его заход живёт в памяти вкладки и умрёт с
 * перезагрузкой, поэтому первая кнопка у него честно называется тем, что
 * требуется на самом деле, — аккаунтом. Сыгранное при этом не пропадает: заход
 * закрывается тем же путём, что у всех, и уезжает в буфер переезда вместе с
 * остальными попытками.
 *
 * «ОТМЕНА» ЕСТЬ, ХОТЯ ВЫБОР НАЗВАН ДВОЙНЫМ. Оба названных выхода — выходы, и
 * без третьей строки случайное касание крестика посреди двадцатиминутной
 * сессии стало бы необратимым. Она оформлена тихо и стоит последней: её ищут
 * только те, кто нажал не туда.
 */
export default function ExitChoice({ guest = false, onSave, onDiscard, onCancel }) {
  return (
    <div className="mt-menu" data-testid="exit-choice">
      <div className="mt-menu__veil" aria-hidden="true" />
      <div className="mt-menu__card">
        <div className="mt-menu__title">Выйти из тренировки?</div>

        <button
          type="button"
          className="mt-menu__item mt-menu__item--main"
          onClick={onSave}
          data-testid="exit-save"
        >
          {guest ? 'Создать аккаунт, чтобы сохранить' : 'Сохранить и выйти'}
        </button>

        <button
          type="button"
          className="mt-menu__item"
          onClick={onDiscard}
          data-testid="exit-discard"
        >
          Выйти без сохранения
        </button>

        <button
          type="button"
          className="mt-menu__item mt-menu__item--quiet"
          onClick={onCancel}
          data-testid="exit-cancel"
        >
          Отмена
        </button>
      </div>
    </div>
  )
}
