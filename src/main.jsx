import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import './index.css'
import App from './App.jsx'

/**
 * МЕТКИ ЗАГРУЗКИ — ответ сторожу из index.html.
 *
 * `bundle` ставится тем, что этот файл вообще начал выполняться: значит код
 * приехал и разобрался. `react` — после первого кадра, а не сразу после
 * render(): render только запускает работу, и приложение, упавшее в первом же
 * рендере, отметилось бы «поднявшимся». requestAnimationFrame срабатывает
 * ПОСЛЕ отрисовки, то есть тогда, когда человек действительно что-то увидел.
 *
 * Функции может не быть (страница из старого кэша, где сторожа ещё нет) —
 * поэтому опциональный вызов, а не проверка на существование в трёх местах.
 */
window.__bootStage?.('bundle')

createRoot(document.getElementById('root')).render(
  <StrictMode>
    <App />
  </StrictMode>,
)

/**
 * `react` СТАВИТСЯ, КОГДА В КОРНЕ ЧТО-ТО ПОЯВИЛОСЬ, а не через один кадр после
 * render(). Одного кадра не хватает: React успевает смонтироваться позже, и
 * прогон на проде это показал — стадия шла html → bundle → data, минуя react
 * вовсе. Для сторожа это опаснее, чем кажется: приложение, которое нарисовалось,
 * но ждёт медленную базу, выглядело бы «не поднявшимся», и человек получил бы
 * экран ошибки поверх работающего приложения.
 *
 * Поэтому смотрим каждый кадр, пока не появится содержимое. Потолок в десять
 * секунд — чтобы цикл не жил вечно на странице, которая и правда не поднялась:
 * там своё слово скажет сторож.
 */
const ждёмПервыйКадр = (дедлайн = Date.now() + 10000) => {
  const root = document.getElementById('root')
  if (root && root.childElementCount > 0) {
    window.__bootStage?.('react')
    убратьМгновенныйЛендинг()
    return
  }
  if (Date.now() < дедлайн) requestAnimationFrame(() => ждёмПервыйКадр(дедлайн))
}
requestAnimationFrame(() => ждёмПервыйКадр())
// Страховка: даже если первый кадр не отметился (фоновая вкладка), через
// 12 секунд мгновенный лендинг уходит сам, когда приложение уже на экране.
setTimeout(() => { if (document.getElementById('root')?.childElementCount) убратьМгновенныйЛендинг(0) }, 12000)

/**
 * МГНОВЕННЫЙ ЛЕНДИНГ (index.html, #zl-pre) уступает место настоящему.
 *
 * Убираем, когда React нарисовал свой лендинг клуба — тогда подмена незаметна.
 * Если приложение решило лендинг не показывать (например, сессия всё-таки
 * нашлась), ждём не дольше 4 секунд после первого кадра и убираем всё равно,
 * чтобы слой не закрыл собой приложение.
 */
function убратьМгновенныйЛендинг(дедлайн = Date.now() + 4000) {
  const pre = document.getElementById('zl-pre')
  if (!pre) return
  const настоящий = document.querySelector('[data-testid="club-landing"]')
  if (настоящий || Date.now() > дедлайн) {
    // Человек мог уже пролистать мгновенный лендинг — оставляем его на том же месте.
    if (настоящий && pre.scrollTop > 0) настоящий.scrollTop = pre.scrollTop
    pre.remove()
    return
  }
  // setTimeout, а не requestAnimationFrame: в фоновой вкладке кадры не идут,
  // и слой мог бы остаться поверх приложения.
  setTimeout(() => убратьМгновенныйЛендинг(дедлайн), 100)
}
