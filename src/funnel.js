/**
 * СЧЁТЧИК ВОРОНКИ НА КЛИЕНТЕ — этап 0 гостевого режима.
 *
 * Зачем. Переходы из Инстаграма есть, регистраций почти нет. Прежде чем убирать
 * стену регистрации, нужен способ увидеть, помогло ли: продуктовой аналитики в
 * проекте нет вовсе, и «стало лучше» пришлось бы определять на глаз.
 *
 * ЧТО УХОДИТ НАРУЖУ: одно слово — имя события. Ни личности, ни устройства, ни
 * содержимого экрана; приёмник (api/set-exercise.js, ветка `?action=funnel`)
 * складывает их в посуточные счётчики, где строку не с чем связать.
 *
 * ОТПРАВКА — «БРОСИЛ И ЗАБЫЛ». Ничего не ждём, ошибок не показываем, ответ не
 * читаем. Счётчик не имеет права ни задержать экран, ни сломать заход: человек
 * пришёл тренироваться, а не помогать нам считать.
 */

/** Адрес приёмника — ветка существующей ручки: новых файлов в api/ заводить нельзя. */
const ENDPOINT = '/api/set-exercise?action=funnel'

/**
 * СОБЫТИЯ РАЗ В СУТКИ, а не на каждый показ.
 *
 * `open` иначе считал бы не людей, а перерисовки: экран входа монтируется
 * заново после каждого возврата назад, после неудачной попытки входа и после
 * восстановления связи. Отношение «открыли → завелись» при этом поехало бы вниз
 * без всякой причины, и мы бы чинили несуществующую проблему.
 *
 * `migrated` — по той же причине. Перенос гостевых данных случается один раз
 * на человека, но зовётся он из четырёх эффектов загрузки дневника; барьер в
 * `foodDiaryMigrate.js` не даёт им перенести дважды, а этот дедуп — посчитать
 * дважды, если барьер сбросится перезагрузкой страницы посреди переноса.
 *
 * Список отдельный, а не «всё подряд раз в сутки»: у событий ценности и
 * предложений смысл ровно в количестве — человек может доиграть трижды за
 * вечер, и это три разных момента, а не один.
 */
const DAILY = new Set([
  'open',
  // Гость открыл приложение. Считается по тем же причинам, что и `open`: экран
  // перерисовывается от любого возврата назад, а нам нужны люди, а не рендеры.
  'open_guest',
  // «Потрогал раздел» — про то, дошёл ли человек до сути, а не сколько раз он
  // переключал вкладки за вечер. Второе заход не характеризует вовсе.
  'try_motion',
  'try_workout',
  'try_diary',
  'migrated',
  /**
   * СТУПЕНИ ВОРОНКИ ЧЕЛЛЕНДЖА — все посуточно, и это не осторожность.
   *
   * Здесь считаются ЛЮДИ, а не нажатия: продажа — решение, которое человек
   * принимает один раз за вечер, и второй заход на ту же страницу не делает
   * его вторым покупателем. Считать нажатия значило бы получить воронку, где
   * «открыли страницу» больше «зашли в приложение», — по ней нельзя принять ни
   * одного решения.
   */
  'ch_open',
  'ch_rules',
  'ch_join',
  'ch_signup',
  'ch_pay',
])

/** Дата в UTC — той же, по которой считает база (см. funnel_bump). */
function todayUtc() {
  return new Date().toISOString().slice(0, 10)
}

/**
 * ВНУТРИ TELEGRAM НЕ СЧИТАЕМ.
 *
 * Mini App — другой вход с другой воронкой: там человек уже в мессенджере,
 * авторизация идёт своим путём (api/telegram-auth.js), и стены регистрации,
 * ради которой всё затевается, он не видит вовсе. Смешать эти цифры с
 * веб-заходами значит испортить и те и другие.
 */
function isTelegram() {
  try {
    return !!globalThis.Telegram?.WebApp?.initData
  } catch {
    return false
  }
}

/**
 * Отметить событие воронки.
 *
 * @param {string} event имя из списка приёмника; незнакомое он молча отбросит
 */
export function bump(event) {
  try {
    if (isTelegram()) return

    if (DAILY.has(event)) {
      const key = `fitpro_funnel_${event}_${todayUtc()}`
      // Хранилище может быть недоступно (приватный режим, отключённые куки) —
      // тогда дедуп просто не работает, а событие всё равно уходит: потерять
      // счёт хуже, чем посчитать дважды.
      if (localStorage.getItem(key)) return
      localStorage.setItem(key, '1')
    }

    fetch(ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ event }),
      // keepalive: событие часто отмечается ровно перед уходом со страницы
      // (регистрация уводит на другой экран), и без него браузер обрывает
      // запрос на размонтировании
      keepalive: true,
    }).catch(() => {})
  } catch {
    // Счётчик сломался — приложение работает. Молчим.
  }
}
