/**
 * ПРОВЕРКА СТРАХОВОК ОТ ЧЁРНОГО ЭКРАНА — до сборки и до браузера.
 *
 * Авария 19.08 случилась не в коде приложения, а в кэшировании: страница
 * кэшировалась наравне с файлами сборки, а файлы сборки — не кэшировались вовсе.
 * Телефон с вчерашней страницей просил вчерашний файл, получал 404 и показывал
 * человеку голый фон. Всё, что тогда починили, держится на трёх вещах, и каждая
 * из них — одна строка, которую легко потерять при следующей правке:
 *
 *   1. /assets/* отдаются годом и immutable — имена с хэшем не меняются;
 *   2. страница отдаётся no-store — она одна связывает браузер с именами
 *      текущей выкладки, и устаревшая копия означает 404 и пустой экран;
 *   3. в index.html живёт страховка перезахода — единственное место, откуда
 *      можно спастись, потому что само приложение в таком заходе не стартует.
 *
 * Прогон в WebKit (test-webkit-boot.mjs) проверяет ПОВЕДЕНИЕ и требует сборки и
 * браузера. Этот файл проверяет НАСТРОЙКИ, стоит секунду и падает первым — чтобы
 * потерянный заголовок было видно сразу, а не после пятнадцати минут прогона.
 *
 * Запуск: node tools/webkit-check.mjs
 */
import { readFileSync, existsSync } from 'node:fs'

const провалы = []
const ок = (что) => console.log('  ✓ ' + что)

// ── 1. заголовки кэша ───────────────────────────────────────────────────────
console.log('заголовки кэша (vercel.json):')
if (!existsSync('vercel.json')) {
  провалы.push('нет vercel.json — заголовки кэша задавать негде')
} else {
  const сырой = readFileSync('vercel.json', 'utf8')
  let cfg = null
  try {
    cfg = JSON.parse(сырой)
  } catch (e) {
    провалы.push('vercel.json не разбирается как JSON: ' + e.message)
  }

  /**
   * КЛЮЧИ-КОММЕНТАРИИ «//» ВАЛЯТ СБОРКУ. Vercel проверяет vercel.json по схеме и
   * отбивает любое лишнее поле: «headers[0] should NOT have additional property
   * "//"». Приём из package.json тут не работает, и цена ошибки высокая — деплой
   * не собирается вовсе, а прод молча остаётся на старой выкладке. Поэтому
   * объяснения к правилам живут здесь, в коде проверки, а не в самом конфиге.
   */
  const комментарии = []
  ;(function обойти(узел, путь) {
    if (Array.isArray(узел)) return узел.forEach((э, i) => обойти(э, `${путь}[${i}]`))
    if (!узел || typeof узел !== 'object') return
    for (const ключ of Object.keys(узел)) {
      if (ключ === '//' || ключ.startsWith('//')) комментарии.push(`${путь}.${ключ}`)
      обойти(узел[ключ], путь ? `${путь}.${ключ}` : ключ)
    }
  })(cfg, '')
  for (const место of комментарии) {
    провалы.push(`в vercel.json ключ-комментарий ${место} — Vercel такое поле не принимает, сборка не пройдёт`)
  }
  if (cfg && !комментарии.length) ок('разбирается как JSON, ключей-комментариев нет')

  const правила = cfg?.headers ?? []
  /** Значение Cache-Control для пути, как его увидит браузер. */
  const кэшДля = (source) =>
    правила
      .find((п) => п.source === source)
      ?.headers?.find((h) => h.key.toLowerCase() === 'cache-control')
      ?.value ?? null

  /**
   * Файлы сборки помечены хэшем: содержимое по такому имени не меняется никогда.
   * Год в кэше и immutable — чтобы телефон не ходил за ними по сети на каждом
   * заходе. До аварии они отдавались с max-age=0, то есть ровно наоборот.
   */
  const assets = кэшДля('/assets/(.*)')
  if (!assets) провалы.push('для /assets/* не задан Cache-Control')
  else if (!/max-age=31536000/.test(assets) || !/immutable/.test(assets)) {
    провалы.push(`/assets/* должны быть год и immutable, а стоит: ${assets}`)
  } else ок('/assets/* — ' + assets)

  /**
   * А сама страница не кэшируется вовсе. Она — единственное, что связывает
   * браузер с именами файлов текущей выкладки, и устаревшая копия означает
   * запрос к именам, которых на сервере уже нет: 404 и пустой экран.
   * must-revalidate тут мало: телефон отдаёт такую страницу из кэша на плохой
   * связи и в WebView Telegram.
   */
  for (const путь of ['/', '/index.html']) {
    const стр = кэшДля(путь)
    if (!стр) провалы.push(`для ${путь} не задан Cache-Control — страница будет кэшироваться`)
    else if (!/no-store/.test(стр)) провалы.push(`${путь} обязан быть no-store, а стоит: ${стр}`)
    else ок(`${путь} — ${стр}`)
  }
}

// ── 2. страховка перезахода в самой странице ────────────────────────────────
console.log('страховка перезахода (index.html):')
if (!existsSync('index.html')) {
  провалы.push('нет index.html')
} else {
  const html = readFileSync('index.html', 'utf8')
  const требуется = [
    // повод для перезахода — не «долго пусто», а неудачная загрузка файла сборки
    [/addEventListener\(\s*['"]error['"]/, 'нет слушателя ошибок загрузки'],
    [/\/assets\//, 'слушатель не отличает файлы сборки от прочих'],
    // перезаход ровно один, иначе бесконечная перезагрузка
    [/sessionStorage/, 'нет отметки о перезаходе — возможна вечная перезагрузка'],
    [/location\.replace|location\.href|location\.reload/, 'нет самого перезахода'],
  ]
  const было = провалы.length
  for (const [что, чего] of требуется) if (!что.test(html)) провалы.push('в index.html ' + чего)
  if (провалы.length === было) ок('слушатель ошибки, отметка о единственном перезаходе, перезаход')
}

// ── 3. допущение, на котором всё держится ───────────────────────────────────
/**
 * Страховка имеет смысл, только пока имена файлов сборки содержат хэш: именно
 * поэтому старое имя пропадает с сервера. Если сборку однажды переведут на
 * постоянные имена, проверка ниже об этом скажет.
 */
if (existsSync('dist/index.html')) {
  const dist = readFileSync('dist/index.html', 'utf8')
  const входной = dist.match(/assets\/(index-[A-Za-z0-9_-]{6,}\.js)/)?.[1]
  console.log('имена сборки:')
  if (!входной) провалы.push('в собранной странице нет входного файла с хэшем — прогон в WebKit не построится')
  else ок(входной)
}

if (провалы.length) {
  console.error('\nСТРАХОВКИ: ПРОВАЛ')
  for (const п of провалы) console.error('  - ' + п)
  process.exit(1)
}
console.log('\nСТРАХОВКИ НА МЕСТЕ')
