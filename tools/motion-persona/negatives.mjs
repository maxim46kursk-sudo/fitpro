/**
 * ОТРИЦАТЕЛЬНЫЕ ПРОГОНЫ: судья ОБЯЗАН насчитать ноль.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ОСТАЛЬНЫХ ТЕСТОВ. Всё, что у нас было, проверяло, что
 * судья ЗАСЧИТЫВАЕТ движение. Ни одна проверка не спрашивала обратного — что
 * он не засчитывает то, чего не было. Именно там и жила жалоба владельца:
 * повторы шли у неподвижного человека, у человека, влезшего в кадр по плечи, и
 * присед уходил в зачёт как выпад.
 *
 * Три случая ниже — ровно эти три. Каждый обязан дать НОЛЬ. Насчитал хоть
 * что-то — прогон красный, и это не «подкрутить порог», это регрессия.
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ run.mjs. Тот гоняет полную сессию в настоящем браузере
 * с настоящим MediaPipe — семнадцать минут и недетерминированное распознавание
 * нарисованной фигуры. Для отрицательных случаев это плохой инструмент: «модель
 * не нашла таз» и «судья не должен был считать» там неразличимы, а красный
 * прогон обязан означать ровно одно. Поэтому здесь в судью подаются ГОТОВЫЕ
 * точки с известной видимостью — то есть проверяется именно судейство, а не
 * распознавание. Судья при этом настоящий: тот же createRepCounter и тот же
 * createCatcher, что уезжают людям.
 *
 * Запуск: npm run test:motion-negatives
 */
import { LM } from '../../src/motion/pose/landmarks.js'
import { createRepCounter } from '../../src/motion/game/strength.js'
import { createCatcher } from '../../src/motion/game/catcher.js'

const ЧАСТОТА = 30
const ШАГ = 1000 / ЧАСТОТА

/**
 * Тело в нормированных координатах кадра. y растёт вниз, как у MediaPipe.
 *
 * @param {object} o
 * @param {number} o.hip высота таза (0 — верх кадра, 1 — низ)
 * @param {number} o.knee сгиб: 0 — нога прямая, 1 — колено у таза
 * @param {number} o.backLeft насколько левая стопа ушла НАЗАД (в глубину)
 * @param {number} o.vis видимость всех точек ниже плеч
 */
function тело({ hip = 0.52, knee = 0, backLeft = 0, vis = 0.95 } = {}) {
  const точки = Array.from({ length: 33 }, () => ({ x: 0.5, y: 0.5, z: 0, visibility: vis }))
  const п = (i, x, y, z = 0, v = vis) => {
    точки[i] = { x, y, z, visibility: v }
  }

  // голова и плечи видны всегда: именно так выглядел кадр на скринах владельца
  п(LM.NOSE, 0.5, hip - 0.34, 0, 0.99)
  п(LM.LEFT_SHOULDER, 0.43, hip - 0.24, 0, 0.99)
  п(LM.RIGHT_SHOULDER, 0.57, hip - 0.24, 0, 0.99)

  п(LM.LEFT_HIP, 0.45, hip)
  п(LM.RIGHT_HIP, 0.55, hip)

  // колено идёт вверх к тазу по мере сгиба, стопа остаётся на полу
  const бедро = 0.17 * (1 - 0.45 * knee)
  const голень = 0.17 * (1 - 0.45 * knee)
  п(LM.LEFT_KNEE, 0.45, hip + бедро)
  п(LM.RIGHT_KNEE, 0.55, hip + бедро)
  п(LM.LEFT_ANKLE, 0.45, hip + бедро + голень, backLeft)
  п(LM.RIGHT_ANKLE, 0.55, hip + бедро + голень, 0)
  п(LM.LEFT_HEEL, 0.45, hip + бедро + голень + 0.01, backLeft)
  п(LM.RIGHT_HEEL, 0.55, hip + бедро + голень + 0.01, 0)
  п(LM.LEFT_FOOT_INDEX, 0.45, hip + бедро + голень + 0.03, backLeft)
  п(LM.RIGHT_FOOT_INDEX, 0.55, hip + бедро + голень + 0.03, 0)
  return точки
}

/**
 * МИРОВЫЕ ТОЧКИ — НАСТОЯЩАЯ ТРЁХМЕРНАЯ ГЕОМЕТРИЯ, а не копия кадра.
 *
 * Это не мелочь: угол в колене судья считает ИМЕННО по мировым точкам
 * (angleAt3D в squat.js). Скопируй сюда плоский кадр, где таз, колено и стопа
 * стоят на одной вертикали, — и угол всегда 180°, то есть нога всегда прямая,
 * и ни один присед не засчитается. Первый вариант этого файла так и молчал:
 * три нуля были на месте, а контрольный прогон показал ноль там, где обязан
 * был показать повторы. Ровно ради этого контроль и стоит.
 *
 * Здесь колено уходит ВПЕРЁД (к камере, z отрицательный) по мере приседа:
 * таз и стопа на месте, колено выдвигается, угол между «колено→таз» и
 * «колено→стопа» едет со 180° до 90°.
 */
function мир({ knee = 0, backLeft = 0, vis = 0.95 } = {}) {
  const точки = Array.from({ length: 33 }, () => ({ x: 0, y: 0, z: 0, visibility: vis }))
  const п = (i, x, y, z) => {
    точки[i] = { x, y, z, visibility: vis }
  }
  п(LM.LEFT_SHOULDER, -0.18, -0.5, 0)
  п(LM.RIGHT_SHOULDER, 0.18, -0.5, 0)
  п(LM.LEFT_HIP, -0.1, 0, 0)
  п(LM.RIGHT_HIP, 0.1, 0, 0)
  // вынос колена вперёд: 0 — нога прямая (180°), 0.4 — угол 90°
  const вперёд = 0.4 * knee
  п(LM.LEFT_KNEE, -0.11, 0.4, -вперёд)
  п(LM.RIGHT_KNEE, 0.11, 0.4, -вперёд)
  // стопа: ушедшая назад нога даёт ПЛЮС по z (дальше от камеры)
  п(LM.LEFT_ANKLE, -0.1, 0.8, backLeft)
  п(LM.RIGHT_ANKLE, 0.1, 0.8, 0)
  return точки
}

/**
 * ТОЛЬКО ГОЛОВА И ПЛЕЧИ В КАДРЕ.
 *
 * Так это и приходит от MediaPipe: модель отдаёт все 33 точки ВСЕГДА и
 * достраивает те, которых не видит. Значит у таза и коленей есть координаты —
 * просто выдуманные, и видимость у них низкая. Ровно это и подаём: координаты
 * есть, видимость 0.05, часть точек уехала за нижний край кадра.
 */
function поПлечи(кадр) {
  return кадр.map((p, i) => {
    const ниже = [
      LM.LEFT_HIP, LM.RIGHT_HIP, LM.LEFT_KNEE, LM.RIGHT_KNEE,
      LM.LEFT_ANKLE, LM.RIGHT_ANKLE, LM.LEFT_HEEL, LM.RIGHT_HEEL,
      LM.LEFT_FOOT_INDEX, LM.RIGHT_FOOT_INDEX,
    ]
    if (!ниже.includes(i)) return p
    return { ...p, y: p.y + 0.55, visibility: 0.05 }
  })
}

/** Плавная волна 0..1..0 — одно повторение движения. */
const волна = (доля) => (1 - Math.cos(доля * 2 * Math.PI)) / 2

// ─────────────────────────────────────────────────────────────── прогоны ───

let провалов = 0

function прогон(имя, ожидание, факт) {
  const ок = факт.reps === 0
  if (!ок) провалов += 1
  const метка = ок ? '✓ НОЛЬ' : '✗ НАСЧИТАЛ'
  console.log(`${метка}  ${имя}`)
  console.log(`        ждём: ${ожидание}`)
  console.log(`        вышло: повторов ${факт.reps}${факт.детали ? `, ${факт.детали}` : ''}`)
}

/**
 * Прогнать движение через настоящий счётчик повторов.
 * @param {string} движение barrier | lunge | jack
 * @param {(доля:number, i:number)=>Array} кадр как выглядит тело на кадре i
 */
function судить(движение, секунд, поза) {
  const счётчик = createRepCounter(движение, {})
  let reps = 0
  const всего = Math.round((секунд * 1000) / ШАГ)
  for (let i = 0; i < всего; i += 1) {
    const t = i * ШАГ
    const п = поза(i / всего, i)
    reps += счётчик.update(t, { landmarks: п.landmarks, worldLandmarks: п.world }) || 0
  }
  const попытки = счётчик.attempts()
  return { reps, детали: `попыток в журнале ${попытки.length}` }
}

/** Поза целиком: кадр и мировые точки из одних и тех же параметров. */
const поза = (o = {}) => ({ landmarks: тело(o), world: мир(o) })

console.log('ОТРИЦАТЕЛЬНЫЕ ПРОГОНЫ СУДЕЙСТВА — каждый обязан дать ноль\n')

// ── 1. человек стоит неподвижно ────────────────────────────────────────────
{
  const стоит = () => поза({ hip: 0.52, knee: 0 })
  const присед = судить('barrier', 20, стоит)
  const выпад = судить('lunge', 20, стоит)
  прогон(
    '1. Человек стоит неподвижно (20 с, полностью в кадре)',
    'ноль: движения не было',
    { reps: присед.reps + выпад.reps, детали: `присед ${присед.reps}, выпад ${выпад.reps}` },
  )
}

// ── 2. в кадре только голова и плечи ───────────────────────────────────────
{
  /**
   * Человек при этом ДВИГАЕТСЯ по-настоящему — приседает. Это и есть суть
   * случая: движение есть, но судить его нечем, потому что таз и колени
   * достроены. Прежний код считал бы такой присед за присед.
   */
  const шаг = (доля) => ({ hip: 0.52 + 0.1 * волна(доля * 8), knee: волна(доля * 8) })
  const кадр = (доля) => ({ landmarks: поПлечи(тело(шаг(доля))), world: мир(шаг(доля)) })
  const присед = судить('barrier', 20, кадр)
  const выпад = судить('lunge', 20, кадр)

  // и ловец мишеней на тех же кадрах
  const ловец = createCatcher({ rng: () => 0.5 })
  let зачётов = 0
  for (let i = 0; i < 600; i += 1) {
    for (const e of ловец.update(i * ШАГ, кадр(i / 600).landmarks)) if (e.kind === 'clear') зачётов += 1
  }

  прогон(
    '2. В кадре только голова и плечи (приседает, таз и колени достроены)',
    'ноль: судить нечем — точки невидимы',
    {
      reps: присед.reps + выпад.reps + зачётов,
      детали: `присед ${присед.reps}, выпад ${выпад.reps}, мишеней поймано ${зачётов}`,
    },
  )
}

// ── 3. просят выпад, сделан присед ─────────────────────────────────────────
{
  /**
   * Настоящий присед, целиком в кадре, обе стопы на месте: назад не уходит
   * НИ ОДНА. Таз при этом проседает — а просадка таза общая у приседа и
   * выпада, и раньше её хватало, чтобы присед ушёл в зачёт выпадом.
   */
  const присед = (доля) => поза({ hip: 0.52 + 0.11 * волна(доля * 8), knee: волна(доля * 8), backLeft: 0 })
  const итог = судить('lunge', 20, присед)
  прогон(
    '3. Просят выпад — сделан присед (обе стопы на месте)',
    'ноль: просадка таза есть, ухода ноги назад нет',
    итог,
  )
}

/**
 * КОНТРОЛЬНЫЙ ПРОГОН: настоящая работа обязана считаться.
 *
 * БЕЗ ЭТОГО ТРИ НУЛЯ ВЫШЕ НИЧЕГО НЕ СТОЯТ. Судья, который не считает ВООБЩЕ
 * ничего, проходит все три отрицательных прогона идеально. Отличить починку от
 * поломки можно только одним способом — рядом с тремя нулями должен стоять
 * честный ненулевой счёт. Это тот же присед, что в случае 3, только судимый
 * как присед, а не как выпад.
 */
{
  const присед = (доля) => поза({ hip: 0.52 + 0.11 * волна(доля * 8), knee: волна(доля * 8) })
  const итог = судить('barrier', 20, присед)
  const ок = итог.reps > 0
  if (!ок) провалов += 1
  console.log(`${ок ? '✓ СЧИТАЕТ' : '✗ НЕ СЧИТАЕТ'}  Контроль: настоящий присед целиком в кадре`)
  console.log('        ждём: больше нуля — иначе три нуля выше ничего не доказывают')
  console.log(`        вышло: повторов ${итог.reps}`)
}

console.log(
  `\nИтог: ${провалов === 0 ? 'ТРИ НУЛЯ + КОНТРОЛЬ СЧИТАЕТ' : `ПРОВАЛЕНО ПРОГОНОВ: ${провалов}`}`,
)
process.exit(провалов ? 1 : 0)
