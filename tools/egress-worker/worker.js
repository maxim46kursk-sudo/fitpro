/**
 * МОСТ НАРУЖУ — ретранслятор для двух API, недостижимых с нашего сервера.
 *
 * Зачем. Приложение переезжает с Vercel на свой сервер в России, и оттуда:
 *   api.anthropic.com  — отвечает 403 «Request not allowed» по обоим
 *     протоколам (блокировка по стране, ключ ни при чём: тот же ключ с
 *     машины владельца работает);
 *   api.telegram.org   — по IPv4 соединение не устанавливается вовсе, а по
 *     IPv6 запрос доходит до настоящего Telegram, но на ЗАВЕДОМО ВЕРНЫЙ токен
 *     приходит 401.
 * Без моста после переключения домена молча отвалятся ИИ-ассистент,
 * распознавание этикеток, вход через Telegram, напоминания, тревоги тренеру и
 * выгрузка данных.
 *
 * Что это. Прозрачный ретранслятор: метод, тело и заголовки уходят наверх как
 * есть, ответ возвращается как есть. Никакой логики про FitPro здесь нет и
 * быть не должно — воркер не знает ни про пакеты, ни про пользователей, ни про
 * то, что за токен едет мимо него. Он знает только два адреса и один ключ.
 *
 * Развёртывание — tools/egress-worker/wrangler.toml, секрет RELAY_KEY кладётся
 * командой `wrangler secret put RELAY_KEY` и в relay-key.txt в корне (вне
 * гита, как monitor-key.txt).
 */

/**
 * КУДА ПУСКАЕМ. Ровно два адреса, перечисленные поимённо.
 *
 * Не «любой хост из заголовка» и не «что просили, туда и сходим»: открытый
 * ретранслятор в интернете живёт часами до того, как его найдут и начнут
 * прокачивать через него что угодно — от накрутки до атак, и отвечать за это
 * будет владелец аккаунта. Новый адрес добавляется правкой этой таблицы, и
 * никак иначе.
 */
const ROUTES = {
  '/tg/': 'https://api.telegram.org/',
  '/ai/': 'https://api.anthropic.com/',
}

/**
 * ЗАГОЛОВКИ, КОТОРЫЕ НАВЕРХ НЕ ЕДУТ.
 *
 * x-relay-key — наш пропуск, и дальше моста ему делать нечего: он не нужен ни
 * Telegram, ни Anthropic, а попадать в чужие журналы секрету незачем.
 * Остальное добавляет сама Cloudflare (адрес звонившего, идентификатор
 * запроса, страна); наверх это уехало бы как приписка от нас, хотя мы её не
 * писали. Host не трогаем руками — его подставит fetch по адресу назначения,
 * и подставит правильно.
 */
const DROP_HEADERS = new Set([
  'x-relay-key',
  'host',
  'cf-connecting-ip',
  'cf-ipcountry',
  'cf-ray',
  'cf-visitor',
  'cf-worker',
  'x-forwarded-for',
  'x-forwarded-proto',
  'x-real-ip',
  // Заголовки одного участка связи (hop-by-hop). Их значения описывают ИМЕННО
  // соединение с нами и к следующему участку отношения не имеют: длина тела
  // после переупаковки другая, сжатие пересогласовывается заново. Пробрось их
  // дальше — и наверх уедет неверная content-length.
  'content-length',
  'transfer-encoding',
  'connection',
  'keep-alive',
  'upgrade',
  'accept-encoding',
])

/**
 * ЗАГОЛОВКИ, КОТОРЫЕ НЕ ВОЗВРАЩАЕМ ВНИЗ.
 *
 * Workers распаковывает тело ответа сам, а заголовок про сжатие остаётся —
 * и звонивший распаковывает уже распакованное, получая двоичный мусор вместо
 * JSON. Ровно так мост однажды и ответил при проверке: HTTP 400 и байты,
 * которые не разобрал ни один парсер. Длину и способ передачи ниже тоже
 * пересчитает среда.
 */
const DROP_RESPONSE_HEADERS = new Set([
  'content-encoding',
  'content-length',
  'transfer-encoding',
  'connection',
  'keep-alive',
])

/**
 * Сверка ключа за постоянное время.
 *
 * Обычное === на секрете сравнивает посимвольно и выходит на первом
 * несовпадении: на потоке запросов разница во времени ответа выдаёт длину
 * общего префикса, и ключ подбирается по одному символу. Та же причина, по
 * которой в api/set-exercise.js своя `секретСовпал` для MONITOR_KEY.
 *
 * У Cloudflare для этого есть crypto.subtle.timingSafeEqual; он требует
 * одинаковой длины, поэтому длину сверяем заранее — она и так не секрет.
 * Запасной путь на случай, если метода в среде не окажется: XOR по всем
 * байтам без досрочного выхода.
 */
function секретСовпал(дано, ожидается) {
  if (typeof дано !== 'string' || typeof ожидается !== 'string') return false
  const a = new TextEncoder().encode(дано)
  const b = new TextEncoder().encode(ожидается)
  if (a.length !== b.length || a.length === 0) return false
  if (crypto.subtle?.timingSafeEqual) return crypto.subtle.timingSafeEqual(a, b)
  let diff = 0
  for (let i = 0; i < a.length; i++) diff |= a[i] ^ b[i]
  return diff === 0
}

/**
 * ОДИН ОТВЕТ НА ВСЕ ОТКАЗЫ — пустой 404.
 *
 * Ни «нужен ключ», ни «ключ неверный», ни «такого маршрута нет». Мост, который
 * объясняет, чего ему не хватило, сам рассказывает, как его открыть: сначала
 * находят, что ключ вообще нужен, потом — что маршрутов ровно два. Молчаливый
 * 404 выглядит как несуществующий адрес, каких у Cloudflare миллионы.
 */
const молча404 = () => new Response(null, { status: 404 })

export default {
  async fetch(request, env) {
    const secret = env.RELAY_KEY
    // Ключ не настроен — мост закрыт целиком. Открытый по недосмотру
    // ретранслятор хуже неработающего.
    if (!secret) return молча404()
    if (!секретСовпал(request.headers.get('x-relay-key'), secret)) return молча404()

    const url = new URL(request.url)
    const prefix = Object.keys(ROUTES).find(p => url.pathname.startsWith(p))
    if (!prefix) return молча404()

    /**
     * Хвост пути и строка запроса едут как есть: getMe, sendDocument,
     * /v1/messages — мост о них не знает и знать не должен.
     *
     * СКЛЕИВАЕМ СТРОКОЙ, А НЕ `new URL(хвост, база)`, и это не вкусовщина.
     * В адресе Telegram токен идёт прямо в пути — /bot<id>:<секрет>/getMe, — а
     * относительный разбор видит в `bot8660150233:AAF…` схему `bot8660150233:`
     * и считает адрес абсолютным. База при этом отбрасывается целиком, запрос
     * уходит в никуда, и мост отвечает пустым 500. Ровно на этом он и упал при
     * первой проверке.
     */
    const target = ROUTES[prefix] + url.pathname.slice(prefix.length) + url.search

    /**
     * И раз адрес собран строкой — проверяем, куда он в итоге показывает.
     * Хвост приходит снаружи, а `//чужой.хост` или `..` в нём превратили бы
     * склейку в обход белого списка. Сверка origin оставляет от списка ровно
     * то, чем он и был: два адреса, и никаких других.
     */
    let targetUrl
    try {
      targetUrl = new URL(target)
    } catch {
      return молча404()
    }
    if (targetUrl.origin !== new URL(ROUTES[prefix]).origin) return молча404()

    const headers = new Headers()
    for (const [name, value] of request.headers) {
      if (!DROP_HEADERS.has(name.toLowerCase())) headers.set(name, value)
    }

    /**
     * ТЕЛО ПРОБРАСЫВАЕТСЯ ПОТОКОМ, А НЕ ЧЕРЕЗ РАЗБОР.
     *
     * Так multipart из sendDocument (выгрузка данных человека уезжает файлом)
     * доходит нетронутым вместе со своей границей и бинарным содержимым.
     * Прочитай мы тело и собери заново — сломалась бы ровно эта отправка, и
     * сломалась бы молча: Telegram ответил бы отказом на разбор формы.
     */
    const upstream = new Request(targetUrl, {
      method: request.method,
      headers,
      body: request.method === 'GET' || request.method === 'HEAD' ? undefined : request.body,
      redirect: 'manual',
    })

    /**
     * Сбой сети наверх отдаём как 502, а не как пустой 500: 500 от воркера
     * означает «мост сломан», 502 — «мост цел, источник не ответил». Разница
     * стоит одной строки, а при разборе экономит час.
     */
    let response
    try {
      response = await fetch(upstream)
    } catch {
      return new Response(null, { status: 502 })
    }

    // Ответ возвращаем как есть — со статусом и заголовками источника, кроме
    // тех, что описывают наше с ним соединение. Тому, кто звонил, мост должен
    // быть неотличим от прямого обращения.
    const respHeaders = new Headers()
    for (const [name, value] of response.headers) {
      if (!DROP_RESPONSE_HEADERS.has(name.toLowerCase())) respHeaders.set(name, value)
    }
    return new Response(response.body, {
      status: response.status,
      statusText: response.statusText,
      headers: respHeaders,
    })
  },
}
