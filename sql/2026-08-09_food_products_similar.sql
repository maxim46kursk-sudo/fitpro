-- Поиск похожей карточки — ДЛЯ ВОПРОСА ЧЕЛОВЕКУ, а не для автоматического
-- слияния.
--
-- Дополняет 2026-08-09_food_products_aliases.sql. Там появилась link_barcode,
-- которая привязывает ещё один штрих-код к существующей карточке; сама
-- привязка правильная и остаётся как есть. Неправильным было РЕШЕНИЕ о ней:
-- совпадение названия и марки принималось за доказательство, что это тот же
-- товар.
--
-- ПОЧЕМУ ЭТО ОПАСНО. У производителя линейка вкусов, а модель, читая пачку,
-- называет их одинаково. В справочнике прямо сейчас две строки «Зефир с
-- кусочками брусники» NEO botanica с разными числами — и это РАЗНЫЕ вкусы, а
-- не дубль. Автоматическое слияние подставило бы человеку чужие КБЖУ, причём
-- незаметно: числа выглядят правдоподобно, проверить их не по чему.
--
-- Поэтому здесь только ЧТЕНИЕ: находим кандидата, показываем обе карточки
-- рядом и спрашиваем прямо — тот же продукт или другой вкус. Решает человек.
--
-- Порядок выбора кандидата ТОТ ЖЕ, что в link_barcode, и это обязательно:
-- человеку показывают одну карточку, а привязка потом ищет её сама. Разъедься
-- сортировки — и код привязался бы не к той строке, которую человек одобрил.
create or replace function find_product_by_name(p_barcode text, p_name text, p_brand text)
returns food_products
language sql
stable
security definer
set search_path = public
as $$
  select fp.*
    from food_products fp
   where lower(btrim(fp.name)) = lower(btrim(p_name))
     and lower(btrim(coalesce(fp.brand, ''))) = lower(btrim(coalesce(p_brand, '')))
     and fp.barcode <> p_barcode
   order by (fp.source in ('off', 'ai_photo')) desc, fp.created_at asc
   limit 1
$$;

comment on function find_product_by_name is
  'Находит карточку с тем же названием и маркой под другим штрих-кодом — чтобы СПРОСИТЬ человека, тот же это продукт или другой вкус. Само по себе совпадение названия дубля не доказывает.';
