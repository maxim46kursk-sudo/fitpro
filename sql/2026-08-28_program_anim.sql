-- Мужские программы: одна карточка с переключателем уровня + рисованные ролики.
--
-- Применять ПОСЛЕ 2026-08-28_programs_mass_men.sql.

-- 1. Группа программ. Программы с одинаковым group_key показываются в списке
--    ОДНОЙ карточкой, а уровень выбирается переключателем внутри. Ключи самих
--    шаблонов не меняются: за них держатся profiles.program и названия
--    тренировок в workouts, история не должна разъехаться.
alter table program_templates add column if not exists group_key text;

update program_templates set group_key = 'massa', updated_at = now()
 where key in ('massa-novichok', 'massa-sredniy');

-- 2. Свой контекст видео для мужских программ.
--    Контекст — это то, какой ролик показать у упражнения (сейчас 'zal' и 'dom').
--    Рисованные ролики кладём в отдельный контекст 'ris' и включаем его только
--    этим двум программам. Тогда внутри них у ВСЕХ упражнений идут рисунки, а в
--    библиотеке и в остальных программах у тех же упражнений остаются снятые
--    ролики тренера — они не затрагиваются вообще (см. pickVideo в src/App.jsx:
--    сначала берётся запрошенный контекст, и только если его нет — zal/dom).
update program_templates set context = 'ris', updated_at = now()
 where key in ('massa-novichok', 'massa-sredniy');

-- 3. Семь упражнений, заведённых под эти программы, прячем из библиотеки:
--    они нужны только внутри программы. hidden убирает упражнение из справочника
--    и пикеров, но НЕ мешает ему работать внутри программы. Упражнения самого
--    тренера в этом списке отсутствуют — их не трогаем.
update catalog_exercises set hidden = true, updated_at = now()
 where name in (
   'Жим штанги лёжа',
   'Жим штанги стоя',
   'Тяга штанги в наклоне',
   'Подъём штанги на бицепс',
   'Французский жим лёжа',
   'Жим ногами в тренажёре',
   'Разгибание ног сидя в тренажёре',
   'Подъём на носки стоя'
 );

