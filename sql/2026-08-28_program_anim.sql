-- Восемь упражнений мужских программ прячем из библиотеки: рисованные ролики
-- нужны только внутри программы, в общий справочник они не идут. hidden убирает
-- упражнение из справочника и пикеров, но НЕ мешает ему работать внутри
-- программы — там рендер идёт по имени (см. mergeCatalog и pickVideo
-- в src/App.jsx). Упражнения самого тренера не трогаем.
update catalog_exercises set hidden = true, updated_at = now()
 where name in (
   'Жим штанги лёжа',
   'Жим штанги стоя',
   'Тяга штанги в наклоне',
   'Подъём штанги на бицепс',
   'Французский жим лёжа',
   'Жим ногами в тренажёре',
   'Разгибание ног сидя в тренажёре',
   'Подъём на носки стоя'
 );

