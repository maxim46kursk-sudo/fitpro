-- ДНЕВНИК ПИТАНИЯ ЧИТАЛСЯ ЦЕЛИКОМ — КАЖДЫЙ РАЗ.
--
-- У public.food_diary не было ни одного индекса, кроме первичного ключа по id.
-- А спрашивают её всегда одинаково: «строки ЭТОГО человека за ЭТУ дату» —
-- и дневник в приложении, и таблица потока, которая складывает питание всех
-- участников за тридцать дней.
--
-- Пока в таблице двадцать три строки, это незаметно. К старту потока их станет
-- десятки тысяч: двести участников × тридцать дней × восемь записей — сорок
-- восемь тысяч, и каждый вызов challenge_standings прочитывал бы их все.
--
-- ЗАМЕР (синтетика той же формы и с теми же индексами, 25 августа):
--   200 участников:  173 мс -> 102 мс   (−41%)
--   500 участников:  399 мс -> 269 мс   (−33%)
--
-- Порядок колонок именно такой: человек первым. Так индекс годится и на
-- «весь дневник человека» (дневник за месяц, экспорт, удаление аккаунта), и на
-- «человек за дату» — а обратный порядок отвечал бы только на второе.
--
-- CONCURRENTLY здесь НЕ НУЖЕН: таблица маленькая, построение занимает
-- миллисекунды, а concurrently нельзя запускать внутри транзакции — то есть
-- и откатить нельзя, если что-то пойдёт не так.

create index if not exists food_diary_user_date_idx
  on public.food_diary (user_id, date);

-- Планировщику надо сказать, что статистика изменилась: без этого он какое-то
-- время продолжит выбирать последовательное чтение по старым оценкам.
analyze public.food_diary;
