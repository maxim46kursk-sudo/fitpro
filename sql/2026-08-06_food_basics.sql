-- Стартовый справочник базовых продуктов: public.food_basics.
--
-- Зачем: поиск в дневнике питания искал только по food_products — таблице
-- отсканированных штрих-кодов. Пока её никто не наполнил, «молоко» не
-- находится вообще, и человеку нечего добавить без упаковки в руках. Это
-- делает поиск бесполезным ровно для самого частого случая: гречка, творог,
-- яблоко — то, у чего штрих-кода нет или пачка давно выброшена.
--
-- Отдельная таблица, а не строки в food_products, и вот почему:
--  • у базовых продуктов НЕТ штрих-кода, а barcode там первичный ключ;
--  • их никто не «заводил» — это не пользовательский вклад, а константа
--    приложения, которую нельзя перезаписать сканом или фотографией;
--  • их не надо обновлять из Open Food Facts: значения взяты из таблиц
--    химического состава, они точнее того, что лежит в открытой базе.
--
-- ЗНАЧЕНИЯ. Все КБЖУ — на 100 г съедобной части, по справочным таблицам
-- химического состава российских продуктов. Где продукт меняет состав при
-- готовке (крупы, макароны, картофель, мясо), сухой и готовый вид заведены
-- ОТДЕЛЬНЫМИ позициями с явным словом в названии: «Гречка ядрица сухая» и
-- «Гречка варёная» — это разные строки с разницей в три с лишним раза, и
-- перепутать их значит промахнуться в дневнике втрое.
--
-- Чего здесь НЕТ намеренно: брендов (для них есть food_products), блюд с
-- сильно плавающим составом (шаурма, домашние салаты под майонез «на глаз») и
-- всего, что даёт меньше 10 ккал на 100 г (чай без сахара, вода, специи) —
-- такие позиции в дневнике не нужны, а список засоряют.

create table if not exists public.food_basics (
  id       serial primary key,
  name     text not null,
  -- Категория пока не показывается в интерфейсе — она для порядка в самом
  -- справочнике и для будущей группировки выдачи. Отдельной таблицы категорий
  -- не заводим: их полтора десятка и они не меняются.
  category text,
  -- not null, в отличие от food_products: у карточки из открытой базы поле
  -- вполне может быть незаполненным, а здесь мы сами отвечаем за данные —
  -- позиция без КБЖУ бесполезна и просто не попадает в справочник.
  kcal100  numeric not null,
  p100     numeric not null,
  c100     numeric not null,
  f100     numeric not null
);

-- Поиск идёт по ILIKE '%q%' по названию. Индекс по name здесь не поможет
-- (btree не работает с ведущим '%'), а таблица маленькая — полтысячи строк
-- сканируются за доли миллисекунды. Триграммный индекс завёл бы зависимость
-- от pg_trgm ради задачи, которой пока нет.

comment on table public.food_basics is
  'Стартовый справочник базовых продуктов (КБЖУ на 100 г, справочные таблицы). Только чтение через service role из api/set-exercise.js; см. sql/2026-08-06_food_basics.sql';

alter table public.food_basics enable row level security;

-- Политик нет — как и у food_products: RLS без единой политики означает
-- «запрещено всем, кроме service_role». Клиент ходит за поиском в
-- /api/set-exercise?action=food-search, а не в таблицу напрямую.
revoke all on table public.food_basics from anon, authenticated;
grant all on table public.food_basics to service_role;

-- Сид идемпотентен: повторный запуск файла не наплодит дублей.
-- Чистим и заливаем заново — таблица целиком принадлежит этой миграции,
-- пользовательских данных в ней нет и быть не может.
truncate table public.food_basics restart identity;

