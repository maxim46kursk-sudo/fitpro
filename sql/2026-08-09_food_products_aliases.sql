-- Один товар — одни цифры, сколько бы штрих-кодов на него ни навесили.
--
-- ЗАЧЕМ. Один и тот же зефир приехал в справочник дважды, под кодами
-- 2627326027856 и 1647516027856, с РАЗНЫМИ числами (138 и 135 ккал). Коды
-- разные по-настоящему: у обоих верна контрольная сумма EAN-13, общий хвост
-- 6027856, префиксы 262 (внутримагазинный) и 164 (не розничный). То есть на
-- один товар физически бывает несколько кодов, и справочник обязан это
-- пережить, а не заводить по карточке на каждый.
--
-- ВЫБОР ХРАНЕНИЯ: массив дополнительных кодов в самой строке.
--
-- Рассматривались три варианта:
--   1. Отдельная таблица связей barcode → product_id. Правильнее всего с точки
--      зрения схемы, но требует ввести суррогатный id, переписать первичный
--      ключ food_products и ВСЕ обращения к нему (ветка barcode, кэш поиска,
--      save-product, импорт OFF, дневник). Ради двух строк дублей — несоразмерно.
--   2. Отдельная строка-двойник с теми же числами. Не требует ничего вовсе, но
--      это копия: поправят числа у одной карточки — вторая останется врать.
--      «Одни цифры» тут держится только на момент записи.
--   3. Массив barcodes[] в строке товара (выбран). Единственный источник цифр
--      остаётся один — сама строка. Существующий поиск по коду НЕ переписан:
--      он как ходил в .eq('barcode', code) по первичному ключу, так и ходит, а
--      обращение к массиву добавлено ВТОРЫМ запросом и только при промахе —
--      то есть на пути, который и так собирался в сеть за Open Food Facts.
--
-- barcode остаётся первичным ключом и «главным» кодом товара; barcodes —
-- дополнительные коды того же товара. Пересечения между ними не бывает:
-- link_barcode ниже не привязывает код к строке, у которой он уже главный.

alter table food_products
  add column if not exists barcodes text[] not null default '{}';

-- Поиск по дополнительному коду. GIN — индекс для оператора @> на массивах;
-- без него запрос при промахе шёл бы последовательным чтением всей таблицы.
create index if not exists food_products_barcodes_gin
  on food_products using gin (barcodes);

-- Поиск дубля по названию и марке при сохранении карточки. Выражения в индексе
-- ТОЧНО те же, что в запросе ниже, иначе индекс не применится.
create index if not exists food_products_name_brand_idx
  on food_products (lower(btrim(name)), lower(btrim(coalesce(brand, ''))));

-- Привязка нового кода к УЖЕ СУЩЕСТВУЮЩЕЙ карточке того же товара.
--
-- Функцией, а не парой запросов из ручки, по одной причине: чтение «есть ли
-- такой товар» и дописывание кода в массив должны быть одной операцией. Иначе
-- двое, сканирующие один товар одновременно, оба увидят «карточки нет» и
-- заведут по своей — ровно тот дубль, от которого мы уходим.
--
-- security definer: ручка ходит service_role-ключом, но пусть право на запись
-- живёт в одном месте вместе с правилом, а не размазывается по ролям.
--
-- ⚠ ОСТОРОЖНО С «ВЕРНУЛА NULL»: тип возврата — food_products, ЦЕЛАЯ СТРОКА
-- ТАБЛИЦЫ. `return null` ниже отдаёт вызывающему не пустоту, а строку, у
-- которой ВСЕ поля равны NULL. Через PostgREST это приезжает объектом
-- {"barcode":null,"name":null,…}, и в JS он truthy — то есть проверка вида
-- `if (linked) { … }` пройдёт и при промахе тоже.
--
-- Это уже стоило нам ветки «Похожий продукт» в api/set-exercise.js: сестра
-- этой функции, find_product_by_name, объявлена точно так же, её пустой ответ
-- считался находкой, и сервер отвечал ok:true, не записав ничего. Человек
-- видел «сохранено», а карточки не было.
--
-- Проверять надо по НЕПУСТОМУ ПОЛЮ, а не по самому объекту:
--   if (linked?.barcode) { … }        -- правильно
--   if (linked) { … }                 -- срабатывает всегда
--
-- Саму функцию не переписываем и миграцию не откатываем: вызовов у неё больше
-- не осталось. Предупреждение — на случай, если привязку кодов когда-нибудь
-- вернут; тогда либо читать barcode, либо менять тип возврата.
create or replace function link_barcode(p_barcode text, p_name text, p_brand text)
returns food_products
language plpgsql
security definer
set search_path = public
as $$
declare
  target text;
  result food_products;
begin
  -- Кандидат ровно один, и выбор среди совпадений не случайный: сначала
  -- точные источники (данные с упаковки и из OFF), затем более старая
  -- карточка. Так победит та, что вернее и на которую уже могли сослаться.
  select fp.barcode into target
    from food_products fp
   where lower(btrim(fp.name)) = lower(btrim(p_name))
     and lower(btrim(coalesce(fp.brand, ''))) = lower(btrim(coalesce(p_brand, '')))
     and fp.barcode <> p_barcode
   order by (fp.source in ('off', 'ai_photo')) desc, fp.created_at asc
   limit 1;

  if target is null then
    return null;
  end if;

  update food_products fp
     set barcodes = case when fp.barcodes @> array[p_barcode]
                         then fp.barcodes
                         else array_append(fp.barcodes, p_barcode) end
   where fp.barcode = target
  returning fp.* into result;

  return result;
end
$$;

comment on function link_barcode is
  'Привязывает ещё один штрих-код к существующей карточке того же товара (по названию и марке без учёта регистра и краевых пробелов). Возвращает карточку или NULL, если такого товара в справочнике нет.';
