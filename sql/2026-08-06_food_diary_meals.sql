-- Приёмы пищи в дневнике питания: food_diary.meal.
--
-- Зачем: до сих пор день был одним плоским списком продуктов. Смотришь на
-- «2100 ккал за день» и не видишь, где именно перебрал — на завтраке или на
-- ночном перекусе. Раскладка по приёмам — то, ради чего люди вообще ведут
-- дневник, и то, чего у нас не было.
--
-- Колонка nullable БЕЗ значения по умолчанию, и это принципиально:
--  • все существующие строки остаются с NULL. Проставлять им приём задним
--    числом нечем — угадывать по времени created_at значило бы выдумать за
--    человека, что он ел на обед, а что на ужин;
--  • NULL честно значит «приём не указан». В интерфейсе такие записи
--    собираются в отдельную секцию «Без категории»: они видны, их можно
--    редактировать и перенести в нужный приём руками, но никто не делает вид,
--    что знает, куда они относятся.
--
-- CHECK, а не enum: enum в Postgres расширяется только через ALTER TYPE, то
-- есть миграцией. Список приёмов — вещь, которую вполне могут захотеть
-- дополнить («второй завтрак»), и это должно стоить правки константы в коде
-- плюс одной строки здесь, а не пересоздания типа.
--
-- CHECK допускает NULL по правилам SQL (NULL не нарушает ограничение), так что
-- старые строки проходят проверку без исключений в условии.
alter table public.food_diary
  add column if not exists meal text
  check (meal in ('breakfast','lunch','dinner','snack'));

comment on column public.food_diary.meal is
  'Приём пищи: breakfast/lunch/dinner/snack. NULL — запись сделана до появления приёмов либо приём не указан (см. sql/2026-08-06_food_diary_meals.sql)';

-- Индекс НЕ добавляем намеренно. Дневник всегда читается целиком за дату или
-- за месяц по (user_id, date) — существующих индексов для этого достаточно, а
-- группировка по приёмам делается уже на клиенте, в памяти, по десятку строк.
-- Отдельный индекс по meal только замедлял бы вставку, ничего не ускоряя.

-- Гранты и RLS не трогаем: колонка добавляется в существующую таблицу, права
-- на неё наследуются от таблицы, а политики food_diary («Users manage own …»)
-- уже ограничивают доступ по user_id. Клиент пишет meal тем же supabase-js под
-- своей ролью, что и остальные поля записи, — отдельной серверной ручки для
-- этого не нужно.
