-- СЛУЖЕБНЫЙ ПОТОК ЧЕЛЛЕНДЖА: живой, покупаемый, видимый только тренеру.
-- Дополняет sql/2026-08-24_challenge_seasons.sql, применять после него.
--
-- ЗАЧЕМ. Владелец обязан пройти весь путь покупки билета живыми деньгами —
-- ссылка Продамуса, подпись, вебхук, зачисление, номер участника, комната с
-- отсчётом, — не открывая продажу людям. Обходной путь («тестовый режим»,
-- ручная строка в challenge_entries) проверял бы обходной путь; сломаться же
-- может именно то, что мы обошли.
--
-- ЭТО ТОТ ЖЕ ПРИЁМ, ЧТО У ТАРИФА «ТЕСТ 50» (src/plans.js, признак staff:true), и
-- смысл у него ровно тот же: товар живой и покупаемый, просто не для клиентов.
-- Отличие только в том, ГДЕ живёт признак. У тарифов список зашит в код, и
-- скрытие там — поле объекта. Потоки живут в базе, значит и «служебность» —
-- это состояние строки, а не константа приложения: заводить рядом отдельную
-- колонку is_staff значило бы завести второй способ сказать про поток то же
-- самое, что уже говорит status, и однажды они разойдутся.
--
-- ПОЧЕМУ НЕ 'draft'. Черновик не виден НИКОМУ и не продаётся: в нём обкатывают
-- цену и условия. Служебный поток — противоположность: он должен продаваться
-- по-настоящему, иначе он ничего не проверяет. Это разные состояния, и «Поток
-- 1» так и остаётся черновиком — его этот файл не трогает.
--
-- ПОЧЕМУ 50 ₽. Столько же стоит служебный тариф ТЕСТ 50, и это НЕ совпадение,
-- а место, требующее внимания: вебхук опознаёт товар по сумме, и до правки
-- api/prodamus-webhook.js платёж за билет начислил бы тариф. После правки цена
-- билета берётся из price_rub ЭТОГО сезона, а не из константы, поэтому ярлык
-- '__challenge' + 50 ₽ — билет, а 50 ₽ без ярлыка — по-прежнему тариф.
-- Правка кода и эта строка в базе связаны: применять их надо вместе.

-- ── 1. Новое состояние потока ───────────────────────────────────────────────
-- Ограничение пересоздаём целиком: check-констрейнт нельзя дополнить, только
-- заменить. Имя берём то же, что дал Postgres при create table.
alter table public.challenge_seasons
  drop constraint if exists challenge_seasons_status_check;

alter table public.challenge_seasons
  add constraint challenge_seasons_status_check
  check (status in ('draft', 'staff', 'open', 'running', 'finished'));

comment on column public.challenge_seasons.status is
  'draft — не виден никому, набор не открыт; staff — служебный: живой и покупаемый, но виден только тренеру; open — идёт продажа; running — поток стартовал; finished — призы розданы.';

-- ── 2. Кто видит служебный поток ────────────────────────────────────────────
-- ПОЛИТИКУ МЕНЯЕМ ДО ВСТАВКИ СТРОКИ, и порядок здесь существенный. Прежнее
-- правило звучало «всё, кроме черновика», то есть новое состояние 'staff' оно
-- пустило бы к каждому вошедшему. Появись строка раньше политики — служебный
-- поток на несколько операторов оказался бы виден всем.
--
-- «Тренер ли это» спрашиваем у public.is_trainer() — той же функции, которой
-- пользуются остальные политики проекта (sql/2026-07-28_error_log.sql). Она
-- STABLE SECURITY DEFINER и берёт роль из profiles по auth.uid(), то есть из
-- подписанного токена: подставить чужую роль вызывающий не может. Разворачивать
-- её здесь в подзапрос по profiles было бы вторым ответом на тот же вопрос — и
-- ответом, который вдобавок зависел бы от того, какие политики стоят на самой
-- profiles.
--
-- Права на запись сюда не входят: challenge_seasons остаётся read-only для
-- клиента, вся запись идёт service_role-ключом.
drop policy if exists challenge_seasons_read on public.challenge_seasons;
create policy challenge_seasons_read on public.challenge_seasons
  for select to authenticated
  using (
    status in ('open', 'running', 'finished')
    or (status = 'staff' and public.is_trainer())
  );

-- ── 3. Сам поток ────────────────────────────────────────────────────────────
-- Условия — БОЕВЫЕ, и это главное требование к этой строке. Половина сборов в
-- призовой фонд, делёж 50/30/20 между тройкой, объявленная дата старта: путь
-- покупки обязан быть неотличим от настоящего, включая то, что человек видит
-- на экране правил и в комнате с отсчётом. Отличается ровно одно — цена, и
-- только потому, что деньги настоящие и платит их владелец.
--
-- where not exists — чтобы повторный прогон файла не завёл второй тест-поток.
insert into public.challenge_seasons (title, status, starts_on, price_rub, prize_pct, prize_split)
select 'Тест-поток', 'staff', date '2026-09-10', 50, 50, '{50,30,20}'::integer[]
 where not exists (
   select 1 from public.challenge_seasons where status = 'staff'
 );

-- Проверка глазами после применения: строка на месте, условия боевые.
select id, title, status, starts_on, price_rub, prize_pct, prize_split
  from public.challenge_seasons
 order by id;
