-- profiles.plan: разрешить служебный тариф test50.
--
-- ЖИВОЙ СБОЙ, РАДИ КОТОРОГО ЭТО НАПИСАНО. Тариф test50 (служебная проверка
-- живой оплаты за 50 ₽) добавили в код — в src/plans.js, в create-payment и в
-- вебхук. Оплата прошла, деньги списались, вебхук опознал сумму и нашёл
-- плательщика, а запись пакета упала:
--
--   new row for relation "profiles" violates check constraint "profiles_plan_check"
--
-- Потому что на profiles.plan висит CHECK со списком допустимых значений, и
-- test50 в нём не было. В журнал платежей строка легла со status='success',
-- в профиль — ничего. Худший вид поломки: деньги взяты, доступ не выдан.
--
-- ПОЧЕМУ ЭТО НЕ ЗАМЕТИЛИ РАНЬШЕ. Ограничение завели вручную при создании
-- таблицы, ещё до появления папки sql/, — в репозитории его не было. Тесты
-- тоже не спасли: в них PostgREST подменён заглушкой, а заглушка констрейнтов
-- не проверяет. Отсюда два вывода, оба закреплены:
--   1. ограничение теперь ЖИВЁТ В РЕПОЗИТОРИИ (этот файл) — следующий, кто
--      добавит тариф, увидит, что менять;
--   2. test-plan-test50.mjs читает ЭТОТ ФАЙЛ и сверяет список значений с
--      ключами из src/plans.js. Добавили тариф и забыли про базу — тест падает
--      до того, как кто-то заплатит.
--
-- Порядок операций: сначала снять, потом добавить. Postgres не умеет менять
-- CHECK на месте. Таблица маленькая, блокировка на доли секунды; новый список —
-- надмножество старого, поэтому существующие строки заведомо проходят и
-- проверка не найдёт нарушителей.

alter table public.profiles
  drop constraint if exists profiles_plan_check;

-- Список ДОЛЖЕН совпадать с ключами PLANS из src/plans.js. Сверяется тестом
-- (test-plan-test50.mjs, раздел «ограничение базы знает все тарифы»), который
-- разбирает массив прямо отсюда — поэтому формат строки менять осторожно.
alter table public.profiles
  add constraint profiles_plan_check
  check (plan = any (array['start'::text, 'base'::text, 'profit'::text, 'premium'::text, 'test50'::text]));

-- base остаётся в списке, хотя снят с продажи: у ранее купивших в profiles.plan
-- до сих пор лежит 'base', и запрет этого значения сломал бы им любое
-- обновление профиля (см. комментарий к hidden в src/plans.js).
