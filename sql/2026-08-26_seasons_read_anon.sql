-- ГОСТЬ ДОЛЖЕН ВИДЕТЬ ДАТУ И ЦЕНУ ПОТОКА — иначе это не продающая страница.
--
-- Что было. У `anon` не было GRANT SELECT на challenge_seasons, и гость получал
-- 401 ещё до всякой политики. Экран честно откатывался на запасные значения:
-- цена бралась из константы в коде, а дата — ниоткуда, и человек читал
-- «ПОТОК 1 · ДАТА БУДЕТ ОБЪЯВЛЕНА». Пока на страницу заходили только через
-- карточку изнутри приложения (то есть уже войдя), этого никто не видел. С
-- прямым адресом из поста это стало ПЕРВЫМ, что видит оплаченный трафик.
--
-- ЧТО ОТКРЫВАЕТСЯ. Ровно то, что и так напечатано на самой странице: название
-- потока, дата старта, цена билета, доля призового фонда. Ничего сверх.
--
-- ОДНОГО ГРАНТА МАЛО: существующая политика challenge_seasons_read объявлена
-- `TO authenticated`, то есть для гостя не срабатывает вовсе и он получает
-- пустой ответ вместо отказа. Поэтому заводится ОТДЕЛЬНАЯ политика для anon —
-- своя, а не расширение прежней: у них разные условия, и смешивать их значит
-- каждый раз перечитывать, кому что достаётся.
--
-- ЧЕГО ГОСТЮ НЕ ДОСТАНЕТСЯ. В его политике нет ветки со служебным потоком
-- вовсе: `is_trainer()` для анонима бессмысленна, и вместо неё честное
-- перечисление трёх публичных статусов. Тест-поток за 50 ₽ (status='staff') и
-- черновики (draft) не видны гостю ни при каких условиях.
--
-- Участники, их номера и результаты живут в challenge_entries — другая таблица,
-- другие права, и эта правка её не касается вовсе.

grant select on public.challenge_seasons to anon;

drop policy if exists challenge_seasons_read_anon on public.challenge_seasons;
create policy challenge_seasons_read_anon on public.challenge_seasons
  for select to anon
  using (status in ('open', 'running', 'finished'));
