-- ЖУРНАЛ ДОЛЖЕН ПРИНИМАТЬ ГОСТЯ — ИНАЧЕ ВОРОНКИ НЕ БУДЕТ.
--
-- Лендинг челленджа читают ДО регистрации: пост опубликован, трафик идёт, и
-- девять из десяти человек на нём — люди без аккаунта. А motion_log.user_id
-- стоял NOT NULL, то есть ровно тех, ради кого воронка и заводится, записать
-- было некуда.
--
-- Отсюда правка: user_id становится необязательным. Строка без него — это
-- посетитель, которого мы не знаем и знать не обязаны; вместо личности у неё
-- анонимный номер визита в payload (он живёт в localStorage браузера и ни с
-- чем не связан).
--
-- ЧТО ЭТО ДЕЛАЕТ С ДОСТУПОМ. Ничего не ослабляет:
--   • motion_log_insert_own и motion_log_select_own сравнивают auth.uid() с
--     user_id — NULL не равен ничему, поэтому анонимные строки для обычного
--     человека невидимы и вставить их из браузера под своей сессией нельзя;
--   • пишет их только сервер служебным ключом, через ветку, которая принимает
--     ТОЛЬКО события `challenge.*` и лимитирована по адресу;
--   • тренер, как и раньше, видит журнал целиком (motion_log_select_trainer).
--
-- УДАЛЕНИЕ АККАУНТА не затрагивается: оно ходит по user_id, а у этих строк его
-- нет — и удалять в них нечего, личности там не бывает по построению.

alter table public.motion_log alter column user_id drop not null;

-- Сводка воронки читает журнал ОКНОМ ПО ВРЕМЕНИ («за час», «за сутки»), а
-- индекса по одному только `at` не было: единственный существующий начинается
-- с user_id и такому запросу не годится. Пока строк тысяча, это незаметно;
-- к первому же посту с трафиком — нет.
create index if not exists motion_log_at_idx on public.motion_log (at desc);

analyze public.motion_log;
