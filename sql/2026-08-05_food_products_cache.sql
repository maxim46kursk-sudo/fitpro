-- Кэш продуктов по штрих-коду: public.food_products.
--
-- Зачем: дневник питания заполняется руками — человек ищет калорийность на
-- пачке и вбивает четыре числа. FatSecret, которым это закрывали раньше, в РФ
-- ограничили. Заменяем его сканером штрих-кода поверх Open Food Facts.
--
-- Почему это ОТДЕЛЬНАЯ таблица, а не запрос к OFF из браузера:
--  • OFF из РФ доступен через раз — ходим к нему только с сервера
--    (api/barcode.js), клиент видит один наш эндпоинт.
--  • Один и тот же десяток продуктов сканируют каждый день. Первый скан идёт в
--    OFF, все следующие — сюда, без внешней сети и её таймаутов.
--  • OFF просит не долбить его API. Кэш — наша часть этой договорённости.
--
-- ПЕРСОНАЛЬНЫХ ДАННЫХ ЗДЕСЬ НЕТ, и это принципиально. В таблице лежит только
-- справочник: «штрих-код → название, бренд, КБЖУ на 100 г». Кто и когда его
-- сканировал — не пишем и писать не надо, иначе получился бы теневой лог
-- питания пользователей рядом с настоящим (food_diary). Поэтому НЕТ user_id,
-- и таблица намеренно НЕ добавлена в USER_TABLES (api/_userTables.js):
-- выгружать и удалять по 152-ФЗ тут нечего. Сам факт съеденного по-прежнему
-- живёт только в food_diary — туда сканер и пишет обычным путём.

create table if not exists public.food_products (
  -- Штрих-код как первичный ключ: он и есть естественный идентификатор
  -- продукта, отдельный id только развёл бы дубли одного кода.
  --
  -- text, а не число: у EAN-8/EAN-13 значащий ведущий ноль (0460068200012 и
  -- 460068200012 — разные товары), а числовой тип его молча съест.
  --
  -- Констрейнт повторяет проверку в api/barcode.js. Дублируется намеренно:
  -- проверка в коде бережёт поход в базу, проверка в базе — единственная,
  -- которую нельзя обойти, если завтра писать сюда станет кто-то ещё.
  barcode    text primary key check (barcode ~ '^[0-9]{8,14}$'),
  name       text not null,
  brand      text,
  -- Всё КБЖУ — НА 100 Г продукта, ровно как печатают на упаковке и как отдаёт
  -- OFF (*_100g). Пересчёт на вес порции делает клиент (src/nutrition.js),
  -- в кэше лежит только исходная, независимая от порции величина.
  --
  -- nullable по-настоящему: в OFF полно карточек, где заполнено название и
  -- калорийность, а белки/жиры не проставлены. NULL здесь значит «неизвестно»,
  -- и это честнее нуля, который в дневнике сложился бы с остальным как факт.
  kcal100    numeric,
  p100       numeric,
  c100       numeric,
  f100       numeric,
  -- Откуда взята карточка. Сейчас единственный источник — 'off' (Open Food
  -- Facts); колонка заведена сразу, чтобы добавление второго справочника (или
  -- ручной правки нашего каталога) не требовало миграции с переписью строк.
  source     text default 'off',
  created_at timestamptz default now()
);

comment on table public.food_products is
  'Справочник продуктов по штрих-коду (кэш Open Food Facts). Персональных данных не содержит, пишется только через service role из api/barcode.js';

alter table public.food_products enable row level security;

-- ПОЛИТИК ДЛЯ КЛИЕНТОВ НЕТ — и это не забывчивость.
--
-- RLS без единой политики означает «запрещено всем, кроме service_role»
-- (service_role обходит RLS по определению). Клиент к таблице не ходит вовсе:
-- он спрашивает /api/barcode, а тот уже читает и пишет сюда серверным ключом.
--
-- Почему не дать клиенту хотя бы SELECT: тогда пришлось бы отдать анонимной
-- роли право читать таблицу целиком, а смысла в этом ноль — прямой поиск по
-- коду всё равно идёт через эндпоинт, который умеет сходить в OFF, если в
-- кэше пусто. Меньше поверхности — меньше о чём думать.
--
-- Гранты выдаём явно, как в sql/2026-07-28_error_log.sql, не наследуя старое
-- «GRANT ALL ON ALL TABLES»: revoke снимает права, доставшиеся anon и
-- authenticated по умолчанию, дальше таблицей владеет только service_role.
-- Без этого revoke таблица была бы закрыта одной лишь RLS — а лишний рубеж
-- тут стоит одной строки.
revoke all on table public.food_products from anon, authenticated;
grant all on table public.food_products to service_role;
