import { defineConfig } from 'vitest/config'

/**
 * ТЕСТЫ РАЗДЕЛА MOTION — отдельный набор, отдельной командой (`npm run test:motion`).
 *
 * Почему не в общий `npm test`. Своя цепочка тестов FitPro — это четырнадцать
 * node-скриптов, запускаемых через `&&`; у Motion — vitest с jsdom. Смешивать их
 * в одну команду значит склеить два разных инструмента ради одной строки в
 * package.json, а заодно сделать так, что падение любого теста Motion скрывает
 * результат проверок оплаты и доступа. Наборы независимы и запускаются
 * независимо.
 *
 * Отдельный файл конфигурации, а не секция в vite.config.js: тот собирает
 * приложение и умеет localApiChatPlugin, читающий ключ Anthropic из окружения.
 * Тестам он не нужен вовсе, а тянуть его — значит требовать ключ там, где не
 * ходят в сеть.
 */
export default defineConfig({
  /**
   * JSX — АВТОМАТИЧЕСКИМ RUNTIME. Без этого сборка тестов идёт классическим и
   * падает на «React is not defined»: в исходниках Motion нет ни одного
   * `import React`, и с автоматическим runtime он не нужен.
   *
   * Задаётся здесь напрямую, а НЕ через @vitejs/plugin-react, и причина
   * неочевидная: vitest 2 приносит с собой собственный Vite 5, а плагин в
   * проекте — версии 6, сделанной под Vite 8. В тестовом конвейере он молча не
   * срабатывает: подключён, ошибок нет, JSX не преобразуется. Одна строка ниже
   * делает ровно то, что от плагина требовалось тестам, и не зависит от того,
   * какой Vite окажется внутри.
   */
  esbuild: { jsx: 'automatic' },
  test: {
    /**
     * ЖУРНАЛ В ТЕСТАХ ВКЛЮЧЁН, а в самой сборке FitPro — нет.
     *
     * Тесты logShipper проверяют его собственное правило: «есть приёмник —
     * отправка идёт». Правило верное и проверять его надо; выключен журнал в
     * FitPro по другой причине — приёмника тут пока нет вовсе (см. detectEnabled).
     * Подменять здесь ожидания теста значило бы переписать проверку под
     * временное состояние хозяина.
     */
    env: { VITE_MOTION_LOG: '1' },
    // Раздел живёт целиком в своей папке — за её пределы набор не выходит
    include: ['src/motion/**/*.test.{js,jsx}'],
    exclude: [
      '**/node_modules/**',
      /**
       * ЧЕТЫРЕ ТЕСТА ОСТАЮТСЯ ЖИТЬ В РЕПОЗИТОРИИ MOTION.
       *
       * Они разбирают настоящие записи движений: тянут `tools/punch-replay.mjs`
       * и папку `recordings/` (около пяти мегабайт). Ни того, ни другого в FitPro
       * нет, и тащить их сюда незачем — это инструмент калибровки порогов, а не
       * часть приложения. Там, у себя, они и продолжают гонять записи.
       *
       * Список точечный, а не маской `*.replay.*`: `strength.test.js` записи
       * тоже читает, но по имени этого не видно, и маска молча пропустила бы его
       * в набор.
       */
      'src/motion/game/punch.replay.test.js',
      'src/motion/game/segments.replay.test.js',
      'src/motion/game/strength.test.js',
      'src/motion/game/vertical.replay.test.js',
    ],
  },
})
