// test-exercise-suggest.mjs — подсказки названий упражнений в режиме тренера.
//
// Что было сломано и почему этот набор именно такой.
//
//   • НОВОЕ НАЗВАНИЕ ТЕРЯЛОСЬ. Введённое словами («+ Добавить «X»») уезжало в
//     workout_sets.exercise обычным текстом и в подсказках не появлялось больше
//     никогда: список брался только из каталога. При этом в «Прогрессе по
//     упражнениям» оно было — тот строится из истории тренировок. Тренер видел
//     упражнение в одном месте приложения и не находил в другом.
//
//   • ИСТОРИЯ ЦЕПЛЯЛАСЬ ПОБУКВЕННО. Прошлые подходы ищутся точным равенством
//     строки, поэтому «жим лежа» не подхватывал историю «Жим лёжа». Подсказка
//     обязана подставлять КАНОНИЧЕСКОЕ написание — иначе тренер молча заводит
//     дубль и теряет всю прошлую динамику.
//
// Проверяется чистый модуль src/exerciseSuggest.js: ни Supabase, ни React тут
// не нужны, а вся суть правки — именно в нём.
//
// Запуск: node test-exercise-suggest.mjs

import { readFileSync } from 'node:fs'
import {
  filterSuggestions, findByName, mergeSuggestions, normalizeName,
} from './src/exerciseSuggest.js'

let pass = 0, fail = 0
function report(label, ok, detail) {
  if (ok) { pass++; console.log(`✓ PASS  ${label}`) }
  else { fail++; console.log(`✗ FAIL  ${label}${detail ? '  — ' + detail : ''}`) }
}
const eq = (label, actual, expected) => {
  const ok = JSON.stringify(actual) === JSON.stringify(expected)
  report(label, ok, ok ? '' : `получено ${JSON.stringify(actual)}, ждали ${JSON.stringify(expected)}`)
}

const КАТАЛОГ = [
  { n: 'Жим лёжа', label: 'Жим лёжа', m: 'Грудь', eq: 'штанга' },
  { n: 'Тяга верхнего блока', label: 'Тяга верхнего блока', m: 'Спина', eq: 'блок' },
  { n: 'Приседания', label: 'Приседания', m: 'Ноги', eq: 'штанга' },
]

// ══════════════════════════════════════════════════════════════════════════
console.log('\n── Новое название сразу в списке ──────────────────────────────────')
{
  // Главный случай: тренер завёл упражнение словами, оно легло в историю —
  // и обязано быть в подсказках при следующем открытии пикера.
  const list = mergeSuggestions(КАТАЛОГ, ['Ягодичный мостик'])
  const найдено = list.find(e => e.n === 'Ягодичный мостик')
  report('название из истории попало в список', !!найдено)
  report('и помечено как своё, а не каталожное', найдено?.fromHistory === true)
  eq('каталог при этом на месте', list.filter(e => !e.fromHistory).length, 3)
}
{
  // Через поиск — то есть так, как его увидит тренер.
  const list = mergeSuggestions(КАТАЛОГ, ['Ягодичный мостик'])
  eq('ищется наравне с каталожными', filterSuggestions(list, 'мостик').map(e => e.n), ['Ягодичный мостик'])
}
{
  // Пустая история ничего не ломает — обычный день с чистым каталогом.
  eq('без истории список = каталог', mergeSuggestions(КАТАЛОГ, []).length, 3)
  eq('история из мусора игнорируется', mergeSuggestions(КАТАЛОГ, [null, '', '   ']).length, 3)
}

// ══════════════════════════════════════════════════════════════════════════
console.log('\n── Без дублей, каноническое написание побеждает ───────────────────')
{
  // ГЛАВНЫЙ ТЕСТ. В истории лежит кривое написание того же упражнения. Двух
  // строк на одно упражнение быть не должно, а победить обязано каталожное:
  // выбор «не той» строки стоил бы тренеру потерянной истории.
  const list = mergeSuggestions(КАТАЛОГ, ['жим лежа', 'ЖИМ  ЛЁЖА'])
  const жимы = list.filter(e => normalizeName(e.n) === 'жим лежа')
  eq('одно упражнение — одна строка', жимы.length, 1)
  eq('написание каталожное', жимы[0]?.n, 'Жим лёжа')
  report('и это не запись из истории', жимы[0]?.fromHistory === false)
}
{
  // Повторы внутри самой истории (а их там сотни — по строке на подход).
  const list = mergeSuggestions([], ['Гиперэкстензия', 'Гиперэкстензия', 'гиперэкстензия'])
  eq('повторы истории схлопнуты', list.length, 1)
}
{
  // Названия из истории — по алфавиту: в базе у них порядок появления подходов,
  // тренеру нужен предсказуемый список.
  eq('история отсортирована', mergeSuggestions([], ['Ягодичный мостик', 'Берпи', 'Планка']).map(e => e.n),
    ['Берпи', 'Планка', 'Ягодичный мостик'])
}

// ══════════════════════════════════════════════════════════════════════════
console.log('\n── Поиск: по вхождению, без регистра, ё=е ─────────────────────────')
const СПИСОК = mergeSuggestions(КАТАЛОГ, ['Разведение гантелей лёжа'])
{
  // ВХОЖДЕНИЕ, А НЕ НАЧАЛО СТРОКИ. Упражнения называют с середины: «блок»
  // ищут в «Тяга верхнего блока», и поиск с начала не нашёл бы ничего.
  eq('находит по середине названия', filterSuggestions(СПИСОК, 'блок').map(e => e.n), ['Тяга верхнего блока'])
  eq('находит по концу названия', filterSuggestions(СПИСОК, 'верхнего блока').map(e => e.n), ['Тяга верхнего блока'])
}
{
  eq('регистр не важен', filterSuggestions(СПИСОК, 'ПРИСЕД').map(e => e.n), ['Приседания'])
  eq('регистр не важен и наоборот', filterSuggestions(СПИСОК, 'тяга').map(e => e.n), ['Тяга верхнего блока'])
}
{
  // ё=е В ОБЕ СТОРОНЫ. Оба написания встречаются примерно поровну, и без
  // замены половина поиска не находит ничего.
  eq('запрос через «е» находит название через «ё»',
    filterSuggestions(СПИСОК, 'жим лежа').map(e => e.n), ['Жим лёжа'])
  eq('запрос через «ё» находит то же самое',
    filterSuggestions(СПИСОК, 'жим лёжа').map(e => e.n), ['Жим лёжа'])
  eq('ё=е работает и для названий из истории',
    filterSuggestions(СПИСОК, 'гантелей лежа').map(e => e.n), ['Разведение гантелей лёжа'])
}
{
  eq('лишние пробелы не мешают', filterSuggestions(СПИСОК, '  жим   лёжа  ').map(e => e.n), ['Жим лёжа'])
  eq('пустой запрос отдаёт всё', filterSuggestions(СПИСОК, '').length, СПИСОК.length)
  eq('ничего не найдено — пустой список', filterSuggestions(СПИСОК, 'зюзюка').length, 0)
}

// ══════════════════════════════════════════════════════════════════════════
console.log('\n── Подстановка канонического названия ─────────────────────────────')
{
  // Ради этого всё и делалось: подсказка отдаёт ту строку, которой упражнение
  // записано в базе, и loadPrev находит историю точным равенством.
  const e = filterSuggestions(СПИСОК, 'жим лежа')[0]
  eq('выбор подсказки даёт каноническое название', e?.n, 'Жим лёжа')
}
{
  // Кнопка «+ Добавить «…»» не должна предлагать дубль под другим написанием.
  report('«жим лежа» опознаётся как уже существующее', findByName(СПИСОК, 'жим лежа')?.n === 'Жим лёжа')
  report('«ЖИМ ЛЁЖА» — тоже', findByName(СПИСОК, 'ЖИМ ЛЁЖА')?.n === 'Жим лёжа')
  report('а действительно новое — не опознаётся', findByName(СПИСОК, 'Прогулка фермера') === null)
  report('пустая строка ничего не находит', findByName(СПИСОК, '   ') === null)
}

// ══════════════════════════════════════════════════════════════════════════
console.log('\n── Экран берёт список именно отсюда ───────────────────────────────')
{
  // Проверка по исходнику: модуль можно написать правильно и не подключить.
  // Поднимать React-экран с Supabase в node дороже, чем он тут стоит.
  const src = readFileSync('src/TrainerSession.jsx', 'utf8')
  report('пикер получает готовые подсказки, а не каталог',
    /<ExercisePicker\s+suggestions=\{suggestions\}/.test(src))
  report('список собирается из каталога и истории',
    /mergeSuggestions\(catalogExercises,\s*historyNames\)/.test(src))
  report('названия из истории клиента действительно читаются',
    /from\('workout_sets'\)[\s\S]{0,120}select\('exercise'\)/.test(src))
  report('отбор идёт через общий фильтр', /filterSuggestions\(suggestions,\s*q\)/.test(src))
  report('дубль под другим написанием не предлагается кнопкой',
    /findByName\(suggestions,\s*custom\)/.test(src))
}

console.log('\n' + '─'.repeat(68))
console.log(`Итог: ${pass} пройдено, ${fail} провалено`)
process.exitCode = fail ? 1 : 0
