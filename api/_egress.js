/**
 * ВЫХОД НАРУЖУ — один адресный переключатель на все внешние вызовы.
 *
 * Зачем. С нашего сервера в России api.anthropic.com отвечает 403 «Request not
 * allowed» — блокировка по стране. На Vercel он открывается напрямую. Значит
 * один и тот же код должен ходить наружу по-разному в зависимости от того, где
 * он запущен, — и решать это должно ОДНО место, а не семь точек вызова.
 *
 * Как. Есть EGRESS_URL и EGRESS_KEY — адреса переписываются на мост
 * (tools/egress-worker), к запросу добавляется заголовок с ключом. Нет их —
 * возвращается ровно то, что пришло, без единого изменения.
 *
 * ⚠ ГЛАВНОЕ СВОЙСТВО, РАДИ КОТОРОГО ЭТОТ ФАЙЛ УСТРОЕН ИМЕННО ТАК: на Vercel
 * переменных нет, и поведение обязано остаться байт в байт прежним — тот же
 * адрес, те же заголовки, ни одного лишнего. Бой во время переезда не должен
 * заметить вообще ничего. Поэтому переписывание — не «нормальный путь с
 * выключателем», а исключение, которое включается явно и только там, где без
 * него нельзя.
 *
 * Файл с подчёркиванием — не serverless-функция (соглашение Vercel; на своём
 * сервере его повторяет server.mjs).
 */

/**
 * Что на что меняем. Ключ — начало настоящего адреса, значение — путь на мосту.
 *
 * ЗДЕСЬ ТОЛЬКО ANTHROPIC, И ЭТО ВАЖНО. Проверкой с сервера установлено:
 * api.anthropic.com отвечает 403 «Request not allowed» — блокировка по стране,
 * без моста никак. А api.telegram.org с того же сервера доступен НАПРЯМУЮ:
 * getMe обоих ботов отдаёт 200.
 *
 * Раньше здесь был и Telegram — по ошибке измерения, а не по делу. Токен для
 * проверок доставали из .env командой, снимавшей кавычки через `tr -d` с
 * шестнадцатеричным экранированием, которого tr не понимает: вместо одного
 * апострофа он вырезал из значения обратный слэш, «x», «2» и «7». Telegram
 * получал испорченный токен и честно отвечал 401 — это и приняли за блокировку.
 * Мораль на будущее: секреты из .env читать питоном или sed, но не tr.
 *
 * Возвращать его сюда не надо. Мост — лишняя точка отказа: ляжет он, и вместе
 * с ИИ-ассистентом молча отвалятся тревоги, напоминания, вход через Telegram и
 * выгрузка данных, то есть всё, что и без моста работало бы прекрасно. Мост
 * несёт ровно то, что без него не поедет.
 *
 * Сам мост (tools/egress-worker) маршрут /tg/ по-прежнему умеет и проверен —
 * он останется запасным входом, если Telegram однажды всё-таки закроют.
 */
const МАРШРУТЫ = [
  { откуда: 'https://api.anthropic.com/', куда: '/ai/' },
]

/** Заголовок с пропуском. Имя то же, что сверяет воркер. */
export const RELAY_HEADER = 'X-Relay-Key'

/**
 * Адрес и ключ моста из окружения.
 *
 * Читаются при каждом вызове, а не один раз на уровне модуля: на своём сервере
 * процесс живёт неделями, и правка .env с перезапуском не должна упираться в
 * значение, застывшее при первом импорте.
 */
function мост() {
  const url = (process.env.EGRESS_URL || '').trim().replace(/\/+$/, '')
  const key = (process.env.EGRESS_KEY || '').trim()
  // Половина настройки — то же самое, что её отсутствие: адрес без ключа даст
  // молчаливый 404 от моста, и разбираться в этом пришлось бы по симптомам.
  if (!url || !key) return null
  return { url, key }
}

/**
 * Переписывает адрес, если мост настроен.
 *
 * Возвращает адрес как есть, когда моста нет ИЛИ когда хост не из списка:
 * помощник — не универсальный прокси. Сейчас в списке один адрес, и Telegram
 * в него не входит намеренно (см. МАРШРУТЫ).
 */
export function egressUrl(адрес) {
  const m = мост()
  if (!m) return адрес
  const s = String(адрес)
  for (const { откуда, куда } of МАРШРУТЫ) {
    if (s.startsWith(откуда)) return m.url + куда + s.slice(откуда.length)
  }
  return адрес
}

/**
 * Добавляет к заголовкам пропуск, если мост настроен.
 *
 * Без моста возвращает ТОТ ЖЕ объект, а не копию: на Vercel вызов обязан
 * остаться в точности прежним, включая порядок ключей.
 */
export function egressHeaders(заголовки = {}) {
  const m = мост()
  if (!m) return заголовки
  return { ...заголовки, [RELAY_HEADER]: m.key }
}

/**
 * Обёртка над fetch: один вызов вместо пары egressUrl + egressHeaders.
 *
 * Ею пользуются все семь точек, которые раньше звали fetch напрямую. Пять из
 * них ходят в Telegram и после сужения маршрутов идут напрямую при любых
 * настройках — вызов остаётся здесь потому, что решение «куда именно» должно
 * жить в одном месте, а не расползаться по ручкам заново, если Telegram
 * когда-нибудь тоже закроют.
 */
export function egressFetch(адрес, опции = {}) {
  const m = мост()
  if (!m) return fetch(адрес, опции)
  const переписан = egressUrl(адрес)
  // Хост не из списка — мост не при чём, идём напрямую и ключ никому не
  // показываем.
  if (переписан === адрес) return fetch(адрес, опции)
  return fetch(переписан, { ...опции, headers: egressHeaders(опции.headers) })
}
