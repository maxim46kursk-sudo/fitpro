// Простой ограничитель частоты запросов В ПАМЯТИ ИНСТАНСА функции.
//
// Зачем именно так: Redis/Valkey в инфраструктуре нет, а заводить его ради
// антифлуда дороже, чем польза. Это ПЕРВАЯ ЛИНИЯ обороны — сбить примитивный
// флуд с одного адреса, а не точный учёт. Настоящие лимиты, которые нельзя
// потерять (дневной лимит ИИ, попытки входа), живут в Postgres.
//
// Чего этот лимитер НЕ умеет — знать перед тем, как на него полагаться:
//  • Счётчик не общий между инстансами. Vercel держит несколько параллельных
//    экземпляров функции, у каждого своя Map — фактический потолок для одного
//    IP кратен числу живых инстансов.
//  • Холодный старт обнуляет счётчики: инстанс поднялся — окно началось заново.
//  • Окно фиксированное (fixed window), а не скользящее. На стыке двух окон
//    можно уложить до 2×limit запросов подряд. Для антифлуда это допустимо.
//  • Ключ — IP. За NAT/корпоративным прокси несколько человек делят лимит,
//    а IP подделывается сменой сети. Поэтому лимиты держим щедрыми.
//
// Имя файла с подчёркиванием — Vercel не делает из таких файлов эндпоинты
// (лимит 12 функций на Hobby у нас уже выбран целиком).

// Ключ `${name}:${ip}` → { count, resetAt }. Живёт на уровне модуля, то есть
// столько же, сколько тёплый инстанс функции.
const hits = new Map()

// Потолок размера Map — защита от роста памяти на потоке уникальных IP.
// При переполнении чистим целиком: LRU здесь избыточен, а разовый сброс
// счётчиков ничем не грозит (в худшем случае флудер получит новое окно).
const MAX_KEYS = 10000

// IP клиента. За прокси Vercel настоящий адрес приходит заголовком; x-real-ip
// проставляет сам Vercel, x-forwarded-for может быть цепочкой "клиент, прокси1,
// прокси2" — берём ПЕРВЫЙ адрес, это исходный клиент.
export function clientIp(req) {
  const real = req.headers?.['x-real-ip']
  if (real) return String(real).trim()
  const fwd = req.headers?.['x-forwarded-for']
  if (fwd) {
    const first = String(fwd).split(',')[0].trim()
    if (first) return first
  }
  return req.socket?.remoteAddress || 'unknown'
}

// Проверяет и учитывает запрос. Возвращает true — можно работать дальше,
// false — ответ 429 уже отправлен, вызывающий обязан сразу выйти из handler:
//   if (!rateLimit(req, res, { name: 'chat', limit: 12 })) return
export function rateLimit(req, res, { name, limit, windowMs = 60000 }) {
  const key = `${name}:${clientIp(req)}`
  const now = Date.now()
  const entry = hits.get(key)

  // Нет записи или окно истекло — начинаем новое окно.
  if (!entry || entry.resetAt <= now) {
    if (hits.size >= MAX_KEYS) hits.clear()
    hits.set(key, { count: 1, resetAt: now + windowMs })
    return true
  }

  entry.count++
  if (entry.count > limit) {
    // Retry-After — целые секунды до конца окна, минимум 1: ноль клиент понял
    // бы как «можно прямо сейчас».
    const retryAfter = Math.max(1, Math.ceil((entry.resetAt - now) / 1000))
    res.setHeader('Retry-After', String(retryAfter))
    res.status(429).json({ error: 'Слишком много запросов, попробуй чуть позже' })
    return false
  }

  return true
}
