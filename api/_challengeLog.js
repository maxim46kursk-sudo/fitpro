// СТУПЕНИ ВОРОНКИ, КОТОРЫЕ ВИДИТ ТОЛЬКО СЕРВЕР.
//
// Четыре первые ступени пишет браузер (src/motion/challengeFunnel.js), а две
// последние он увидеть не может: ссылку на кассу выписывает create-payment, а
// об оплате узнаёт вебхук — в этот момент человека на странице может уже не
// быть вовсе. Поэтому их пишет сервер, и пишет ТУДА ЖЕ, в motion_log: воронка
// в двух местах — это не воронка, а два обрывка.
//
// ФОРМА СТРОКИ повторяет клиентскую до знака: `<время> [тег] {json}`. Разбор в
// сводке один на всех, и расходись эти формы, он читал бы половину.
//
// НИЧЕГО НЕ ЖДЁМ И НИЧЕМ НЕ РИСКУЕМ. Запись в журнал не должна ни задержать
// выдачу ссылки, ни тем более сорвать зачисление оплаченного билета: любая
// ошибка глотается, а вызывающий её даже не проверяет.
//
// Имя файла с подчёркиванием — Vercel не делает из таких файлов эндпоинты.

/**
 * Записать ступень воронки от имени сервера.
 *
 * @param {object} db      клиент Supabase со служебным ключом
 * @param {string} шаг     'pay-start' | 'paid'
 * @param {object} что     поля события; userId уходит и в колонку, и в строку
 * @param {string} [что.userId] кто это был — здесь он уже известен
 * @param {string} [что.vid]    номер посетителя, если клиент его прислал
 */
export async function ступеньСервера(db, шаг, { userId = null, vid = null, ...поля } = {}) {
  try {
    const строка = `${new Date().toISOString()} [challenge.${шаг}] ${JSON.stringify({
      vid: vid || undefined,
      uid: userId || undefined,
      ...поля,
    })}`
    await db.from('motion_log').insert({
      user_id: userId,
      // Своя «сессия» на каждую серверную запись: колонка обязательная, а
      // настоящей сессии браузера у сервера нет и быть не может. Префикс
      // отличает эти строки от браузерных с одного взгляда.
      session: `srv-${шаг}-${(vid || userId || 'нет').slice(0, 24)}`,
      payload: { lines: [строка] },
    })
  } catch {
    // Журнал не записался — деньги при этом целы, билет выдан. Молчим.
  }
}
